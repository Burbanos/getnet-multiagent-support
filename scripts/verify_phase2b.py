"""Phase 2B acceptance checks (docs/SPEC.md, Phase 2B: LLM robustness). Cross-platform.

Usage (from the repository root):  python scripts/verify_phase2b.py
Requires the dev environment. Never calls a real LLM.
Do NOT edit this file to make checks pass: the reviewer runs an independent copy.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

ROOT = Path.cwd()
RESULTS: list[tuple[str, bool]] = []
DEFAULT_MODEL = "gemini-3.8-flash"

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=900)


def static_checks() -> None:
    check("S1.default_model_config", f'"{DEFAULT_MODEL}"' in read("src/config.py"),
          f"src/config.py default GEMINI_MODEL is not {DEFAULT_MODEL}")
    check("S1.default_model_env_example", f"GEMINI_MODEL={DEFAULT_MODEL}" in read(".env.example"),
          f".env.example does not set GEMINI_MODEL={DEFAULT_MODEL}")
    check("S1.default_model_compose", DEFAULT_MODEL in read("docker-compose.yml") or "GEMINI_MODEL" not in read("docker-compose.yml"),
          f"docker-compose.yml still defaults GEMINI_MODEL to another model")
    stale = [f for f in ["src/config.py", ".env.example", "docker-compose.yml", "README.md"] if "gemini-2.5-flash" in read(f)]
    check("S1.no_retired_model", not stale, f"gemini-2.5-flash still referenced in {stale}")


def runtime_checks() -> None:
    tmp = tempfile.mkdtemp(prefix="verify_p2b_")
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["GEMINI_API_KEY"] = ""
    sys.path.insert(0, str(ROOT))
    try:
        from fastapi.testclient import TestClient
        from langchain_core.exceptions import ModelNotFoundError, ModelRateLimitError
        from langchain_core.messages import AIMessage, ToolMessage

        import src.core.graph as graph_mod
        import src.core.llm as llm_mod
        from src.config import settings
        from src.core.graph import OrchestrationGraph
        from src.main import app
        from tests.fakes import ScriptedChatModel
    except Exception as exc:  # noqa: BLE001
        check("R0.imports", False, f"{type(exc).__name__}: {exc}")
        return

    missing = [a for a in ("LLM_TIMEOUT_S", "LLM_MAX_RETRIES", "MAX_SUPERVISOR_STEPS") if not hasattr(settings, a)]
    check("R1.settings", not missing, f"missing settings: {missing}")
    check("R1.config_error_class", hasattr(llm_mod, "LLMConfigurationError"), "src.core.llm.LLMConfigurationError missing")
    if missing:
        return

    try:
        settings.GEMINI_API_KEY = "dummy-key-for-construction-only"
        m = llm_mod.get_chat_model()
        ok = getattr(m, "timeout", None) == float(settings.LLM_TIMEOUT_S) and getattr(m, "max_retries", None) == int(settings.LLM_MAX_RETRIES)
        check("R2.timeout_and_retries", ok, f"timeout={getattr(m, 'timeout', None)}, max_retries={getattr(m, 'max_retries', None)}")
        check("R2.model_name", DEFAULT_MODEL in str(getattr(m, "model", "")), f"model={getattr(m, 'model', None)}")
    except Exception as exc:  # noqa: BLE001
        check("R2.runtime", False, f"{type(exc).__name__}: {exc}")
    finally:
        settings.GEMINI_API_KEY = ""

    fake = ScriptedChatModel(responses=[AIMessage(content=[{"type": "text", "text": "Olá, lojista."}])])
    st = OrchestrationGraph(chat_model=fake).run_sync(user_id="cliente1988", message="oi", session_id="v2b-text")
    check("R3.content_blocks_to_text", st.agent_response == "Olá, lojista.", f"agent_response={st.agent_response!r}")

    class Raising(ScriptedChatModel):
        exc: Exception | None = None

        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            raise self.exc

    client = TestClient(app)
    try:
        graph_mod._orchestrator_instance = OrchestrationGraph(chat_model=Raising(exc=ModelNotFoundError("model gone")))
        r = client.post("/chat", json={"message": "oi", "user_id": "cliente1988"})
        check("R4.config_error_503", r.status_code == 503 and "misconfigured" in r.text.lower(),
              f"status {r.status_code}: {r.text[:200]}")
        check("R6.trace_header_on_503", bool(r.headers.get("X-Trace-Id")), "X-Trace-Id header missing on 503")

        graph_mod._orchestrator_instance = OrchestrationGraph(chat_model=Raising(exc=ModelRateLimitError("429")))
        r = client.post("/chat", json={"message": "oi", "user_id": "cliente1988"})
        check("R4.transient_error_503", r.status_code == 503 and "unavailable" in r.text.lower()
              and "misconfigured" not in r.text.lower(), f"status {r.status_code}: {r.text[:200]}")

        class Exploding:
            def run_sync(self, *a, **k):
                raise RuntimeError("SECRET-INTERNAL-DETAIL-123")

        graph_mod._orchestrator_instance = Exploding()
        r = client.post("/chat", json={"message": "oi", "user_id": "cliente1988"})
        tid = r.headers.get("X-Trace-Id", "")
        check("R5.internal_error_no_leak", r.status_code == 500 and "SECRET-INTERNAL-DETAIL-123" not in r.text,
              f"status {r.status_code}: {r.text[:200]}")
        check("R5.internal_error_has_reference", bool(tid) and tid in r.text, "500 body does not include the X-Trace-Id")

        graph_mod._orchestrator_instance = OrchestrationGraph(chat_model=ScriptedChatModel(responses=[AIMessage(content="ok")]))
        r = client.post("/chat", json={"message": "oi", "user_id": "cliente1988"})
        meta_tid = r.json().get("metadata", {}).get("trace_id") if r.status_code == 200 else None
        check("R6.trace_header_matches_metadata", r.status_code == 200 and r.headers.get("X-Trace-Id") == meta_tid,
              f"status {r.status_code}, header={r.headers.get('X-Trace-Id')!r}, metadata={meta_tid!r}")
    except Exception as exc:  # noqa: BLE001
        check("R4.runtime", False, f"{type(exc).__name__}: {exc}")
    finally:
        graph_mod._orchestrator_instance = None

    try:
        old = settings.MAX_SUPERVISOR_STEPS
        settings.MAX_SUPERVISOR_STEPS = 3
        looping = ScriptedChatModel(responses=[
            AIMessage(content="", tool_calls=[{"name": "get_settlement_status", "args": {}, "id": f"loop-{i}"}])
            for i in range(20)])
        orch = OrchestrationGraph(chat_model=looping)
        st = orch.run_sync(user_id="cliente1988", message="loop forever", session_id="v2b-loop")
        tid = (st.ticket or {}).get("ticket_id", "")
        check("R7.step_limit_model_calls", len(looping.received) == 3, f"model called {len(looping.received)} times (limit 3)")
        check("R7.forced_escalation", bool(tid) and st.tools_used[-1:] == ["escalate_to_human"] and tid in (st.agent_response or ""),
              f"ticket={tid!r}, tools_used={st.tools_used}, response={st.agent_response!r}")
        msgs = orch.graph.get_state({"configurable": {"thread_id": "v2b-loop"}}).values.get("messages", [])
        call_ids = {c["id"] for m in msgs if isinstance(m, AIMessage) for c in (m.tool_calls or [])}
        answered = {m.tool_call_id for m in msgs if isinstance(m, ToolMessage)}
        check("R8.history_consistent", call_ids <= answered, f"tool calls without ToolMessage: {sorted(call_ids - answered)}")
    except Exception as exc:  # noqa: BLE001
        check("R7.runtime", False, f"{type(exc).__name__}: {exc}")
    finally:
        settings.MAX_SUPERVISOR_STEPS = old


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks() -> None:
    env0 = {k: v for k, v in os.environ.items() if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY")}
    env0["GEMINI_API_KEY"] = ""
    prev = run([sys.executable, "scripts/verify_phase2a.py"], env=env0)
    summary = [ln for ln in prev.stdout.splitlines() if ln.startswith("SUMMARY")]
    fails = [ln for ln in prev.stdout.splitlines() if ln.startswith("FAIL")]
    check("Q0.phase2a_still_passes", prev.returncode == 0, "; ".join(fails[:5]) or prev.stdout[-300:],
          info=summary[-1] if summary else "")
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    static_checks()
    runtime_checks()
    suite_checks()
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
