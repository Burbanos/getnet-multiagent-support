def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def block(text: str, start: str) -> str:
    i = text.find("````markdown\n" + start)
    if i < 0:
        return ""
    i += len("````markdown\n")
    j = text.find("\n````", i)
    return text[i:j].strip() if j > 0 else ""


def static_checks() -> None:
    compose, docker, ignore, ci = read("docker-compose.yml"), read("Dockerfile"), read(".dockerignore"), read(".github/workflows/ci.yml")
    mounts = [ln.strip() for ln in compose.splitlines() if ln.strip().startswith("- ") and ":/app/" in ln]
    check("D1.volume_on_state", mounts and all(m.endswith(":/app/state") for m in mounts) and "/app/data" not in compose,
          f"the named volume must be mounted on /app/state only (index and corpus come from the image): {mounts}")
    check("D1.db_paths_in_state", "CHECKPOINT_DB_PATH=${CHECKPOINT_DB_PATH:-state/checkpoints.db}" in compose
          and "TICKETS_DB_PATH=${TICKETS_DB_PATH:-state/tickets.db}" in compose, "compose must default both database paths to state/")
    check("D2.dockerfile", "USER appuser" in docker and "HEALTHCHECK" in docker and "777" not in docker and "/app/state" in docker,
          "Dockerfile: non-root user, healthcheck, /app/state owned by appuser, and no world-writable chmod 777")
    check("D2.dockerignore", all(p in ignore for p in ("data/*.db", "data/*.db-wal", "data/*.db-shm")),
          ".dockerignore must keep local SQLite databases (real conversations and tickets) out of the image")
    check("D3.ci_non_root", "id -u" in ci, "CI must assert the container does not run as root (id -u != 0)")
    readme, prompt = read("README.md"), read("docs/phase-prompts/8B.md")
    table = block(prompt, "## 9. Afirmações e evidências")
    check("R1.claims_table", bool(table) and table in readme and readme.count("## 9. Afirmações e evidências") == 1,
          "README must contain the claims table exactly as given in docs/phase-prompts/8B.md")
    dc = readme[readme.find("### Execução via Docker Compose"):readme.find("### Execução Local")]
    check("R2.readme_docker", "/app/state" in dc and "getnet_app_state" in dc,
          "README Docker Compose section must say the volume (getnet_app_state) holds only the databases in /app/state")
    paths = sorted(set(re.findall(r"`((?:src|tests|scripts|data|reports|\.github)/[A-Za-z0-9_./-]*|Dockerfile|docker-compose\.yml)`", table)))
    missing = [p for p in paths if not (ROOT / p).exists()]
    check("R3.evidence_exists", paths and not missing, f"evidence paths that do not exist: {missing}")
    results = readme[readme.find("### Resultados da avaliação"):readme.find("Limites e falhas conhecidas")]
    check("R4.results_kept", "62/69 (89,9%)" in results and "## 6. Matriz de Cobertura dos Cenários Oficiais" in readme,
          "the results section and the official matrix must stay")


