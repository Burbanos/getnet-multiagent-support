if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


SECRET_USER = "user-SECRET-77"
CARD, CPF = "4111 1111 1111 1111", "123.456.789-09"


def static_checks() -> None:
    srcs = {p.relative_to(ROOT).as_posix(): p.read_text(encoding="utf-8") for p in (ROOT / "src").rglob("*.py")}
    bad = []
    for path, text in srcs.items():
        for m in re.finditer(r"logger\.(?:debug|info|warning|error|exception|critical)\((.*?)\)\s*\n", text, flags=re.S):
            body = m.group(1)
            if any(w in body for w in ("user_id}", "user_id=", "message[:", ".user_id", "{user_id", "{message")):
                bad.append(f"{path}: {' '.join(body.split())[:90]}")
    check("L0.no_identifiers_in_log_calls", not bad, f"log calls still format the raw user id or message: {bad[:4]}")
    env_ex = read(".env.example")
    check("L0.salt_setting", "LOG_HASH_SALT=" in env_ex and "LOG_HASH_SALT" in read("src/config.py"),
          "LOG_HASH_SALT must be a setting and appear in .env.example")
    readme = read("README.md")
    check("L0.readme", all(w in readme for w in ("user_hash", "LOG_HASH_SALT", "node finished", "tool finished")),
          "README must document the log fields (trace_id, session_id, user_hash), LOG_HASH_SALT and the node/tool events")


def main_checks(tmp: str) -> None:
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["CHECKPOINT_DB_PATH"] = str(Path(tmp) / "checkpoints.db")
    os.environ["GEMINI_API_KEY"] = ""
    sys.path.insert(0, str(ROOT))
    try:
        from typing import Any

        from langchain_core.messages import AIMessage
        from langchain_core.outputs import ChatGeneration, ChatResult
        from pydantic import Field

        import src.core.tickets_db as tdb
        from src.config import JsonFormatter, settings
        from src.core import log_context as lc
        from src.core.graph import OrchestrationGraph
        from tests.fakes import ScriptedChatModel
    except Exception as exc:  # noqa: BLE001
        check("L1.imports", False, f"{type(exc).__name__}: {exc}")
        return
    need = [n for n in ("user_hash", "bind", "current") if not callable(getattr(lc, n, None))]
    check("L1.api", not need, f"src/core/log_context.py is missing {need}")
    if need:
        return
    h1 = lc.user_hash(SECRET_USER)
    old = settings.LOG_HASH_SALT
    settings.LOG_HASH_SALT = "pepper"
    h2 = lc.user_hash(SECRET_USER)
    settings.LOG_HASH_SALT = old
    check("L1.user_hash", h1 == lc.user_hash(SECRET_USER) and h1 != h2 and SECRET_USER not in h1 and h1 != lc.user_hash("other")
          and len(h1) >= 12, f"hash={h1!r}, salted={h2!r}")
    with lc.bind("trc-aaaaaaaaaaaa", "s-1", SECRET_USER):
        inside = lc.current()
    check("L1.bind_and_reset", inside.get("trace_id") == "trc-aaaaaaaaaaaa" and inside.get("session_id") == "s-1"
          and inside.get("user_hash") == h1 and SECRET_USER not in json.dumps(inside) and lc.current() == {},
          f"inside={inside}, after={lc.current()}")

    class StepFake(ScriptedChatModel):
        responses: list[Any] = Field(default_factory=list)

        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            self.received.append(list(messages))
            return ChatResult(generations=[ChatGeneration(message=self.responses.pop(0))])

    def call(name: str, args: dict, cid: str) -> AIMessage:
        return AIMessage(content="", tool_calls=[{"name": name, "args": args, "id": cid}])

    buf = io.StringIO()
    handler = logging.StreamHandler(buf)
    handler.setFormatter(JsonFormatter())
    root_app = logging.getLogger("multiagent")
    root_app.addHandler(handler)
    old_level = root_app.level
    root_app.setLevel(logging.INFO)
    try:
        tdb.reset_tickets_repository()
        fake = StepFake(responses=[call("ask_support_agent", {"request": "Check yesterday's settlement"}, "s1"),
                                   call("get_settlement_status", {}, "s2"), AIMessage(content="SPEC"),
                                   call("escalate_to_human", {"reason": "merchant asked for a human", "priority": "standard"}, "s3"),
                                   AIMessage(content="FINAL")])
        st = OrchestrationGraph(chat_model=fake).run_sync(user_id=SECRET_USER, message=f"Meu cartão {CARD} e CPF {CPF}: quando recebo?",
                                                          session_id="sess-7a", trace_id="trc-7a7a7a7a7a7a")
        logging.getLogger("multiagent.verify").info("after the request")
    except Exception as exc:  # noqa: BLE001
        check("L2.run", False, f"{type(exc).__name__}: {exc}")
        return
    finally:
        root_app.removeHandler(handler)
        root_app.setLevel(old_level)
        tdb.reset_tickets_repository()
    lines = [ln for ln in buf.getvalue().splitlines() if ln.strip()]
    recs = []
    for ln in lines:
        try:
            recs.append(json.loads(ln))
        except ValueError:
            recs.append({"_raw": ln})
    raw = buf.getvalue()
    leaked = [w for w in (SECRET_USER, "4111", "1111 1111", "123.456.789", "quando recebo") if w in raw]
    check("L2.no_pii_in_logs", not leaked and recs, f"logs contain {leaked}")
    during, after = recs[:-1], recs[-1:]
    wrong = [r.get("message", r.get("_raw", ""))[:60] for r in during
             if r.get("trace_id") != "trc-7a7a7a7a7a7a" or r.get("session_id") != "sess-7a" or r.get("user_hash") != h1]
    check("L3.context_on_every_record", during and not wrong and "user_id" not in json.dumps(during),
          f"{len(wrong)} of {len(during)} records lack trace_id/session_id/user_hash, e.g. {wrong[:3]}")
    check("L3.context_cleared", after and after[0].get("message") == "after the request" and "trace_id" not in after[0],
          f"record after run_sync: {after}")
    nodes = {r.get("node") for r in during if r.get("message") == "node finished" and isinstance(r.get("latency_ms"), (int, float))}
    check("L4.node_events", {"guardrail", "supervisor", "tools"} <= nodes, f"node events with latency_ms: {sorted(n for n in nodes if n)}")
    tools = {(r.get("tool"), r.get("status")) for r in during if r.get("message") == "tool finished"
             and isinstance(r.get("latency_ms"), (int, float))}
    names = {t for t, _ in tools}
    check("L5.tool_events", {"ask_support_agent", "get_settlement_status", "escalate_to_human"} <= names
          and all(s in ("ok", "error") for _, s in tools), f"tool events: {sorted(tools, key=str)}")
    check("L6.run_still_works", st.agent_response == "FINAL" and st.trace_id == "trc-7a7a7a7a7a7a" and st.escalation_ticket_id,
          f"response={st.agent_response!r}, ticket={st.escalation_ticket_id!r}")


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks(tmp: str) -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    tests = read("tests/test_logging.py")
    n_tests = len(re.findall(r"^def test_", tests, flags=re.M))
    check("Q0.logging_tests", n_tests >= 4, f"tests/test_logging.py has {n_tests} tests (need >= 4)")
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH",
                         "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1", CHECKPOINT_DB_PATH=str(Path(tmp) / "nested" / "checkpoints.db"))
    for script, allowed in PRIOR.items():
        env_s = {k: v for k, v in nested.items() if k != "CHECKPOINT_DB_PATH"} if script == "verify_phase4b.py" else nested
        r = run([sys.executable, f"scripts/{script}"], env=env_s)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    marks = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in ("data/tickets.db", "data/checkpoints.db")}
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "warning" not in last, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")
    after = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in marks}
    check("Q4.tests_do_not_touch_data_dbs", marks == after, f"the test suite wrote {[p for p in marks if marks[p] != after[p]]}")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p7a_")
    static_checks()
    main_checks(tmp)
    suite_checks(tmp)
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
