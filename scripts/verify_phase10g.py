def ref_tools_ok(case: dict, result: dict) -> Any:
    """Reference for the only check 10G changes; the other checks are the 6A reference, rerun by verify_phase6a.py."""
    if result.get("status") != "ok" or not result.get("turns"):
        return None
    t, e = result["turns"][-1], case["expect"]
    if not (e["tools_all"] or e["tools_none"]):
        return None
    used = t.get("tools_used", [])
    ok = all(x in used for x in e["tools_all"]) and not any(x in used for x in e["tools_none"])
    for tool, st in (e.get("api_status") or {}).items():
        ok = ok and any(a.get("tool") == tool and a.get("status") == st for a in (t.get("api_results") or []))
    return ok


def synth(case: dict, rng: random.Random) -> dict:
    tools = [x for x in LEAF if rng.random() < 0.3] + [x for x in case["expect"]["tools_all"] if rng.random() < 0.8]
    api = []
    for tool in API_TOOLS:
        for _ in range(rng.choice([0, 0, 1, 2])):
            api.append({"tool": tool, "status": rng.choice(API_STATUSES), "source_url": rng.choice([None, "https://u"])})
    for tool, st in (case["expect"].get("api_status") or {}).items():
        if rng.random() < 0.5:
            api.append({"tool": tool, "status": st, "source_url": "https://u"})
    turn = {"message": "m", "response": rng.choice(["Olá, você pode ver isso no app.", "You can check it in the app.", ""]),
            "agents_used": ["SupervisorAgent"] + [a for a in SPECIALISTS if rng.random() < 0.5], "tools_used": tools,
            "sources": [], "retrieved_docs": [], "web_results": [], "tool_results": [], "ticket_id": None,
            "ticket_priority": None, "is_safe": rng.random() < 0.9, "handoff": None, "llm_model": None, "tokens": None,
            "latency_ms": 1.0}
    if rng.random() < 0.85:
        turn["api_results"] = api
    return {"id": case["id"], "status": rng.choice(["ok"] * 9 + ["error"]), "error_type": None, "turns": [turn]}


