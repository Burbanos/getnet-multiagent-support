def norm(s: str) -> str:
    return " ".join((s or "").split()).lower()


def ref_facts_ok(case, result):
    if result.get("status") != "ok" or not result.get("turns") or not case["expect"]["facts_any"]:
        return None
    resp = norm(result["turns"][-1].get("response", ""))
    return all(any(norm(a) in resp for a in g) for g in case["expect"]["facts_any"])


def ref_judge_section(cases, results, judgments):
    by_r = {r["id"]: r for r in results}
    by_j = {j["id"]: j for j in judgments}
    rows = [(c, by_r[c["id"]], by_j.get(c["id"])) for c in cases if c["id"] in by_r and by_r[c["id"]].get("status") == "ok"]
    judged = [(c, r, j) for c, r, j in rows if j and j.get("status") == "ok"]
    n_err = sum(1 for _, _, j in rows if j and j.get("status") != "ok")
    mean = lambda xs: (sum(xs) / len(xs)) if xs else None  # noqa: E731
    ab = [(c["expect"]["abstain"], j["abstained"]) for c, _, j in judged if c["expect"]["abstain"] is not None]
    tp = sum(1 for e, p in ab if e and p)
    pred = sum(1 for _, p in ab if p)
    pos = sum(1 for e, _ in ab if e)
    dis = []
    for c, r, j in judged:
        f = ref_facts_ok(c, r)
        if (f is True and j["grounded"] <= 2) or (f is False and j["grounded"] >= 4 and j["answers_question"] >= 4):
            dis.append(c["id"])
    return {"n_judged": len(judged), "n_judge_errors": n_err,
            "grounded_mean": mean([j["grounded"] for _, _, j in judged]),
            "answers_mean": mean([j["answers_question"] for _, _, j in judged]),
            "abstention_precision": tp / pred if pred else None, "abstention_recall": tp / pos if pos else None,
            "abstention_errors": sorted(c["id"] for c, _, j in judged if c["expect"]["abstain"] is not None
                                        and j["abstained"] != c["expect"]["abstain"]),
            "disagreements": sorted(dis), "judge_models": sorted({j.get("judge_model") for _, _, j in judged if j.get("judge_model")})}


def close(a, b) -> bool:
    if a is None or b is None:
        return a is None and b is None
    return math.isclose(float(a), float(b), abs_tol=1e-9)


