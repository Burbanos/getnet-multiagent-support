"""Phase 15C2 acceptance checks (docs/SPEC.md, §3.6, paragraph "15C2": the 15C chunking test compares only the original
pages with the committed index, so it stays valid after the author rebuilds the index), plus every check of Phase 15C.

Usage (from the repository root):  python scripts/verify_phase15c2.py
Requires the dev environment and git history (the 15C verifier is read from `a1cfac9`). Never calls a real LLM or the network.
The index rebuild is simulated with a fake embedder inside a temporary git worktree; the repository's data/ is never touched.

Superseded checks of the 15C verifier (it is re-run here, unchanged, from `a1cfac9`): A1.reviewer_files,
A2.retired_process_files, A3.scope and S1.status, re-checked below against `a1cfac9`. Every other 15C check (and, through it,
every non-superseded 15B check) must still pass.
Do NOT edit this file to make checks pass: the reviewer runs its own copy.
"""
from __future__ import annotations

import ast
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path.cwd()
RESULTS: list[tuple[str, bool]] = []
BASE = "a1cfac9"  # end of 15C
PROMPT = "docs/phase-prompts/15C2.md"
PINNED = {
    "docs/SPEC.md": "6b05345ed28c7a84be87e2d107736278a29b38149ee569eb57713ac58818d0e9",
    PROMPT: "b24add1a94ac70a6c5fd721d7c85e3bf5bdac165614f5f04b6b2d80f24f354bd",
}
REVIEWER = set(PINNED) | {"scripts/verify_phase15c2.py"}
RETIRED = {"docs/phase-prompts/15C.md", "scripts/verify_phase15c.py"}
TEST = "tests/test_chunking_index_15c.py"
FUNC = "test_original_33_pages_match_committed_chunks_as_url_text_pairs"
ALLOWED = {TEST, "docs/STATUS.md"}
SUPERSEDED_15C = {"A1.reviewer_files", "A2.retired_process_files", "A3.scope", "S1.status"}
MIN_TESTS = 596  # passed at 15C; 15C2 adds none
REBUILD = """
import hashlib
import src.core.llm as llm
from src.config import settings

class FakeEmbedder:
    def __init__(self, dim):
        self.dim = dim
    def _v(self, t):
        d = hashlib.sha256(t.encode("utf-8")).digest()
        return [d[i % 32] / 255.0 - 0.5 for i in range(self.dim)]
    def embed_documents(self, texts):
        return [self._v(t) for t in texts]
    def embed_query(self, t):
        return self._v(t)

llm.get_embedder = lambda *a, **k: FakeEmbedder(int(settings.EMBEDDING_DIM))
settings.INDEX_DIR = "data/index"
import src.rag.index as ix
ix.main()
"""

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, bool(ok)))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def note(cid: str, text: str) -> None:
    print(f"INFO {cid} :: {text}", flush=True)


def read(rel: str, root: Path = ROOT) -> str:
    p = root / rel
    return p.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n") if p.exists() else ""


def sha(rel: str) -> str:
    return hashlib.sha256(read(rel).encode("utf-8")).hexdigest()


def run(cmd: list[str], cwd: Path = ROOT, env: dict | None = None, timeout: int = 3600) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True, encoding="utf-8", errors="replace",
                          timeout=timeout)


def base_file(rel: str) -> str:
    r = run(["git", "show", f"{BASE}:{rel}"])
    return r.stdout.replace("\r\n", "\n") if r.returncode == 0 else ""


def clean_env() -> dict:
    env = {k: v for k, v in os.environ.items() if k not in ("GEMINI_API_KEY", "GOOGLE_API_KEY")}
    env.update(APP_ENV="testing", GEMINI_API_KEY="", PYTHONDONTWRITEBYTECODE="1")
    return env


# ------------------------------------------------------------------------------------------------------------- static
def static_checks() -> None:
    mism = {rel: sha(rel)[:12] for rel, digest in PINNED.items() if sha(rel) != digest}
    check("A1.reviewer_files", not mism and (ROOT / "scripts/verify_phase15c2.py").exists(),
          f"reviewer files differ from the reviewer's copy: {mism}")

    verifiers = sorted(p.name for p in (ROOT / "scripts").glob("verify_*.py"))
    prompts = sorted(p.name for p in (ROOT / "docs/phase-prompts").glob("*.md"))
    check("A2.retired_process_files", verifiers == ["verify_phase15c2.py"] and prompts == ["15C2.md"],
          f"only verify_phase15c2.py and 15C2.md may remain: {verifiers} {prompts}")

    diff = run(["git", "diff", "--name-only", "--no-renames", BASE])
    untracked = run(["git", "ls-files", "--others", "--exclude-standard"]).stdout.split()
    changed = set(diff.stdout.split()) | set(untracked)
    extra = sorted(p for p in changed if p not in REVIEWER and p not in RETIRED and p not in ALLOWED)
    check("A3.scope", diff.returncode == 0 and not extra, f"15C2 may change only {sorted(ALLOWED)}; also changed: {extra}")

    old, new = base_file(TEST), read(TEST)
    try:
        t_old, t_new = ast.parse(old, feature_version=(3, 11)), ast.parse(new, feature_version=(3, 11))
    except SyntaxError as exc:
        check("T1.only_the_named_test_changed", False, f"not valid Python 3.11: {exc}")
        return

    def nodes(tree):
        return {getattr(n, "name", f"#{i}:{type(n).__name__}"): ast.dump(n) for i, n in enumerate(tree.body)}

    n_old, n_new = nodes(t_old), nodes(t_new)
    others_same = {k: v for k, v in n_old.items() if k != FUNC} == {k: v for k, v in n_new.items() if k != FUNC}
    fn = next((n for n in t_new.body if getattr(n, "name", "") == FUNC), None)
    fn_src = ast.get_source_segment(new, fn) if fn is not None else ""
    check("T1.only_the_named_test_changed", others_same and fn is not None and n_old.get(FUNC) != n_new.get(FUNC)
          and "== 103" in fn_src and "rebuilt_pairs == committed_pairs" in fn_src,
          f"other top-level nodes unchanged={others_same}; {FUNC} present={fn is not None}, changed="
          f"{n_old.get(FUNC) != n_new.get(FUNC)}, keeps '== 103' and the pair equality={'== 103' in fn_src}")

    st = read("docs/STATUS.md")
    check("S1.status", 0 < len(st.split("\n")) <= 60 and "15C2" in st and "Perguntas" in st and "verify_phase15c2" in st,
          f"docs/STATUS.md must be rewritten for 15C2 in at most 60 lines (has {len(st.splitlines())}) with the verifier "
          f"output and 'Perguntas / divergências'")


# ----------------------------------------------------------------------------------------------------- rebuild simulation
def rebuild_simulation(tmp: str) -> None:
    env = clean_env()
    here = run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", TEST], env=env)
    check("T2.test_file_passes_with_committed_index", here.returncode == 0, here.stdout[-600:] + here.stderr[-300:],
          info=(here.stdout.strip().splitlines() or [""])[-1])

    wt = Path(tmp) / "wt"
    add = run(["git", "worktree", "add", "--detach", str(wt), "HEAD"])
    if add.returncode != 0:
        check("T3.test_file_passes_after_index_rebuild", False, f"git worktree add failed: {add.stderr[-300:]}")
        return
    try:
        changed = set(run(["git", "diff", "--name-only", "--no-renames", "HEAD"]).stdout.split())
        changed |= set(run(["git", "ls-files", "--others", "--exclude-standard"]).stdout.split())
        for rel in changed:
            src, dst = ROOT / rel, wt / rel
            if src.exists():
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, dst)
            elif dst.exists():
                dst.unlink()
        reb = run([sys.executable, "-c", REBUILD], cwd=wt, env=env)
        n_chunks = len([x for x in read("data/index/chunks.jsonl", wt).splitlines() if x.strip()])
        old_test = wt / "tests" / "test_zz_old_15c_chunking.py"
        old_test.write_text(base_file(TEST), encoding="utf-8")
        old = run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", str(old_test.relative_to(wt)),
                   "-k", FUNC], cwd=wt, env=env)
        old_test.unlink()
        new = run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", TEST], cwd=wt, env=env)
        check("T3.test_file_passes_after_index_rebuild",
              reb.returncode == 0 and n_chunks > 103 and old.returncode != 0 and new.returncode == 0,
              f"rebuild rc={reb.returncode} chunks={n_chunks} {reb.stderr[-300:]!r}; the 15C version must fail on the "
              f"rebuilt index (rc={old.returncode}); the 15C2 version must pass (rc={new.returncode}): "
              f"{new.stdout[-500:]}",
              info=f"rebuilt index with {n_chunks} chunks; 15C version fails, 15C2 version passes")
    finally:
        run(["git", "worktree", "remove", "--force", str(wt)])
        run(["git", "worktree", "prune"])


# --------------------------------------------------------------------------------------------------------- 15C checks
def rerun_15c(tmp: str) -> None:
    src = base_file("scripts/verify_phase15c.py")
    if not src:
        check("P15C.previous_verifier", False, f"scripts/verify_phase15c.py not found at {BASE}")
        return
    path = Path(tmp) / "verify_phase15c_from_a1cfac9.py"
    path.write_text(src, encoding="utf-8")
    r = run([sys.executable, str(path)], env={k: v for k, v in os.environ.items()
                                             if k not in ("GEMINI_API_KEY", "GOOGLE_API_KEY")}, timeout=5400)
    lines = r.stdout.splitlines()
    results = {}
    for ln in lines:
        m = re.match(r"^(PASS|FAIL) (\S+)", ln)
        if m:
            results[m.group(2)] = m.group(1) == "PASS"
    for ln in lines:
        if ln.startswith("INFO "):
            print(ln, flush=True)
    failed = sorted(c for c, ok in results.items() if not ok and c not in SUPERSEDED_15C)
    for c in sorted(SUPERSEDED_15C & set(results)):
        note(f"P15C.{c}", "superseded by the 15C2 check of the same name (the 15C copy "
             + ("passes" if results[c] else "fails") + ")")
    expected = {"K10.bearer_rechecks_api_key", "K11.refresh_rechecks_api_key_and_revokes_family",
                "X4.gold_snippets_in_index_chunks", "X5.original_pages_chunks_unchanged", "A4.index_and_corpus_unchanged", "P15B.previous_verifier",
                "Q2c.test_count", "R4.probes_left_tree_clean"}
    check("P15C.previous_verifier", not failed and expected <= set(results) and len(results) >= 21,
          f"15C checks failing (not superseded): {failed}; missing: {sorted(expected - set(results))}; "
          f"stderr: {r.stderr[-300:]}", info=f"{sum(results.values())}/{len(results)} pass")
    q2 = next((ln for ln in lines if " Q2c.test_count" in ln), "")
    m = re.search(r"(\d+) passed", q2)
    n = int(m.group(1)) if m else 0
    check("Q2.test_count", n >= MIN_TESTS, f"pytest passed {n} < {MIN_TESTS}: {q2[:200]}", info=f"{n} passed")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p15c2_")
    static_checks()
    status_before = run(["git", "status", "--porcelain"]).stdout
    worktrees_before = run(["git", "worktree", "list", "--porcelain"]).stdout
    try:
        rebuild_simulation(tmp)
    except Exception as exc:  # a crash in the probe is a failed check, never a crashed verifier
        check("T3.test_file_passes_after_index_rebuild", False, f"probe raised {type(exc).__name__}: {str(exc)[:300]}")
    check("R1.probes_left_tree_clean", status_before == run(["git", "status", "--porcelain"]).stdout
          and worktrees_before == run(["git", "worktree", "list", "--porcelain"]).stdout,
          "the simulation changed the working tree or left a worktree behind")
    rerun_15c(tmp)
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
