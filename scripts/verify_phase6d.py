if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def fake_state(docs, **kw):
    base = dict(agent_response="resposta", agents_used=["SupervisorAgent", "KnowledgeAgent"], tools_used=["search_knowledge_base"],
                sources=[d["url"] for d in docs], retrieved_docs=docs, tool_results=[{"agent": "KnowledgeAgent", "answer": "x"}],
                escalation_ticket_id=None, ticket=None, is_safe=True, handoff=None, llm_model="fake-model",
                tokens={"input_tokens": 3, "output_tokens": 2, "total_tokens": 5})
    base.update(kw)
    return SimpleNamespace(**base)


def main_checks(tmp: str) -> None:
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["CHECKPOINT_DB_PATH"] = str(Path(tmp) / "checkpoints.db")
    os.environ["GEMINI_API_KEY"] = ""
    sys.path.insert(0, str(ROOT))
    try:
        from src.eval import cases as ecases
        from src.eval import judge as ejudge
        from src.eval import runner as erunner
    except Exception as exc:  # noqa: BLE001
        check("R0.imports", False, f"{type(exc).__name__}: {exc}")
        return
    cases = {c["id"]: c for c in ecases.load_cases(ROOT / "data/eval/cases.jsonl")}
    chunks = [json.loads(ln) for ln in read("data/index/chunks.jsonl").splitlines() if ln.strip()]
    long = [c for c in chunks if len(c.get("text", "")) > 700]
    check("J0.index_has_long_chunks", len(long) >= 10, f"only {len(long)} chunks longer than 700 chars in data/index/chunks.jsonl")
    if not long:
        return

    # --- observe_turn keeps up to 2000 characters (supersedes 6B R1.observe_turn, which pinned 600)
    try:
        t = erunner.observe_turn(fake_state([{"url": "u", "chunk_id": "c", "score": 0.7, "text": "Z" * 5000, "title": "t"}]), "m", 1.0)
        d = t["retrieved_docs"][0]
        keys = {"message", "response", "agents_used", "tools_used", "sources", "retrieved_docs", "tool_results", "ticket_id",
                "ticket_priority", "is_safe", "handoff", "llm_model", "tokens", "latency_ms"}
        check("R1.observe_turn_2000", set(t) == keys and set(d) == {"url", "chunk_id", "score", "text"} and len(d["text"]) == 2000,
              f"keys={sorted(t)}, doc keys={sorted(d)}, text len={len(d.get('text', ''))}")
    except Exception as exc:  # noqa: BLE001
        check("R1.observe_turn_2000", False, f"{type(exc).__name__}: {exc}")

    # --- judge input rebuilds the full passage from the committed index by chunk_id
    try:
        check("J1.api", callable(getattr(ejudge, "load_chunk_texts", None)), "src/eval/judge.py must define load_chunk_texts(path=None)")
        a, b = long[0], long[1]
        docs = [{"url": a.get("doc_url", "u"), "chunk_id": a["chunk_id"], "score": 0.8, "text": a["text"][:600]},
                {"url": b.get("doc_url", "u"), "chunk_id": b["chunk_id"], "score": 0.7, "text": b["text"][:600]},
                {"url": "https://example.org/x", "chunk_id": "not-in-index-0001", "score": 0.6, "text": "STORED-ONLY-TEXT"},
                {"url": "https://example.org/y", "chunk_id": None, "score": None, "text": "NO-CHUNK-ID-TEXT"}]
        res = {"id": "k01", "status": "ok", "error_type": None, "turns": [erunner.observe_turn(fake_state(docs), cases["k01"]["turns"][0], 1.0)]}
        payload = json.loads(ejudge.build_judge_input(cases["k01"], res))
        texts = [p.get("text") for p in payload.get("passages", [])]
        check("J2.full_passages", texts == [a["text"], b["text"], "STORED-ONLY-TEXT", "NO-CHUNK-ID-TEXT"]
              and set(payload.get("passages", [{}])[0]) == {"url", "text"},
              f"passage lengths={[len(x or '') for x in texts]} (want {len(a['text'])}, {len(b['text'])}, stored, stored)")
        m = ejudge.load_chunk_texts()
        alt = Path(tmp) / "alt_chunks.jsonl"
        alt.write_text(json.dumps({"chunk_id": "alt-1", "text": "ALT"}) + "\n", encoding="utf-8")
        check("J3.load_chunk_texts", isinstance(m, dict) and len(m) == len(chunks) and m.get(a["chunk_id"]) == a["text"]
              and ejudge.load_chunk_texts(alt) == {"alt-1": "ALT"}, f"{len(m) if isinstance(m, dict) else m} texts loaded")
        leaked = [w for w in ("k01", "expect", "category", "facts_any") if w in json.dumps(payload)]
        check("J4.still_blind", not leaked, f"judge input leaks {leaked}")
    except Exception as exc:  # noqa: BLE001
        check("J2.full_passages", False, f"{type(exc).__name__}: {exc}")


def static_checks() -> None:
    readme, status = read("README.md"), read("docs/STATUS.md")
    bad = [w for w in ("1.500", "1,500", "1500 req", "1.500 req") if w in readme]
    check("S1.readme_no_false_quota", not bad and "500" in readme, f"README still states a false Flash-Lite quota: {bad}")
    check("S2.readme_run_example", "python -m src.eval run --run-id full-1" not in readme,
          "README must not suggest `run --run-id full-1` (it would skip every case): use a new run id")
    check("S3.readme_judge_limits", "data/index/chunks.jsonl" in readme and "search_web" in readme,
          "README must say the judge reads full passages from data/index/chunks.jsonl and that search_web results are not "
          "visible to the judge")
    tail = status[status.rfind("Fase 6D"):] if "Fase 6D" in status else ""
    check("S4.status_next_phase", tail and "6E" in tail and "maximizar pass rate" not in tail,
          "STATUS (section Fase 6D) must name 6E as the next step and must not plan prompt tuning to maximise the pass rate")
    check("D1.flawed_judge_file_removed", not (ROOT / "reports/eval_runs/full-1.judge.jsonl").exists(),
          "reports/eval_runs/full-1.judge.jsonl (judged with truncated passages) must be deleted, not committed")


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks(tmp: str) -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    tests = read("tests/test_eval_runner_judge.py")
    n_tests = len(re.findall(r"^def test_", tests, flags=re.M))
    check("Q0.runner_judge_tests", n_tests >= 15, f"tests/test_eval_runner_judge.py has {n_tests} tests (need >= 15: 13 from 6C + 2)")
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH",
                         "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1", CHECKPOINT_DB_PATH=str(Path(tmp) / "nested" / "checkpoints.db"))
    for script, allowed in PRIOR.items():
        env_s = {k: v for k, v in nested.items() if k != "CHECKPOINT_DB_PATH"} if script == "verify_phase4b.py" else nested
        r = run([sys.executable, f"scripts/{script}"], env=env_s)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    marks = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in ("data/tickets.db", "data/checkpoints.db")}
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "warning" not in last, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")
    after = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in marks}
    check("Q4.tests_do_not_touch_data_dbs", marks == after, f"the test suite wrote {[p for p in marks if marks[p] != after[p]]}")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p6d_")
    static_checks()
    main_checks(tmp)
    suite_checks(tmp)
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
