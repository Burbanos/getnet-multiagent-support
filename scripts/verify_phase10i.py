def md_blocks(rel: str, kinds: str = "markdown") -> list[str]:
    return re.findall(r"````(?:" + kinds + r")\n(.*?)\n````", read(rel).replace("\r\n", "\n"), re.S)


def br(x: float, nd: int) -> str:
    return f"{x:.{nd}f}".replace(".", ",")


def close(a: Any, b: Any, tol: float = 1e-9) -> bool:
    if isinstance(a, dict) and isinstance(b, dict):
        return set(a) == set(b) and all(close(a[k], b[k], tol) for k in a)
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(close(x, y, tol) for x, y in zip(a, b))
    if isinstance(a, float) or isinstance(b, float):
        return isinstance(a, (int, float)) and isinstance(b, (int, float)) and abs(a - b) <= tol * max(1.0, abs(a), abs(b))
    return a == b


