    for rel in files:
        p = ROOT / rel
        if not rel or not p.is_file() or p.suffix.lower() in (".npy", ".npz", ".png", ".jpg", ".pdf", ".xlsx", ".db", ".pyc"):
            continue
        try:
            text = p.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        words = re.findall(r"[a-z]+", _norm_name(text))
        hit = any(hashlib.sha256(w.encode()).hexdigest() in NAME_SHA for w in words) or any(
            hashlib.sha256(f"{a} {b}".encode()).hexdigest() in NAME_SHA for a, b in zip(words, words[1:]))
        if hit:
            leaks.append(rel)
    check("D3.annotator_name_absent", not leaks, f"the annotator's name appears in {leaks[:5]}")


