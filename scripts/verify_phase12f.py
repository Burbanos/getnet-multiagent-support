def prompt_blocks(kind: str) -> list[tuple[str, str]]:
    prompt = read(PROMPT)
    blocks = re.findall(r"^~~~~" + kind + r"\n(.*?)\n~~~~$", prompt, re.S | re.M)
    return [(blocks[i], blocks[i + 1]) for i in range(0, len(blocks) - 1, 2)]


def apply(text: str, edits: list[tuple[str, str]]) -> str | None:
    for old, new in edits:
        if text.count(old) != 1:
            return None
        text = text.replace(old, new, 1)
    return text


def first_diff(a: str, b: str) -> str:
    la, lb = a.splitlines(), b.splitlines()
    for i, (x, y) in enumerate(zip(la, lb)):
        if x != y:
            return f"line {i + 1}: {x[:120]!r} (expected {y[:120]!r})"
    return f"length {len(la)} lines (expected {len(lb)})"


def pct(x: float) -> str:
    return f"{x * 100:.1f}".replace(".", ",")


def kappa(x: float) -> str:
    return f"{x:.2f}".replace(".", ",").replace("-", "\u2212")


