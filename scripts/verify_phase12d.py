def r_fold(t: str) -> str:
    t = "".join(c for c in unicodedata.normalize("NFKD", t) if not unicodedata.combining(c)).lower()
    return "".join(c if c.isalnum() else " " for c in t)


def r_urls(text: str) -> list[str]:
    out: list[str] = []
    for tok in text.split():
        for pre in ("https://", "http://"):
            i = tok.find(pre)
            if i >= 0:
                for part in tok[i:].split("]("):
                    if not part.startswith(("https://", "http://")):
                        continue
                    while part and part[-1] in ")]}>.,;:!?\"'*`":
                        part = part[:-1]
                    if len(part) > 8 and part not in out:
                        out.append(part)
                break
    return out


def r_tickets(text: str) -> list[str]:
    out, i = [], text.find("GET-TKT-")
    while i >= 0:
        j = i + 8
        while j < len(text) and (text[j].isalnum() or text[j] == "-"):
            j += 1
        t = text[i:j].rstrip("-")
        if t not in out:
            out.append(t)
        i = text.find("GET-TKT-", j)
    return out


def r_check(answer: str, evidence: str, ids: set[str], ticket_turn: bool) -> dict[str, list[str]]:
    ev = unquote(evidence).lower()
    out: dict[str, list[str]] = {}
    bad = [u for u in r_urls(answer) if unquote(u).lower().rstrip("/") not in ev]
    if bad:
        out["urls"] = bad
    bt = [t for t in r_tickets(answer) if t not in ids and t not in evidence]
    if bt:
        out["ticket_ids"] = bt
    if ticket_turn:
        pad = " " + " ".join(r_fold(answer).split()) + " "
        pr = [p for p in PROMISES if f" {p} " in pad]
        if pr:
            out["time_promise"] = pr
    return out


