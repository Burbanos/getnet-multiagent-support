"""Phase 2E acceptance checks (docs/SPEC.md, Phase 2E: real token usage, tools without invented values).

Usage (from the repository root):  python scripts/verify_phase2e.py
Requires the dev environment. Never calls a real LLM.
Do NOT edit this file to make checks pass: the reviewer runs an independent copy.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

ROOT = Path.cwd()
RESULTS: list[tuple[str, bool]] = []
SUPERSEDED = {
    "verify_phase2a.py": {"R2.single_tool_flow", "R3.user_id_injected", "R3.bound_tools", "R4.two_tools_sequence"},
    "verify_phase2b.py": {"S1.default_model_config", "S1.default_model_env_example", "R2.model_name"},
    "verify_phase2c.py": set(),
    "verify_phase2d.py": set(),
}
NESTED_Q0 = {"Q0.phase2a_still_passes", "Q0.phase2b_only_superseded_fail", "Q0.verify_phase2a_regressions",
             "Q0.verify_phase2b_regressions", "Q0.verify_phase2c_regressions"}

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def static_checks() -> None:
    src = "\n".join(p.read_text(encoding="utf-8") for p in (ROOT / "src").rglob("*.py"))
    check("S1.no_generic_decline_text", "Erro Genérico" not in src, "invented generic decline description still in src/")
    terminal = read("src/tools/terminal_tools.py")
    bad = [w for w in ("Get Smart", "Claro", "Vivo", "instável na localidade") if w in terminal]
    check("S2.terminal_no_hardcoded_specifics", not bad, f"terminal_tools.py still hardcodes {bad}")
    check("S3.fixed_sampling_warning_filtered", "fixed sampling defaults" in read("src/core/llm.py"),
          "src/core/llm.py does not filter the benign 'fixed sampling defaults' UserWarning")


def runtime_checks() -> None:
    tmp = tempfile.mkdtemp(prefix="verify_p2e_")
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["GEMINI_API_KEY"] = ""
    sys.path.insert(0, str(ROOT))
    try:
        from fastapi.testclient import TestClient
        from langchain_core.messages import AIMessage

        import src.core.graph as graph_mod
        from src.core.graph import OrchestrationGraph
        from src.core.mock_db import get_mock_db
        from src.main import app
        from src.tools.agent_tools import TOOLS_BY_NAME
        from tests.fakes import ScriptedChatModel
    except Exception as exc:  # noqa: BLE001
        check("R0.imports", False, f"{type(exc).__name__}: {exc}")
        return

    def usage(i: int, o: int) -> dict:
        return {"input_tokens": i, "output_tokens": o, "total_tokens": i + o}

    def ai(content: str = "", calls: list | None = None, u: dict | None = None) -> AIMessage:
        kw = {"usage_metadata": u} if u else {}
        return AIMessage(content=content, tool_calls=calls or [], **kw)

    def call(name: str, args: dict, cid: str) -> list:
        return [{"name": name, "args": args, "id": cid}]

    try:
        fake = ScriptedChatModel(responses=[
            ai(calls=call("ask_support_agent", {"request": "settlement"}, "t1"), u=usage(100, 10)),
            ai(calls=call("get_settlement_status", {}, "t2"), u=usage(50, 5)),
            ai("S", u=usage(60, 20)),
            ai("FINAL", u=usage(130, 40)),
        ])
        orch = OrchestrationGraph(chat_model=fake)
        st = orch.run_sync(user_id="cliente1988", message="x", session_id="v2e-1")
        check("R1.tokens_total", st.tokens == {"input_tokens": 340, "output_tokens": 75, "total_tokens": 415},
              f"tokens={st.tokens}")
        tba = getattr(st, "tokens_by_agent", None)
        check("R1.tokens_by_agent", tba == {"SupervisorAgent": usage(230, 50), "SupportAgent": usage(110, 25)},
              f"tokens_by_agent={tba}")
        check("R1.cost_still_null", st.estimated_cost_usd is None, f"estimated_cost_usd={st.estimated_cost_usd}")

        fake.responses.extend([ai("TURN2", u=usage(500, 7))])
        st2 = orch.run_sync(user_id="cliente1988", message="y", session_id="v2e-1")
        check("R2.tokens_per_turn", st2.tokens == {"input_tokens": 500, "output_tokens": 7, "total_tokens": 507},
              f"second turn tokens={st2.tokens} (must count only this turn)")

        st3 = OrchestrationGraph(chat_model=ScriptedChatModel(responses=[ai("no usage")])).run_sync(
            user_id="cliente1988", message="z", session_id="v2e-3")
        check("R3.tokens_null_when_unmeasured", st3.tokens is None and getattr(st3, "tokens_by_agent", "missing") is None,
              f"tokens={st3.tokens}, tokens_by_agent={getattr(st3, 'tokens_by_agent', 'missing')}")

        graph_mod._orchestrator_instance = OrchestrationGraph(chat_model=ScriptedChatModel(responses=[ai("ok", u=usage(9, 1))]))
        r = TestClient(app).post("/chat", json={"message": "oi", "user_id": "cliente1988"})
        meta = r.json().get("metadata", {}) if r.status_code == 200 else {}
        check("R4.api_tokens", meta.get("tokens") == usage(9, 1) and meta.get("tokens_by_agent") == {"SupervisorAgent": usage(9, 1)},
              f"status {r.status_code}, tokens={meta.get('tokens')}, tokens_by_agent={meta.get('tokens_by_agent')}")
    except Exception as exc:  # noqa: BLE001
        check("R1.runtime", False, f"{type(exc).__name__}: {exc}")
    finally:
        graph_mod._orchestrator_instance = None

    db = get_mock_db()
    original_get_user = db.get_user
    cfg = {"configurable": {"user_id": "probe-user"}}

    def with_user(user: dict):
        db.get_user = lambda uid: user if uid == "probe-user" else original_get_user(uid)

    try:
        base = original_get_user("cliente1988") or {}
        no_declines = dict(base, recent_transactions=[t for t in base.get("recent_transactions", []) if t.get("status") != "DECLINED"])
        with_user(no_declines)
        out = json.loads(TOOLS_BY_NAME["diagnose_declined_transaction"].invoke({}, config=cfg))
        check("R5.no_decline_no_invented_code", out.get("latest_declined_transaction") is None and out.get("queried_code") is None
              and out.get("code_details") is None, f"output={str(out)[:300]}")
        out = json.loads(TOOLS_BY_NAME["diagnose_declined_transaction"].invoke({"error_code": "999"}, config=cfg))
        check("R6.unknown_code_not_invented", out.get("queried_code") == "999" and out.get("code_details") is None
              and out.get("code_known") is False, f"output={str(out)[:300]}")
        out = json.loads(TOOLS_BY_NAME["diagnose_declined_transaction"].invoke({"error_code": "51"}, config=cfg))
        check("R6.known_code_kept", out.get("code_known") is True and (out.get("code_details") or {}).get("error_code") == "51",
              f"output={str(out)[:300]}")

        term = dict((base.get("terminals") or [{}])[0])
        healthy = dict(term, model="Get Mini", sim_operator="TIM", signal_level="forte", wifi_connected=True,
                       sim_status="ativo", status="online", connection_type="Wi-Fi")
        with_user(dict(base, terminals=[healthy]))
        text = TOOLS_BY_NAME["diagnose_terminal"].invoke({}, config=cfg)
        bad = [w for w in ("Get Smart", "Claro", "Vivo", "instável", "fraco") if w in text]
        check("R7.terminal_reflects_data_healthy", not bad and "Get Mini" in text, f"invented content {bad}; output={text[:300]}")

        weak = dict(term, model="Get Mini", sim_operator="TIM", signal_level="fraco", wifi_connected=False, sim_status="ativo")
        with_user(dict(base, terminals=[weak]))
        out = json.loads(TOOLS_BY_NAME["diagnose_terminal"].invoke({}, config=cfg))
        steps = " ".join(out.get("troubleshooting_steps") or [])
        check("R8.terminal_reflects_data_weak", "Wi-Fi" in steps,
              f"weak-signal steps should recommend Wi-Fi; output={str(out)[:300]}")
        check("R8.terminal_no_other_operator", not any(w in json.dumps(out, ensure_ascii=False) for w in ("Claro", "Vivo", "Get Smart")),
              f"output={str(out)[:300]}")
    except Exception as exc:  # noqa: BLE001
        check("R5.runtime", False, f"{type(exc).__name__}: {exc}")
    finally:
        db.get_user = original_get_user


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks() -> None:
    env0 = {k: v for k, v in os.environ.items() if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY")}
    env0["GEMINI_API_KEY"] = ""
    for script, allowed in SUPERSEDED.items():
        r = run([sys.executable, f"scripts/{script}"], env=env0)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed - NESTED_Q0 - {"Q1.ruff_clean", "Q2.pytest_offline_no_key", "Q3.tree_unchanged"})
        check(f"Q0.{script[:-3]}_regressions", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    static_checks()
    runtime_checks()
    suite_checks()
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
