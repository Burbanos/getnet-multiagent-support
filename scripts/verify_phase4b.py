if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def db_file_of(saver) -> str:
    conn = getattr(saver, "conn", None)
    if conn is None:
        return ""
    rows = conn.execute("PRAGMA database_list").fetchall()
    return next((r[2] for r in rows if r[1] == "main"), "")


def same_file(a: str, b: str) -> bool:
    try:
        return bool(a) and os.path.samefile(a, b)
    except OSError:
        return False


def static_checks() -> None:
    req = read("requirements.txt")
    check("S1.requirement_declared", "langgraph-checkpoint-sqlite" in req, "requirements.txt must declare langgraph-checkpoint-sqlite")
    lock = read("requirements.lock")
    pins = {p: bool(re.search(rf"^{p}==", lock, flags=re.M)) for p in ("langgraph-checkpoint-sqlite", "aiosqlite", "sqlite-vec")}
    check("S1.lock_regenerated_on_linux", all(pins.values()) and "Python 3.11" in lock and re.search(r"^uvloop==", lock, flags=re.M)
          and re.search(r"^langgraph-checkpoint==4\.3\.1$", lock, flags=re.M),
          f"pins={pins}; the lock must be regenerated in Codespaces with Python 3.11 (uvloop pinned), "
          "keeping langgraph-checkpoint==4.3.1")
    gi = read(".gitignore")
    check("S2.gitignore", "-wal" in gi and "-shm" in gi and ("*.db" in gi or "checkpoints.db" in gi),
          ".gitignore must cover the SQLite database and its WAL files (*.db-wal, *.db-shm)")
    env_ex, compose = read(".env.example"), read("docker-compose.yml")
    check("S3.config_documented", "CHECKPOINT_DB_PATH=data/checkpoints.db" in env_ex and "CHECKPOINT_DB_PATH" in compose,
          "CHECKPOINT_DB_PATH must be in .env.example (data/checkpoints.db) and docker-compose.yml")
    mod = read("src/core/checkpointer.py")
    check("S4.no_silent_fallback", bool(mod) and "/tmp" not in mod and "TEMP" not in mod and "gettempdir" not in mod
          and "MemorySaver" not in mod, "src/core/checkpointer.py must exist and never fall back to a temp dir or memory")
    main_src = read("src/main.py")
    check("S5.no_memorysaver_claims", "MemorySaver" not in main_src, "src/main.py (/ and /agents) still describes MemorySaver")
    readme = read("README.md")
    check("S6.readme", "CHECKPOINT_DB_PATH" in readme and "SqliteSaver" in readme and "API_KEYS" in readme
          and "será implementada na Fase 4B" not in readme and "ocorre na Fase 4B" not in readme,
          "README must document CHECKPOINT_DB_PATH/SqliteSaver persistence and drop the 'until 4B' limitation text")


def runtime_checks(tmp: str) -> None:
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["GEMINI_API_KEY"] = ""
    sys.path.insert(0, str(ROOT))
    try:
        import hashlib

        from fastapi.testclient import TestClient
        from langchain_core.messages import AIMessage
        from langgraph.checkpoint.memory import MemorySaver
        from langgraph.checkpoint.sqlite import SqliteSaver

        import src.core.auth as auth
        import src.core.graph as graph_mod
        from src.config import settings
        from src.core.checkpointer import build_sqlite_checkpointer
        from src.core.graph import OrchestrationGraph
        from src.main import app
        from tests.fakes import ScriptedChatModel
    except Exception as exc:  # noqa: BLE001
        check("R0.imports", False, f"{type(exc).__name__}: {exc}")
        return

    check("R0.settings", getattr(settings, "CHECKPOINT_DB_PATH", None) == "data/checkpoints.db",
          f"CHECKPOINT_DB_PATH={getattr(settings, 'CHECKPOINT_DB_PATH', None)!r}")

    def scripted(n: int) -> ScriptedChatModel:
        return ScriptedChatModel(responses=[AIMessage(content=f"resposta {i}") for i in range(n)])

    def seen(model, start: int) -> str:
        return " ".join(str(m.content) for call in model.received[start:] for m in call)

    # --- builder
    try:
        p = Path(tmp) / "nested" / "dir" / "cp.db"
        s1 = build_sqlite_checkpointer(p)
        check("R1.builder", isinstance(s1, SqliteSaver) and p.parent.is_dir() and same_file(db_file_of(s1), str(p)),
              f"type={type(s1).__name__}, db={db_file_of(s1)!r}")
        blocker = Path(tmp) / "a_file"
        blocker.write_text("x", encoding="utf-8")
        before = set(Path(tmp).iterdir())
        try:
            build_sqlite_checkpointer(blocker / "sub" / "cp.db")
            check("R1.fails_loudly", False, "a path under a regular file was accepted (silent fallback?)")
        except Exception:  # noqa: BLE001
            check("R1.fails_loudly", set(Path(tmp).iterdir()) == before, "the failed build created files somewhere else")
    except Exception as exc:  # noqa: BLE001
        check("R1.runtime", False, f"{type(exc).__name__}: {exc}")
        return

    # --- default graph stays in memory; restart survival and isolation over SQLite
    try:
        g0 = OrchestrationGraph(chat_model=scripted(1))
        check("R2.default_in_memory", isinstance(g0.checkpointer, MemorySaver),
              f"OrchestrationGraph() without checkpointer must keep MemorySaver (tests), got {type(g0.checkpointer).__name__}")
        db = Path(tmp) / "restart" / "checkpoints.db"
        m1 = scripted(2)
        g1 = OrchestrationGraph(chat_model=m1, checkpointer=build_sqlite_checkpointer(db))
        g1.run_sync(user_id="merchant_a", message="guarde o codigo CODIGO-R42", session_id="s-restart")
        del g1
        gc.collect()
        m2 = scripted(3)
        g2 = OrchestrationGraph(chat_model=m2, checkpointer=build_sqlite_checkpointer(db))
        n = len(m2.received)
        g2.run_sync(user_id="merchant_a", message="qual era o codigo?", session_id="s-restart")
        check("R3.memory_survives_restart", "CODIGO-R42" in seen(m2, n),
              "a new orchestrator over the same SQLite file did not see the previous turn")
        st = g2.graph.get_state({"configurable": {"thread_id": "merchant_a:s-restart"}})
        check("R3.thread_id_in_sqlite", bool(st.values) and len(st.values.get("messages", [])) >= 4,
              f"messages in merchant_a:s-restart = {len(st.values.get('messages', [])) if st.values else 0}")
        n = len(m2.received)
        g2.run_sync(user_id="merchant_b", message="o que foi dito antes?", session_id="s-restart")
        check("R4.isolation_over_sqlite", "CODIGO-R42" not in seen(m2, n), "merchant_b read merchant_a's conversation")
        with sqlite3.connect(db) as conn:
            threads = {r[0] for r in conn.execute("SELECT DISTINCT thread_id FROM checkpoints")}
        check("R4.threads_on_disk", threads == {"merchant_a:s-restart", "merchant_b:s-restart"}, f"threads={threads}")
    except Exception as exc:  # noqa: BLE001
        check("R2.runtime", False, f"{type(exc).__name__}: {exc}")

    # --- API wiring, fail-fast startup, invalid API_KEYS
    orig = (settings.APP_ENV, settings.API_KEYS, settings.CHECKPOINT_DB_PATH, settings.RATE_LIMIT_PER_MINUTE)
    try:
        settings.APP_ENV, settings.API_KEYS, settings.RATE_LIMIT_PER_MINUTE = "development", "", 1000
        api_db = Path(tmp) / "api" / "checkpoints.db"
        settings.CHECKPOINT_DB_PATH = str(api_db)
        graph_mod._orchestrator_instance = None
        auth.reset_rate_limiter()
        o = graph_mod.get_orchestrator()
        check("R5.api_uses_sqlite", isinstance(o.checkpointer, SqliteSaver) and same_file(db_file_of(o.checkpointer), str(api_db)),
              f"get_orchestrator() checkpointer={type(o.checkpointer).__name__}, db={db_file_of(o.checkpointer)!r}")
        graph_mod._orchestrator_instance = None
        api_db2 = Path(tmp) / "api2" / "checkpoints.db"
        settings.CHECKPOINT_DB_PATH = str(api_db2)
        with TestClient(app) as c:
            h = c.get("/health")
        check("R6.startup_opens_db", api_db2.exists() and h.status_code == 200,
              f"lifespan must open the checkpoint DB at startup: exists={api_db2.exists()}, /health={h.status_code}")
        graph_mod._orchestrator_instance = None
        settings.CHECKPOINT_DB_PATH = str(Path(tmp) / "a_file" / "x" / "checkpoints.db")
        try:
            with TestClient(app):
                pass
            check("R6.startup_fails_on_bad_db_path", False, "the app started with an unusable CHECKPOINT_DB_PATH")
        except Exception:  # noqa: BLE001
            check("R6.startup_fails_on_bad_db_path", True)
        graph_mod._orchestrator_instance = None
        settings.CHECKPOINT_DB_PATH = str(api_db2)

        settings.API_KEYS = "abc:merchant:customer"
        try:
            auth.validate_auth_config()
            check("R7.validate_rejects_bad_keys", False, "validate_auth_config() accepted a malformed API_KEYS")
        except ValueError:
            check("R7.validate_rejects_bad_keys", True)
        client = TestClient(app)
        r = client.post("/chat", json={"message": "oi"}, headers={"X-API-Key": "k"})
        h = client.get("/health").json()
        check("R7.bad_keys_503_not_500", r.status_code == 503 and "API_KEYS" in r.text and h.get("auth_mode") == "invalid",
              f"/chat -> {r.status_code} {r.text[:150]}, /health auth_mode={h.get('auth_mode')}")
        try:
            with TestClient(app):
                pass
            check("R7.startup_fails_on_bad_keys", False, "the app started with a malformed API_KEYS")
        except Exception:  # noqa: BLE001
            check("R7.startup_fails_on_bad_keys", True)
        settings.API_KEYS = f"{hashlib.sha256(b'good').hexdigest()}:merchant_ok:customer"
        try:
            auth.validate_auth_config()
            ok = True
        except Exception:  # noqa: BLE001
            ok = False
        graph_mod._orchestrator_instance = None
        r = TestClient(app).post("/chat", json={"message": "oi", "session_id": "x"}, headers={"X-API-Key": "nope"})
        check("R7.valid_keys_unchanged", ok and r.status_code == 401, f"validate ok={ok}, unknown key -> {r.status_code}")
    except Exception as exc:  # noqa: BLE001
        check("R5.runtime", False, f"{type(exc).__name__}: {exc}")
    finally:
        settings.APP_ENV, settings.API_KEYS, settings.CHECKPOINT_DB_PATH, settings.RATE_LIMIT_PER_MINUTE = orig
        auth.reset_rate_limiter()
        graph_mod._orchestrator_instance = None


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks(tmp: str) -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    tests = read("tests/test_checkpointer.py")
    n_tests = len(re.findall(r"^def test_", tests, flags=re.M))
    check("Q0.checkpointer_tests", n_tests >= 5, f"tests/test_checkpointer.py has {n_tests} test functions (need >= 5)")
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1", CHECKPOINT_DB_PATH=str(Path(tmp) / "nested" / "checkpoints.db"))
    for script, allowed in PRIOR.items():
        r = run([sys.executable, f"scripts/{script}"], env=nested)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    real_db = ROOT / "data" / "checkpoints.db"
    mark = real_db.stat().st_mtime_ns if real_db.exists() else None
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")
    after = real_db.stat().st_mtime_ns if real_db.exists() else None
    check("Q4.tests_do_not_touch_data_db", mark == after,
          "the test suite wrote data/checkpoints.db; tests/conftest.py must point CHECKPOINT_DB_PATH to a temp dir before importing src")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p4b_")
    static_checks()
    runtime_checks(tmp)
    suite_checks(tmp)
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
