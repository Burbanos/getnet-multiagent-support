"""Phase 2C acceptance checks (docs/SPEC.md, Phase 2C: provider layer, fallback, safety fixes).

Usage (from the repository root):  python scripts/verify_phase2c.py
Requires the dev environment. Never calls a real LLM.
Do NOT edit this file to make checks pass: the reviewer runs an independent copy.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

ROOT = Path.cwd()
RESULTS: list[tuple[str, bool]] = []
PRIMARY, FALLBACK = "gemini-3.5-flash", "gemini-3.5-flash-lite"
# Phase 2B checks superseded by the Phase 2C model decision (default model changed on purpose).
SUPERSEDED_2B = {"S1.default_model_config", "S1.default_model_env_example", "R2.model_name"}

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=900)


def static_checks() -> None:
    files = ["src/config.py", ".env.example", "docker-compose.yml", "README.md"] + \
        [p.relative_to(ROOT).as_posix() for p in (ROOT / "src").rglob("*.py")]
    stale = sorted({f for f in files if "GEMINI_MODEL" in read(f)})
    check("S1.gemini_model_renamed", not stale, f"GEMINI_MODEL still referenced in {stale}")
    env_ex = read(".env.example")
    want = [f"LLM_PROVIDER=google_genai", f"LLM_MODEL={PRIMARY}", f"LLM_FALLBACK_MODEL={FALLBACK}"]
    check("S2.env_example", all(w in env_ex for w in want), f".env.example must contain {want}")
    readme = read("README.md")
    check("S3.readme_provider_docs", all(w in readme for w in ["LLM_PROVIDER", "LLM_MODEL", "LLM_FALLBACK_MODEL"]),
          "README does not document LLM_PROVIDER / LLM_MODEL / LLM_FALLBACK_MODEL")


def runtime_checks() -> None:
    tmp = tempfile.mkdtemp(prefix="verify_p2c_")
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["GEMINI_API_KEY"] = ""
    sys.path.insert(0, str(ROOT))
    try:
        from fastapi.testclient import TestClient
        from langchain_core.exceptions import ModelNotFoundError, ModelRateLimitError
        from langchain_core.messages import AIMessage

        import src.core.graph as graph_mod
        import src.core.llm as llm_mod
        from src.config import settings
        from src.core.graph import OrchestrationGraph
        from src.main import app
        from src.tools.agent_tools import TOOLS_BY_NAME
        from tests.fakes import ScriptedChatModel
    except Exception as exc:  # noqa: BLE001
        check("R0.imports", False, f"{type(exc).__name__}: {exc}")
        return

    have = {a: getattr(settings, a, None) for a in ("LLM_PROVIDER", "LLM_MODEL", "LLM_FALLBACK_MODEL")}
    check("R1.settings_defaults", have == {"LLM_PROVIDER": "google_genai", "LLM_MODEL": PRIMARY, "LLM_FALLBACK_MODEL": FALLBACK},
          f"settings={have}")
    check("R1.gemini_model_removed", not hasattr(settings, "GEMINI_MODEL"), "settings.GEMINI_MODEL still exists")

    try:
        settings.GEMINI_API_KEY = "dummy-key-for-construction-only"
        p = llm_mod.get_chat_model()
        f = llm_mod.get_fallback_model()
        o = llm_mod.get_chat_model("some-other-model")
        check("R2.factory_primary", PRIMARY in str(getattr(p, "model", "")) and FALLBACK not in str(getattr(p, "model", "")),
              f"primary model={getattr(p, 'model', None)}")
        check("R2.factory_fallback", f is not None and FALLBACK in str(getattr(f, "model", "")), f"fallback={getattr(f, 'model', None)}")
        check("R2.factory_model_override", "some-other-model" in str(getattr(o, "model", "")), f"override={getattr(o, 'model', None)}")
        check("R2.timeouts_kept", getattr(p, "timeout", None) == float(settings.LLM_TIMEOUT_S)
              and getattr(f, "timeout", None) == float(settings.LLM_TIMEOUT_S), "timeout not applied to primary and fallback")
        old_fb = settings.LLM_FALLBACK_MODEL
        settings.LLM_FALLBACK_MODEL = ""
        check("R2.fallback_disabled_when_empty", llm_mod.get_fallback_model() is None, "empty LLM_FALLBACK_MODEL must return None")
        settings.LLM_FALLBACK_MODEL = old_fb
        for prov in ("not-a-provider", "anthropic"):
            old_p = settings.LLM_PROVIDER
            settings.LLM_PROVIDER = prov
            try:
                llm_mod.get_chat_model()
                check(f"R3.provider_{prov}", False, "no error raised")
            except llm_mod.LLMConfigurationError:
                check(f"R3.provider_{prov}", True)
            except Exception as exc:  # noqa: BLE001
                check(f"R3.provider_{prov}", False, f"raised {type(exc).__name__} instead of LLMConfigurationError")
            finally:
                settings.LLM_PROVIDER = old_p
    except Exception as exc:  # noqa: BLE001
        check("R2.runtime", False, f"{type(exc).__name__}: {exc}")
    finally:
        settings.GEMINI_API_KEY = ""

    class Raising(ScriptedChatModel):
        exc: Exception | None = None

        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            self.received.append(list(messages))
            raise self.exc

    class NamedFake(ScriptedChatModel):
        model: str = "fake-fallback-model"

    try:
        fb = NamedFake(responses=[AIMessage(content="resposta do reserva")])
        st = OrchestrationGraph(chat_model=Raising(exc=ModelRateLimitError("429")), fallback_model=fb).run_sync(
            user_id="cliente1988", message="oi", session_id="v2c-fb")
        check("R4.fallback_on_transient", st.agent_response == "resposta do reserva", f"response={st.agent_response!r}")
        check("R4.model_used_reported", getattr(st, "llm_model", None) == "fake-fallback-model",
              f"llm_model={getattr(st, 'llm_model', None)!r}")

        fb2 = NamedFake(responses=[AIMessage(content="nao deveria")])
        try:
            OrchestrationGraph(chat_model=Raising(exc=ModelNotFoundError("gone")), fallback_model=fb2).run_sync(
                user_id="cliente1988", message="oi", session_id="v2c-cfg")
            check("R5.no_fallback_on_config_error", False, "no exception raised")
        except llm_mod.LLMConfigurationError:
            check("R5.no_fallback_on_config_error", len(fb2.received) == 0, "fallback was called on a configuration error")

        try:
            OrchestrationGraph(chat_model=Raising(exc=ModelRateLimitError("429")),
                               fallback_model=Raising(exc=TimeoutError("t"))).run_sync(user_id="cliente1988", message="oi", session_id="v2c-both")
            check("R6.both_fail_unavailable", False, "no exception raised")
        except llm_mod.LLMUnavailableError:
            check("R6.both_fail_unavailable", True)

        fake_only = ScriptedChatModel(responses=[AIMessage(content="ok")])
        st = OrchestrationGraph(chat_model=fake_only).run_sync(user_id="cliente1988", message="oi", session_id="v2c-nofb")
        check("R7.injected_model_without_fallback", st.agent_response == "ok", f"response={st.agent_response!r}")

        graph_mod._orchestrator_instance = OrchestrationGraph(chat_model=NamedFake(responses=[AIMessage(content="ok")]))
        r = TestClient(app).post("/chat", json={"message": "oi", "user_id": "cliente1988"})
        check("R7.api_reports_model", r.status_code == 200 and r.json().get("metadata", {}).get("llm_model") == "fake-fallback-model",
              f"status {r.status_code}, llm_model={r.json().get('metadata', {}).get('llm_model') if r.status_code == 200 else None!r}")
    except Exception as exc:  # noqa: BLE001
        check("R4.runtime", False, f"{type(exc).__name__}: {exc}")
    finally:
        graph_mod._orchestrator_instance = None

    out = TOOLS_BY_NAME["get_settlement_status"].invoke({}, config={"configurable": {"user_id": "cliente1988"}})
    leaked = [s for s in ("1234", "98765") if s in out]
    check("R8.bank_account_masked", not leaked and "65-4" in out, f"leaked={leaked}; masked tail '65-4' present={'65-4' in out}")

    original = TOOLS_BY_NAME["escalate_to_human"]

    class BadTool:
        name = "escalate_to_human"

        def __init__(self, mode: str):
            self.mode = mode

        def invoke(self, *a, **k):
            if self.mode == "raise":
                raise RuntimeError("db down")
            return "not-json"

    old_steps = settings.MAX_SUPERVISOR_STEPS
    try:
        settings.MAX_SUPERVISOR_STEPS = 1
        for mode in ("garbage", "raise"):
            TOOLS_BY_NAME["escalate_to_human"] = BadTool(mode)
            loop = ScriptedChatModel(responses=[
                AIMessage(content="", tool_calls=[{"name": "get_settlement_status", "args": {}, "id": f"l-{mode}-{i}"}])
                for i in range(5)])
            try:
                st = OrchestrationGraph(chat_model=loop).run_sync(user_id="cliente1988", message="x", session_id=f"v2c-esc-{mode}")
                resp = st.agent_response or ""
                ok = st.ticket is None and "PENDING" not in resp and "Registrei" not in resp and bool(resp)
                check(f"R9.no_false_ticket_{mode}", ok, f"ticket={st.ticket!r}, response={resp!r}")
            except Exception as exc:  # noqa: BLE001
                check(f"R9.no_false_ticket_{mode}", False, f"raised {type(exc).__name__}: {exc}")
    finally:
        TOOLS_BY_NAME["escalate_to_human"] = original
        settings.MAX_SUPERVISOR_STEPS = old_steps


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks() -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    env0 = {k: v for k, v in os.environ.items() if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY")}
    env0["GEMINI_API_KEY"] = ""
    a = run([sys.executable, "scripts/verify_phase2a.py"], env=env0)
    fails_a = [ln for ln in a.stdout.splitlines() if ln.startswith("FAIL")]
    check("Q0.phase2a_still_passes", a.returncode == 0, "; ".join(fails_a[:5]) or a.stdout[-300:])
    b = run([sys.executable, "scripts/verify_phase2b.py"], env=env0)
    fails_b = {ln.split()[1] for ln in b.stdout.splitlines() if ln.startswith("FAIL")}
    unexpected = sorted(fails_b - SUPERSEDED_2B)
    check("Q0.phase2b_only_superseded_fail", "SUMMARY" in b.stdout and not unexpected,
          f"unexpected 2B failures: {unexpected}" if unexpected else b.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    static_checks()
    runtime_checks()
    suite_checks()
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
