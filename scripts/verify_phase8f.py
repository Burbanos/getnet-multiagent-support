def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def static_checks() -> None:
    readme, status = read("README.md"), read("docs/STATUS.md")
    i = readme.find("#### Execuções registradas")
    j = readme.find("### Resultados da avaliação: comparação de modelos")
    sec = readme[i:j] if 0 <= i < j else ""
    check("F1.runs_heading", "Execução de Referência Registrada" not in readme and bool(sec)
          and all(w in sec for w in ("reports/eval_models.md", "full-1", "histórica", "full-2", "full-7")),
          "the 'Execução de Referência Registrada' sub-heading must become '#### Execuções registradas' (right before the "
          "comparison section) naming the six runs, reports/eval_models.md and full-1 as historical")
    lim = readme[readme.find("## Limitações atuais"):readme.find("## Interface Visual")]
    line = next((ln for ln in lim.splitlines() if "Testes com modelo roteirizado" in ln), "")
    check("F2.limitations_point_to_comparison", "reports/eval_models.md" in line,
          f"'Limitações atuais' must point to reports/eval_models.md: {line[-160:]!r}")
    toc = readme[readme.find("## Sumário"):readme.find("## 1. Arquitetura do Sistema")]
    check("F3.toc_entry", f"]({ANCHOR})" in toc and "#resultados-da-avaliação-execução-full-1-2026-11-07" in toc,
          "the table of contents must link the comparison section and keep the full-1 link")
    obs = readme[readme.find("### Observabilidade Técnica"):readme.find("* **Logs Estruturados e Privacidade")]
    check("F4.reasoning_tokens_note", all(w in obs for w in ("raciocínio", "1.484.859", "215.078", "AI Studio")),
          "the cost bullets must say the recorded output tokens include reasoning tokens, with the AI Studio cross-check")
    for must in ("62/69 (89,9%)", "## 6. Matriz de Cobertura dos Cenários Oficiais", "| Casos aprovados (checagens determinísticas) | 86,0% (84,1–89,9) | 88,9% (88,4–89,9) |"):
        check(f"F5.kept.{must[:24]}", must in readme, f"README lost {must!r}")
    tail = status[status.rfind("Fase 8F"):] if "Fase 8F" in status else ""
    check("E1.status", bool(tail), "STATUS needs a 'Fase 8F' section")
    diff = run(["git", "diff", "--name-only", "c2d52e3"])
    changed = set(diff.stdout.split())
    extra = sorted(changed - {"README.md", "docs/STATUS.md", "docs/SPEC.md", "docs/phase-prompts/8F.md", "scripts/verify_phase8f.py"})
    check("E2.readme_only", diff.returncode == 0 and not extra, f"since 8E (c2d52e3), 8F may change only README.md and docs/STATUS.md: {extra or diff.stderr[-200:]}")


