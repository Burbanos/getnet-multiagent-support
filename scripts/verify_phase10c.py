def module_checks(tmp: str) -> None:  # noqa: C901 - one scenario per check, kept linear on purpose
    os.environ["GEMINI_API_KEY"] = ""
    sys.path.insert(0, str(ROOT))
    try:
        from langchain_core.language_models.chat_models import BaseChatModel
        from langchain_core.messages import AIMessage
        from langchain_core.outputs import ChatGeneration, ChatResult
        from pydantic import Field

        from src.agents.injection_classifier import InjectionClassifier
        from src.config import settings
        from src.core.llm import LLMNotConfiguredError
        from src.core.pii import sanitize_pii
        from src.eval import guardrail_eval as ge
    except Exception as exc:  # noqa: BLE001
        check("C1.imports", False, f"{type(exc).__name__}: {exc}")
        return

    class Fake(BaseChatModel):
        """Answers by a rule on the message (callable) or pops scripted items (an Exception is raised); records inputs."""
        name_: str = "gemini-3.5-flash-lite"
        rule: Any = None
        responses: list[Any] = Field(default_factory=list)
        received: list[list[Any]] = Field(default_factory=list)

        def bind_tools(self, tools, **kwargs):
            return self

        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            self.received.append(list(messages))
            if self.rule is not None:
                r = self.rule(messages[-1].content)
            else:
                r = self.responses.pop(0) if self.responses else RuntimeError("verify fake: no scripted response left")
            if isinstance(r, Exception):
                raise r
            return ChatResult(generations=[ChatGeneration(message=r)])

        @property
        def _llm_type(self) -> str:
            return self.name_

    def vd(v: str, c: str, i: int = 120, o: int = 9) -> AIMessage:
        return AIMessage(content="", tool_calls=[{"name": "GuardrailVerdict", "args": {"verdict": v, "category": c}, "id": "g"}],
                         usage_metadata={"input_tokens": i, "output_tokens": o, "total_tokens": i + o,
                                         "input_token_details": {"cache_read": 0}})

    cases = load_set()
    by_text = {c["text"]: c for c in cases}

    def oracle(content: str) -> AIMessage:  # a perfect classifier, keyed on the unescaped message text
        inner = content.split("\n", 1)[1].rsplit("\n", 1)[0].replace("&lt;", "<").replace("&gt;", ">")
        c = by_text[inner]
        return vd("allow", "none", 100, 5) if c["label"] == "allow" else vd("block", c["kind"], 140, 9)

    masked = {c["id"]: sanitize_pii(c["text"])[0] for c in cases}
    names = ("run_guardrail", "guardrail_report", "write_guardrail_report", "guardrail_summary", "write_guardrail_summary",
             "GUARDRAIL_TARGETS", "GUARDRAIL_COST_NOTE", "RECORD_KEYS", "DEFAULT_GUARDRAIL_RUNS_DIR")
    keys_ok = all(hasattr(ge, n) for n in names)
    check("C1.api", keys_ok and ge.GUARDRAIL_TARGETS == TARGETS and ge.GUARDRAIL_COST_NOTE == COST_NOTE
          and ge.RECORD_KEYS == RECORD_KEYS and Path(ge.DEFAULT_GUARDRAIL_RUNS_DIR).as_posix() == "reports/guardrail_runs",
          f"guardrail_eval must expose {names} exactly as in the prompt")
    if not keys_ok:
        return

    # C2/C3: a full run with a perfect classifier, then a resumed run
    try:
        path = Path(tmp, "runs", "perfect.jsonl")
        fake = Fake(rule=oracle)
        out = ge.run_guardrail(cases, path, "perfect", classifier=InjectionClassifier(model=fake), sleep_s=0)
        raw = path.read_text(encoding="utf-8")
        lines = [json.loads(ln) for ln in raw.splitlines() if ln.strip()]
        leaked = [c["id"] for c in cases if c["text"] in raw]
        rec_ok = (len(lines) == 36 and all(set(r) == RECORD_KEYS for r in lines) and [r["id"] for r in lines] == [c["id"] for c in cases]
                  and all(r["run_id"] == "perfect" and r["status"] == "ok" for r in lines)
                  and all(r["pattern_category"] == ref_pattern(masked[r["id"]]) for r in lines)
                  and all(r["usage"] is not None and set(r["usage"]) == {"input_tokens", "output_tokens", "total_tokens"} for r in lines)
                  and all(set(r["classifier"]) == {"status", "verdict", "category", "error_type", "latency_ms", "model"} for r in lines))
        check("C2.run_records", out == {"attempted": 36, "ok": 36, "errors": 0, "skipped": 0, "stopped_early": False} and rec_ok
              and not leaked and len(fake.received) == 36, f"out={out} records_ok={rec_ok} leaked={leaked} calls={len(fake.received)}")
        again = ge.run_guardrail(cases, path, "perfect", classifier=InjectionClassifier(model=Fake(rule=oracle)), sleep_s=0)
        check("C3.resume_skips_ok", again == {"attempted": 0, "ok": 0, "errors": 0, "skipped": 36, "stopped_early": False},
              f"second run: {again}")
    except Exception as exc:  # noqa: BLE001
        check("C2.run_records", False, f"{type(exc).__name__}: {exc}")

    # C4: errors, stop, retry; PII masked before the classifier
    try:
        path = Path(tmp, "runs", "errs.jsonl")
        f1 = Fake(responses=[vd("allow", "none") if c["label"] == "allow" else vd("block", c["kind"]) for c in cases[:2]]
                  + [RuntimeError("x"), RuntimeError("y"), RuntimeError("z")])
        o1 = ge.run_guardrail(cases, path, "errs", classifier=InjectionClassifier(model=f1), sleep_s=0)
        recs1 = [json.loads(ln) for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]
        f2 = Fake(rule=oracle)
        o2 = ge.run_guardrail(cases, path, "errs", classifier=InjectionClassifier(model=f2), sleep_s=0)
        first_call = f2.received[0][-1].content if f2.received else ""
        pii_case = [{"id": "p1", "lang": "pt", "label": "allow", "kind": "legit", "source": "near_miss", "split": "dev",
                     "text": f"Meu cartão {CARD} e CPF {CPF}, a venda caiu?"}]
        f3 = Fake(responses=[vd("allow", "none")])
        ge.run_guardrail(pii_case, Path(tmp, "runs", "pii.jsonl"), "pii", classifier=InjectionClassifier(model=f3), sleep_s=0)
        seen = f3.received[0][-1].content if f3.received else ""
        ok = (o1 == {"attempted": 5, "ok": 2, "errors": 3, "skipped": 0, "stopped_early": True} and len(recs1) == 5
              and [r["status"] for r in recs1] == ["ok", "ok", "error", "error", "error"]
              and recs1[2]["classifier"]["error_type"] == "RuntimeError" and recs1[2]["usage"] is None
              and o2 == {"attempted": 34, "ok": 34, "errors": 0, "skipped": 2, "stopped_early": False}
              and cases[2]["text"] in first_call.replace("&lt;", "<").replace("&gt;", ">")
              and CARD not in seen and CPF not in seen and "[CARTAO_MASCARADO_****1111]" in seen)
        check("C4.errors_stop_retry_and_pii", ok, f"first={o1} statuses={[r['status'] for r in recs1]} second={o2} "
              f"pii_seen={seen[:120]!r}")
    except Exception as exc:  # noqa: BLE001
        check("C4.errors_stop_retry_and_pii", False, f"{type(exc).__name__}: {exc}")

    # C5: no key -> LLMNotConfiguredError, no line written
    try:
        settings.GEMINI_API_KEY = ""
        path = Path(tmp, "runs", "nokey.jsonl")
        try:
            ge.run_guardrail(cases, path, "nokey", sleep_s=0)
            raised = None
        except LLMNotConfiguredError:
            raised = "LLMNotConfiguredError"
        except Exception as exc:  # noqa: BLE001
            raised = type(exc).__name__
        written = path.read_text(encoding="utf-8").strip() if path.exists() else ""
        check("C5.no_key_propagates", raised == "LLMNotConfiguredError" and not written, f"raised={raised} written={written[:80]!r}")
    except Exception as exc:  # noqa: BLE001
        check("C5.no_key_propagates", False, f"{type(exc).__name__}: {exc}")

    def rec(cid: str, status: str, verdict: str | None = None, category: str | None = None, lat: float | None = 50.0,
            model: str | None = "gemini-3.5-flash-lite", usage: dict | None = None) -> dict:
        return {"id": cid, "run_id": "syn", "status": status, "pattern_category": None,
                "classifier": {"status": status, "verdict": verdict, "category": category,
                               "error_type": None if status == "ok" else "RuntimeError", "latency_ms": lat, "model": model},
                "usage": usage, "recorded_at": "2026-11-09T00:00:00+00:00"}

    # C6-C8: report against the reference on synthetic records (misses, false positive, errors, missing)
    reports: dict[str, dict] = {}
    try:
        u = {"input_tokens": 130, "output_tokens": 7, "total_tokens": 137}
        syn: dict[str, dict] = {}
        lat_seq = [float(90 + (k * 37) % 401) for k in range(len(cases))]  # distinct values: p95 is not the maximum
        for k, c in enumerate(cases):
            if c["id"] in ("gb19", "ga16"):
                continue  # no record
            if c["id"] in ("gb12", "ga09"):
                syn[c["id"]] = rec(c["id"], "error", lat=lat_seq[k])
                continue
            if c["id"] in ("gb10", "gb11", "ga03"):  # classifier misses gb10/gb11 and blocks the legitimate ga03
                v, cat = ("allow", "none") if c["label"] == "block" else ("block", "prompt_leak")
            else:
                v, cat = ("allow", "none") if c["label"] == "allow" else ("block", c["kind"])
            syn[c["id"]] = rec(c["id"], "ok", v, cat, lat=lat_seq[k], usage=dict(u, input_tokens=100 + k))
        got = ge.guardrail_report(cases, syn, "syn", SET_PATH)
        want = ref_report(cases, syn, masked)
        differ = [k for k in want if got.get(k) != want[k]]
        meta_ok = (set(got) == REPORT_KEYS and got.get("run_id") == "syn" and got.get("set_path") == SET_PATH
                   and got.get("set_sha256") == ge.guardrail_set_sha256(cases) and isinstance(got.get("generated_at"), str)
                   and all(set(ci) == CASE_ITEM_KEYS for ci in got.get("cases", [])))
        check("C6.report_semantics", not differ and meta_ok,
              f"keys differing from the reference: {differ[:6]} (meta_ok={meta_ok}); "
              + "; ".join(f"{k}: got {str(got.get(k))[:160]} want {str(want[k])[:160]}" for k in differ[:2]),
              info=f"synthetic hybrid {want['layers']['hybrid']['all']['blocked_block']}/20 blocked, "
                   f"{want['layers']['hybrid']['all']['blocked_allow']}/16 false positives, targets_met={want['targets_met']}")
        reports["syn"] = got
        perfect = {c["id"]: rec(c["id"], "ok", *(("allow", "none") if c["label"] == "allow" else ("block", c["kind"])), usage=u)
                   for c in cases}
        gp = ge.guardrail_report(cases, perfect, "p", SET_PATH)
        unpriced = {k: dict(v, classifier=dict(v["classifier"], model="some-unlisted-model")) for k, v in perfect.items()}
        gu = ge.guardrail_report(cases, unpriced, "u", SET_PATH)
        incomplete = {k: v for k, v in perfect.items() if k != "ga16"}  # perfect rates, one legitimate message never classified
        gi = ge.guardrail_report(cases, incomplete, "i", SET_PATH)
        lat_ok = got["latency_ms"]["p95"] != max(r["classifier"]["latency_ms"] for r in syn.values())
        check("C7.targets_and_cost", gp["targets_met"] is True and got["targets_met"] is False and lat_ok
              and gi["targets_met"] is False and gi["complete"] is False and gi["missing"] == ["ga16"]
              and gi["layers"]["hybrid"]["all"]["block_rate"] == 1.0 and gi["layers"]["hybrid"]["all"]["false_positive_rate"] == 0.0
              and gp["cost_usd_mean_per_message"] is not None
              and gp["cost_usd_mean_per_message"] == ref_report(cases, perfect, masked)["cost_usd_mean_per_message"]
              and gu["cost_usd_mean_per_message"] is None,
              f"perfect targets_met={gp['targets_met']} synthetic={got['targets_met']} incomplete={gi['targets_met']} "
              f"(complete={gi['complete']}, missing={gi['missing']}) p95_differs_from_max={lat_ok} "
              f"cost={gp['cost_usd_mean_per_message']} unpriced={gu['cost_usd_mean_per_message']}")
        reports["p"], reports["u"] = gp, gu
        out_j, out_m = Path(tmp, "rep", "g.json"), Path(tmp, "rep", "g.md")
        wr = ge.write_guardrail_report(cases, syn, out_j, out_m, "syn", SET_PATH)
        disk = json.loads(out_j.read_text(encoding="utf-8"))
        md = out_m.read_text(encoding="utf-8").replace("\r\n", "\n")
        want_md = ref_md(wr)
        check("C8.report_files", disk == wr and md == want_md,
              "written JSON must equal the returned dict and the Markdown must follow the prompt exactly: "
              + next((f"got {a!r} want {b!r}" for a, b in zip(md.splitlines(), want_md.splitlines()) if a != b),
                     f"length differs ({len(md)} vs {len(want_md)})"))
    except Exception as exc:  # noqa: BLE001
        check("C6.report_semantics", False, f"{type(exc).__name__}: {exc}")

    # C10: summary across runs
    try:
        if len(reports) == 3:
            rs = [reports["syn"], reports["p"], reports["u"]]
            s = ge.guardrail_summary(rs)
            ok = (set(s) == {"generated_at", "n_runs", "runs", "all_targets_met", "metrics"} and s["n_runs"] == 3
                  and s["runs"] == [{"run_id": r["run_id"], "models": r["models"], "complete": r["complete"],
                                     "targets_met": r["targets_met"]} for r in rs]
                  and s["all_targets_met"] is False and s["metrics"] == ref_summary_metrics(rs)
                  and ge.guardrail_summary([reports["p"], reports["p"]])["all_targets_met"] is True)
            wj, wm = Path(tmp, "sum", "s.json"), Path(tmp, "sum", "s.md")
            w = ge.write_guardrail_summary(rs, wj, wm)
            md = wm.read_text(encoding="utf-8")
            ok_files = (json.loads(wj.read_text(encoding="utf-8")) == w and md.startswith("# Guardrail: resumo de 3 execuções")
                        and all(f"- {r['run_id']}:" in md for r in rs) and "| Métrica | Média | Mínimo | Máximo |" in md
                        and md.rstrip().endswith("Metas atingidas em todas as execuções: não"))
            check("C10.summary", ok and ok_files, f"metrics={s.get('metrics')} want {ref_summary_metrics(rs)}; files_ok={ok_files}")
        else:
            check("C10.summary", False, "reports from C6/C7 unavailable")
    except Exception as exc:  # noqa: BLE001
        check("C10.summary", False, f"{type(exc).__name__}: {exc}")


def cli_checks(tmp: str) -> None:
    env = {k: v for k, v in os.environ.items() if k not in ("GEMINI_API_KEY", "LLM_PROVIDER")}
    env["GEMINI_API_KEY"] = ""
    runs = Path(tmp, "cli_runs")
    r1 = run([sys.executable, "-m", "src.eval", "guardrail-run", "--run-id", "k", "--runs-dir", str(runs), "--sleep", "0"], env=env)
    f = runs / "k.jsonl"
    no_lines = (not f.exists()) or not f.read_text(encoding="utf-8").strip()
    out_missing = Path(tmp, "cli_out")
    r2 = run([sys.executable, "-m", "src.eval", "guardrail-report", "--run-id", "nope", "--runs-dir", str(runs),
              "--out-dir", str(out_missing)], env=env)
    r3 = run([sys.executable, "-m", "src.eval", "guardrail-summary", "--run-ids", "nope", "--out-dir", str(out_missing)], env=env)
    nothing = not out_missing.exists() or not any(out_missing.iterdir())
    recs = []
    for c in load_set():
        v, cat = ("allow", "none") if c["label"] == "allow" else ("block", c["kind"])
        recs.append({"id": c["id"], "run_id": "cli1", "status": "ok", "pattern_category": None,
                     "classifier": {"status": "ok", "verdict": v, "category": cat, "error_type": None, "latency_ms": 100.0,
                                    "model": "gemini-3.5-flash-lite"},
                     "usage": {"input_tokens": 120, "output_tokens": 8, "total_tokens": 128},
                     "recorded_at": "2026-11-09T00:00:00+00:00"})
    runs.mkdir(parents=True, exist_ok=True)
    (runs / "cli1.jsonl").write_text("\n".join(json.dumps(x) for x in recs) + "\n", encoding="utf-8")
    out = Path(tmp, "cli_out2")
    r4 = run([sys.executable, "-m", "src.eval", "guardrail-report", "--run-id", "cli1", "--runs-dir", str(runs),
              "--out-dir", str(out)], env=env)
    r5 = run([sys.executable, "-m", "src.eval", "guardrail-summary", "--run-ids", "cli1,cli1", "--out-dir", str(out)], env=env)
    rep_ok = (out / "guardrail_cli1.json").exists() and (out / "guardrail_cli1.md").exists()
    sum_ok = (out / "guardrail_summary.json").exists() and (out / "guardrail_summary.md").exists()
    line4 = next((ln for ln in r4.stdout.splitlines() if ln.startswith("guardrail-report:")), "")
    line5 = next((ln for ln in r5.stdout.splitlines() if ln.startswith("guardrail-summary:")), "")
    check("C11.cli", r1.returncode == 2 and "GEMINI_API_KEY" in r1.stderr and no_lines and r2.returncode == 1
          and r3.returncode == 1 and nothing and r4.returncode == 0 and rep_ok and "targets_met True" in line4
          and r5.returncode == 0 and sum_ok and "2 runs, all_targets_met True" in line5,
          f"run rc={r1.returncode} {r1.stderr.strip()[-120:]!r} lines_written={not no_lines}; report-missing rc={r2.returncode}; "
          f"summary-missing rc={r3.returncode}; nothing_written={nothing}; report rc={r4.returncode} {line4!r}; "
          f"summary rc={r5.returncode} {line5!r}", info=line4)


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks(tmp: str) -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH",
                         "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1", CHECKPOINT_DB_PATH=str(Path(tmp) / "nested" / "checkpoints.db"))
    for script, allowed in PRIOR.items():
        env_s = {k: v for k, v in nested.items() if k != "CHECKPOINT_DB_PATH"} if script == "verify_phase4b.py" else nested
        r = run([sys.executable, f"scripts/{script}"], env=env_s)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else (r.stdout + r.stderr)[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    marks = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in ("data/tickets.db", "data/checkpoints.db")}
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "warning" not in last, last, info=last)
    g = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider",
             "tests/test_guardrail_eval_runs.py"], env=env)
    glines = [ln for ln in g.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    glast = glines[-1] if glines else g.stdout[-300:]
    m = re.search(r"(\d+) passed", glast)
    check("Q2.runner_tests", g.returncode == 0 and bool(m) and int(m.group(1)) >= len(TEST_NAMES), glast, info=glast)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")
    after = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in marks}
    check("Q4.tests_do_not_touch_data_dbs", marks == after, f"the test suite wrote {[p for p in marks if marks[p] != after[p]]}")
    extra_reports = sorted(p.name for p in (ROOT / "reports").glob("guardrail_*")
                           if p.name not in ("guardrail_patterns.json", "guardrail_patterns.md"))
    check("Q5.no_real_runs_committed", not extra_reports,
          f"10C must not create real-model reports (they come from the user's runs in 10F): {extra_reports}")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p10c_")
    static_checks()
    module_checks(tmp)
    cli_checks(tmp)
    suite_checks(tmp)
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
