def r_fold(text: str) -> str:
    t = "".join(c for c in unicodedata.normalize("NFKD", text) if not unicodedata.combining(c)).lower()
    return "".join(c if c.isalnum() else " " for c in t)


class RefBM25:
    def __init__(self, docs: list[str], k1: float = 1.2, b: float = 0.75) -> None:
        self.toks = [r_fold(d).split() for d in docs]
        self.k1, self.b, self.n = k1, b, len(docs)
        self.avg = sum(map(len, self.toks)) / self.n if self.n else 0.0
        self.df: dict[str, int] = {}
        for t in self.toks:
            for w in set(t):
                self.df[w] = self.df.get(w, 0) + 1

    def scores(self, q: str) -> list[float]:
        terms = list(dict.fromkeys(r_fold(q).split()))
        out = []
        for t in self.toks:
            parts = []
            for w in terms:
                tf = t.count(w)
                if tf:
                    idf = math.log(1 + (self.n - self.df[w] + 0.5) / (self.df[w] + 0.5))
                    parts.append(idf * tf * (self.k1 + 1) / (tf + self.k1 * (1 - self.b + self.b * len(t) / self.avg)))
            out.append(math.fsum(parts))
        return out

    def top(self, q: str, k: int) -> list[tuple[int, float]]:
        return sorted([(i, s) for i, s in enumerate(self.scores(q)) if s > 0], key=lambda x: (-x[1], x[0]))[:k]


def ref_pipeline(np, chunks, emb, qvec, query, rerank_fn, bm, min_score=0.61, top_k=4, nd=6, nl=6, minrel=2, k=60):
    """Returns (status, reason, docs[(chunk_id, dense_rank, lexical_rank, relevance)], candidates[chunk_id], relevance, called)."""
    q = np.array(qvec, dtype=np.float32).flatten()
    q = q / np.linalg.norm(q)
    s = emb @ q
    order = [int(i) for i in np.argsort(-s, kind="stable")]
    if s[order[0]] < min_score:
        return "abstain", "below_threshold", [], [], None, False
    drank = {i: r for r, i in enumerate(order, 1)}
    D, L = order[:nd], [i for i, _ in bm.top(query, nl)]
    lrank = {i: r for r, i in enumerate(L, 1)}
    cands = list(dict.fromkeys(D + L))
    fused = {i: math.fsum(1 / (k + r) for lst in (D, L) for r, j in enumerate(lst, 1) if j == i) for i in cands}
    cands.sort(key=lambda i: (-fused[i], drank[i], i))
    status, rel = rerank_fn([chunks[i] for i in cands])
    if status == "ok":
        kept = sorted([p for p in range(len(cands)) if rel[p] >= minrel], key=lambda p: (-rel[p], p))[:top_k]
        docs = [(chunks[cands[p]]["chunk_id"], drank[cands[p]], lrank.get(cands[p]), rel[p]) for p in kept]
        return ("success" if docs else "abstain"), (None if docs else "no_passage_answers"), docs, \
            [chunks[i]["chunk_id"] for i in cands], rel, True
    docs = [(chunks[i]["chunk_id"], drank[i], lrank.get(i), None) for i in order[:top_k] if s[i] >= min_score]
    return "success", None, docs, [chunks[i]["chunk_id"] for i in cands], None, True


def norm_text(s: str) -> str:
    return " ".join(s.split()).lower()


def ref_metrics(labeled, docs_by_id, chunks_by_id) -> dict:
    ans = [r for r in labeled if r["category"] == "answerable"]
    out_r, h1, h3, ah, answered, ranks = [], 0, 0, 0, 0, {}
    for r in ans:
        docs = [chunks_by_id[c] for c in docs_by_id.get(r["id"], [])]
        answered += bool(docs)
        first = next((k for k, d in enumerate(docs, 1) if d["doc_url"] in r["gold_urls"]), None)
        h1 += bool(first and first <= 1)
        h3 += bool(first and first <= 3)
        out_r.append(1 / first if first else 0.0)
        hit = next((k for k, d in enumerate(docs, 1) if d["doc_url"] in r["gold_urls"]
                    and any(norm_text(g) in norm_text(d["text"]) for g in r["gold_snippets"])), None)
        ranks[r["id"]] = hit
        ah += bool(hit and hit <= 3)
    n = len(ans)
    cat = lambda c: [r for r in labeled if r["category"] == c]  # noqa: E731
    return {"answer_rate": answered / n, "hit@1": h1 / n, "hit@3": h3 / n, "mrr": math.fsum(out_r) / n, "answer_hit@3": ah / n,
            "off_topic_abstain_rate": sum(1 for r in cat("off_topic") if not docs_by_id.get(r["id"])) / len(cat("off_topic")),
            "uncovered_abstain_rate": sum(1 for r in cat("uncovered") if not docs_by_id.get(r["id"])) / len(cat("uncovered")),
            "answer_chunk_rank": ranks}


def close(a, b, path="") -> list[str]:
    if isinstance(a, bool) or isinstance(b, bool):
        return [] if a == b and type(a) is type(b) else [path]
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return [] if math.isclose(a, b, rel_tol=0, abs_tol=1e-9) else [path]
    if isinstance(a, dict) and isinstance(b, dict):
        if set(a) != set(b):
            return [f"{path} keys {sorted(a)} != {sorted(b)}"]
        return [d for k in a for d in close(a[k], b[k], f"{path}.{k}")]
    if isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            return [f"{path} len"]
        return [d for i, (x, y) in enumerate(zip(a, b)) for d in close(x, y, f"{path}[{i}]")]
    return [] if a == b else [path]


