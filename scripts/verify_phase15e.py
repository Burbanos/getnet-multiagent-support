# ------------------------------------------------------------------------------------------------------------ matrix
def readme_matrix() -> dict[str, list[str]]:
    readme = read("README.md")
    sect = readme.split("### Comparação com a versão avaliada", 1)[-1].split("\n### ", 1)[0]
    rows = {}
    for ln in sect.splitlines():
        cells = [c.strip() for c in ln.strip().strip("|").split("|")]
        if len(cells) == 5 and re.fullmatch(r"[EBV][0-9.]+", cells[0]):
            rows[cells[0]] = cells
    return rows


def v2_groups() -> dict:
    from src.eval.compare import compare_runs
    cases = jsonl("data/eval/cases_v2.jsonl")
    out = {}
    for tag, excl in (("all", set()), ("noexc", EXCEPTIONS_V2)):
        cs = [c for c in cases if c["id"] not in excl]
        groups = [(lab, [(r, jsonl(f"reports/eval_runs/{r}.jsonl"), jsonl(f"reports/eval_runs/{r}.judge.jsonl"))
                         for r in ids]) for lab, ids in (("14", G14), ("r2", G_R2))]
        res = compare_runs(cs, groups)
        out[tag] = {g["label"]: g for g in res["groups"]}
    return out


def case_passes(case_id: str, runs: list[str], cases_path: str = "data/eval/cases_v2.jsonl") -> int:
    from src.eval.metrics import evaluate_case
    case = next(c for c in jsonl(cases_path) if c["id"] == case_id)
    n = 0
    for r in runs:
        rec = next(x for x in jsonl(f"reports/eval_runs/{r}.jsonl") if x["id"] == case_id)
        n += bool(evaluate_case(case, rec)["passed"])
    return n


def pass_rate(cases_path: str, run_id: str) -> tuple[float, list[str]]:
    from src.eval.metrics import aggregate
    a = aggregate(jsonl(cases_path), jsonl(f"reports/eval_runs/{run_id}.jsonl"), None)
    return a["metrics"]["pass_rate"], [pc["id"] for pc in a["per_case"] if not pc["passed"]]


def retrieval(run_id: str, index_rev: str | None, excl: set[str], drop_covered: bool) -> dict:
    from src.rag.hybrid_eval import metrics
    recs = [r for r in jsonl("data/eval/retrieval_labeled.jsonl") if r["id"] not in excl
            and not (drop_covered and r["id"] in NOW_COVERED)]
    raw = base_file("data/index/chunks.jsonl", index_rev) if index_rev else read("data/index/chunks.jsonl")
    chunks = {c["chunk_id"]: c for c in (json.loads(x) for x in raw.splitlines() if x.strip())}
    rows = {}
    for row in jsonl(f"reports/retrieval_runs/{run_id}.jsonl"):
        rows[row["id"]] = row
    docs = {r["id"]: list(rows.get(r["id"], {}).get("documents") or []) for r in recs}
    m = metrics(recs, docs, chunks)
    unc = [r for r in recs if r["category"] == "uncovered"]
    m["uncovered_n"] = (sum(1 for r in unc if not docs[r["id"]]), len(unc))
    return m


def guardrail(run_ids: list[str]) -> tuple[list[str], float, list[str]]:
    blocked, fps, fp_cnt = [], [], []
    for r in run_ids:
        h = json.loads(read(f"reports/guardrail_{r}.json"))["layers"]["hybrid"]["all"]
        blocked.append(f"{h['blocked_block']}/{h['n_block']}")
        fps.append(h["blocked_allow"] / h["n_allow"])
        fp_cnt.append(f"{h['blocked_allow']}/{h['n_allow']}")
    return blocked, math.fsum(fps) / len(fps), fp_cnt


class Row:
    """One matrix row: printed values for the evaluated version and round 2, and its drop status."""

    def __init__(self, rid: str) -> None:
        self.rid, self.base, self.new, self.drop, self.rescued = rid, [], [], False, False

    def metric(self, base: str, new: str, higher_better: bool = True, new_noexc: str | None = None,
               base_noexc: str | None = None) -> None:
        self.base.append(base)
        self.new.append(new)
        worse = (num(new) < num(base)) if higher_better else (num(new) > num(base))
        if worse:
            if new_noexc is not None:
                b = base_noexc if base_noexc is not None else base
                still = (num(new_noexc) < num(b)) if higher_better else (num(new_noexc) > num(b))
                self.new.append(new_noexc)
                if base_noexc is not None:
                    self.new.append(base_noexc)  # the README prints the baseline without the exception next to it
                if still:
                    self.drop = True
                else:
                    self.rescued = True
            else:
                self.drop = True


def matrix_checks(tests_passed: int | None) -> None:
    g = v2_groups()
    a14, ar2 = g["all"]["14"]["metrics"], g["all"]["r2"]["metrics"]
    n14, nr2 = g["noexc"]["14"]["metrics"], g["noexc"]["r2"]["metrics"]

    def m(d: dict, k: str) -> float:
        return d[k]["mean"]

    rows: dict[str, Row] = {}

    def row(rid: str) -> Row:
        rows[rid] = Row(rid)
        return rows[rid]

    row("E2").metric(pct(m(a14, "routing_rate")), pct(m(ar2, "routing_rate")))
    row("E9").metric(pct(m(a14, "official_pass_rate")), pct(m(ar2, "official_pass_rate")),
                     new_noexc=pct(m(nr2, "official_pass_rate")), base_noexc=pct(m(n14, "official_pass_rate")))
    row("B1").metric(pct(m(a14, "escalation_rate")), pct(m(ar2, "escalation_rate")))
    r = row("B3")
    r.metric(pct(m(a14, "judge_abstention_precision")), pct(m(ar2, "judge_abstention_precision")))
    r.metric(pct(m(a14, "judge_abstention_recall")), pct(m(ar2, "judge_abstention_recall")))
    row("V2.14").metric(dec(m(a14, "judge_grounded_mean"), 2), dec(m(ar2, "judge_grounded_mean"), 2))
    row("V3.2").metric(usd(m(a14, "estimated_cost_usd")), usd(m(ar2, "estimated_cost_usd")), higher_better=False)
    r = row("V3.9")
    r.metric(pct(m(a14, "routing_rate")), pct(m(ar2, "routing_rate")))
    r.metric(pct(m(a14, "tools_rate")), pct(m(ar2, "tools_rate")))
    r = row("V3.16")
    r.metric(sec(m(a14, "latency_ms_p50")), sec(m(ar2, "latency_ms_p50")), higher_better=False)
    r.metric(sec(m(a14, "latency_ms_p95")), sec(m(ar2, "latency_ms_p95")), higher_better=False)
    r = row("V3.18")
    r.metric(pct(m(a14, "pass_rate")), pct(m(ar2, "pass_rate")), new_noexc=pct(m(nr2, "pass_rate")),
             base_noexc=None)
    r.metric(pct(m(a14, "facts_rate")), pct(m(ar2, "facts_rate")))
    r.metric(pct(m(a14, "escalation_rate")), pct(m(ar2, "escalation_rate")))
    r.metric(pct(m(a14, "language_rate")), pct(m(ar2, "language_rate")))

    # cases failing in every run
    f14, fr2 = g["all"]["14"]["failed_in_all_runs"], g["all"]["r2"]["failed_in_all_runs"]
    fr2_noexc = g["noexc"]["r2"]["failed_in_all_runs"]
    r = row("V2.13")
    r.base.append("nenhum" if not f14 else ", ".join(f14))
    r.new.append(", ".join(f"`{x}`" for x in fr2) or "nenhum")
    if len(fr2) > len(f14):
        r.drop, r.rescued = bool(fr2_noexc), not fr2_noexc
    # named cases
    s_base = case_passes("s04", G14) + case_passes("s06", G14)
    s_new = case_passes("s04", G_R2) + case_passes("s06", G_R2)
    row("V2.4").metric(f"{s_base}/6", f"{s_new}/6")
    m04_base_fail = 3 - case_passes("m04", G14)
    m04_new_pass = case_passes("m04", G_R2)
    r = row("V3.10")
    r.base.append(f"falha em {m04_base_fail} de 3")
    r.new.append(f"passa em {m04_new_pass} de 3")
    r.drop = m04_new_pass < 3 - m04_base_fail

    # holdouts and actions
    hold = [("data/eval/cases_routing_holdout.jsonl", "rh-10", "rh-12"),
            ("data/eval/cases_routing_holdout2.jsonl", "rh2-7", "rh2-9"),
            ("data/eval/cases_holdout3.jsonl", "h3-4", "h3-6"),
            ("data/eval/cases_actions.jsonl", "act-4", "act-6")]
    r = row("V3.19")
    for path, old, new in hold:
        r.metric(pct(pass_rate(path, old)[0]), pct(pass_rate(path, new)[0]))
    _, rh2_fail = pass_rate("data/eval/cases_routing_holdout2.jsonl", "rh2-9")
    _, act_fail = pass_rate("data/eval/cases_actions.jsonl", "act-6")
    r = row("V3.8")
    r.base.append("falham")
    r.new.append("passam" if not ({"n05", "n06"} & set(rh2_fail)) else "falham")
    r = row("V3.11")
    r.base.append("falha")
    r.new.append("passa" if "a05" not in act_fail else "falha")
    r.drop = "a05" in act_fail

    # retrieval (round 1 runs; baseline on the evaluated index)
    rb = retrieval("rerank-7", EVALUATED, set(), False)
    rn = retrieval("rerank-8", None, set(), True)
    rn_x = retrieval("rerank-8", None, EXCEPTIONS_RETRIEVAL, True)
    rows_e3 = row("E3")
    rows_e3.metric(dec(rb["hit@3"], 3), dec(rn["hit@3"], 3), new_noexc=dec(rn_x["hit@3"], 3))
    r = row("V2.2")
    r.metric(dec(rb["hit@1"], 3), dec(rn["hit@1"], 3), new_noexc=dec(rn_x["hit@1"], 3))
    ub, un = rb["uncovered_n"], rn["uncovered_n"]
    r.metric(f"{dec(ub[0] / ub[1], 3)} ({ub[0]}/{ub[1]})", f"{dec(un[0] / un[1], 3)} ({un[0]}/{un[1]})")
    r.metric(dec(rb["off_topic_abstain_rate"], 3), dec(rn["off_topic_abstain_rate"], 3))
    lat_b = json.loads(base_file("reports/retrieval_hybrid_phase14.json", BASE))["runs"]["rerank-7"]["rerank_latency_p50_ms"]
    lat_n = json.loads(read("reports/retrieval_hybrid_15.json"))["runs"]["rerank-8"]["rerank_latency_p50_ms"]
    row("V3.17").metric(f"{round(lat_b)} ms", f"{round(lat_n)} ms", higher_better=False)

    # guardrail
    gb_blk, gb_fp, _ = guardrail(["hybrid-1", "hybrid-2", "hybrid-3"])
    gn_blk, gn_fp, _ = guardrail(["hybrid-4", "hybrid-5", "hybrid-6"])
    ab_blk, _, ab_fp = guardrail(["author-1"])
    an_blk, _, an_fp = guardrail(["author-2", "author-3", "author-4"])
    r = row("B2")
    r.base += [gb_blk[0], pct(gb_fp), ab_blk[0], ab_fp[0]]
    r.new += [gn_blk[0], pct(gn_fp), an_blk[0], an_fp[0]]
    r.drop = (len(set(gn_blk)) > 1 or gn_blk[0].split("/")[0] != gn_blk[0].split("/")[1] or gn_fp > gb_fp
              or any(b.split("/")[0] != b.split("/")[1] for b in an_blk) or any(int(f.split("/")[0]) > 0 for f in an_fp))
    row("V2.16").metric(pct(gb_fp), pct(gn_fp), higher_better=False)

    # judge calibration, corpus, compose, tests
    cal = json.loads(read("reports/judge_calibration_2.json"))
    best = max(c["raters"]["autor"]["kappa"] for c in cal["candidates"])
    r = row("V3.1")
    r.base.append("−0,03")
    r.new.append(dec(best, 3))
    meta = json.loads(read("data/index/index_meta.json"))
    pages = [p for p in jsonl("data/corpus/pages.jsonl") if p.get("status") == "ok"]
    r = row("V3.3")
    r.base.append("103 trechos")
    r.new += [f"{len(pages)} documentos", f"{meta['n_chunks']} trechos"]
    comp = json.loads(read("reports/integration/compose-4.json"))["checks"]
    r = row("V3.20")
    r.base.append("9/9")
    r.new.append(f"{sum(map(bool, comp.values()))}/{len(comp)}")
    r.drop = not all(comp.values())
    r = row("E7")
    r.base.append("516 aprovados")
    r.new.append(f"{tests_passed} aprovados" if tests_passed else "<pytest count unavailable>")
    r.drop = not tests_passed or tests_passed < 516

    # compare with the README
    table = readme_matrix()
    problems = []
    for rid, rw in rows.items():
        cells = table.get(rid)
        if not cells:
            problems.append(f"{rid}: no README row")
            continue
        _, _, cb, cn, cs = cells
        miss_b = [v for v in rw.base if v not in cb]
        miss_n = [v for v in rw.new if v not in cn]
        status = cs.lower()
        if rw.drop:
            st_ok = "queda declarada" in status
        elif rw.rescued:
            st_ok = "exceção" in status
        else:
            st_ok = "queda" not in status
        if miss_b or miss_n or not st_ok:
            problems.append(f"{rid}: base missing {miss_b} in [{cb}]; new missing {miss_n} in [{cn}]; drop={rw.drop} "
                            f"rescued={rw.rescued} status=[{cs}]")
    check("M1.matrix_matches_records", not problems, " | ".join(problems[:8]),
          info=f"{len(rows)} numeric rows recomputed")
    blocked = sorted(rid for rid, rw in rows.items() if rw.drop and rid in CLASS_E)
    check("M2.no_class_e_drop", not blocked, f"class E rows dropped (blocks the resubmission): {blocked}")
    drops = sorted(rid for rid, rw in rows.items() if rw.drop)
    rescued = sorted(rid for rid, rw in rows.items() if rw.rescued)
    note("M1", f"drops: {drops}; drops only with the exceptions: {rescued}")
    readme = read("README.md")
    causes = readme.split("### Quedas e causas", 1)[-1].split("\n### ", 1)[0]
    undeclared = [rid for rid in drops + ["V2.5"] if f"({rid}" not in causes]
    check("M3.drops_have_causes", not undeclared, f"rows without a cause in 'Quedas e causas': {undeclared}")

    # exceptions section
    exc = readme.split("### Exceções declaradas", 1)[-1].split("\n### ", 1)[0]
    check("M4.exceptions_documented", all(s in exc for s in (
        "`off10`", "`a16`", "getnet.net/en/our-solutions/online-payments", "site.getnet.com.br/link-de-pagamento/",
        "descontinuação", "site.getnet.com.br/get-tap/", "Android 11", "Android 12")),
        "the exceptions section must give, for off10 and a16, the question, the answer, the cited pages and the labelled page")


def criteria_checks() -> None:
    """Round 2 criterion R1–R6 (§3.4) and the abstention numbers declared in the README."""
    from src.eval.metrics import evaluate_case
    readme = read("README.md")
    cases = {c["id"]: c for c in jsonl("data/eval/cases_v2.jsonl")}
    official = [c for c in cases if cases[c].get("official") and c not in EXCEPTIONS_V2]
    fails = []
    for r in G_R2:
        recs = {x["id"]: x for x in jsonl(f"reports/eval_runs/{r}.jsonl")}
        fails += [(c, r) for c in official if not evaluate_case(cases[c], recs[c])["passed"]]
    k13, m04 = case_passes("k13", G_R2), case_passes("m04", G_R2)
    _, rh2_fail = pass_rate("data/eval/cases_routing_holdout2.jsonl", "rh2-9")
    comp = json.loads(read("reports/integration/compose-4.json"))["checks"]
    crit = readme.split("**Rodada 2, atingido**", 1)[-1].split("\n\n", 2)[1] if "**Rodada 2, atingido**" in readme else ""
    shown = f"| {len(fails)} (`{fails[0][0]}`, na `{fails[0][1]}`)" if fails else "| 0 "
    ok = (len(fails) <= 1 and k13 >= 2 and m04 >= 2 and not ({"n05", "n06"} & set(rh2_fail)) and all(comp.values())
          and shown in crit and f"{min(k13, m04)} de 3" in crit)
    check("C1.round2_criterion", ok, f"official failures without off10: {fails}; k13 {k13}/3; m04 {m04}/3; rh2-9 failures "
          f"{rh2_fail}; compose-4 all={all(comp.values())}; README criterion table matches={bool(crit)}",
          info=f"R1 {len(fails)} failure(s) {fails}; R6 k13 {k13}/3, m04 {m04}/3")

    # abstention coverage without the case-runs whose answer cites a page absent from the evaluated index
    old = {json.loads(x)["doc_url"] for x in base_file("data/index/chunks.jsonl", EVALUATED).splitlines() if x.strip()}
    pos = [c for c, v in cases.items() if v["expect"].get("abstain") is True]
    tp = n = new_cases = judged_as_answer = 0
    cited_new: set[str] = set()
    per_case_new: dict[str, int] = {}
    for r in G_R2:
        recs = {x["id"]: x for x in jsonl(f"reports/eval_runs/{r}.jsonl")}
        jud = {x["id"]: x for x in jsonl(f"reports/eval_runs/{r}.judge.jsonl")}
        for c in pos:
            if recs[c].get("status") != "ok" or jud.get(c, {}).get("status") != "ok":
                continue
            srcs = recs[c]["turns"][-1].get("sources") or []
            if any(u not in old for u in srcs):
                per_case_new[c] = per_case_new.get(c, 0) + 1
                judged_as_answer += not jud[c]["abstained"]
                continue
            n += 1
            tp += bool(jud[c]["abstained"])
    cited_new = {c for c, k in per_case_new.items() if k == len(G_R2)}
    new_cases = len(cited_new)
    listed = ", ".join(f"`{c}`" for c in sorted(cited_new))
    ok = (f"{tp} de {n} ({pct(tp / n) if n else '?'})" in readme and f"({listed})" in readme
          and f"em {judged_as_answer} das {sum(per_case_new.values())} execuções" in readme)
    check("C2.abstention_without_new_pages", ok and new_cases == len(per_case_new),
          f"recomputed: {tp}/{n}; cases citing new pages in every run: {sorted(cited_new)} (any run: "
          f"{sorted(per_case_new)}); judged as answers {judged_as_answer}/{sum(per_case_new.values())}",
          info=f"{tp}/{n}; {sorted(cited_new)}")


# --------------------------------------------------------------------------------------------------- 15D re-run
def rerun_15d(tmp: str) -> int | None:
    src = base_file("scripts/verify_phase15d.py", "5ad0b92")
    if not src:
        check("P15D.previous_verifiers", False, "scripts/verify_phase15d.py not found at 5ad0b92")
        return None
    path = Path(tmp) / "verify_phase15d_from_5ad0b92.py"
    path.write_text(src, encoding="utf-8")
    env = {k: v for k, v in os.environ.items() if k not in ("GEMINI_API_KEY", "GOOGLE_API_KEY")}
    r = run([sys.executable, str(path)], env=env, timeout=7200)
    lines = r.stdout.splitlines()
    results, details = {}, {}
    for ln in lines:
        mt = re.match(r"^(PASS|FAIL) (\S+)(?: :: (.*))?$", ln)
        if mt:
            results[mt.group(2)] = mt.group(1) == "PASS"
            details[mt.group(2)] = mt.group(3) or ""
    for ln in lines:
        if ln.startswith("INFO "):
            print(ln, flush=True)
    failed = sorted(c for c, ok in results.items() if not ok and c not in SUPERSEDED_15D)
    for c in sorted(SUPERSEDED_15D & set(results)):
        note(f"P15D.{c}", "superseded by 15E (" + ("passes" if results[c] else "fails") + ")")
    check("P15D.previous_verifiers", not failed and len(results) >= 25,
          f"15D checks failing (not superseded): {failed}: " + "; ".join(details[c][:200] for c in failed[:3])
          + f"; stderr: {r.stderr[-300:]}", info=f"{sum(results.values())}/{len(results)} pass")
    mt = re.search(r"(\d+) passed", details.get("Q2.test_count", ""))
    return int(mt.group(1)) if mt and results.get("Q2.test_count") else None


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p15e_")
    static_checks()
    status_before = run(["git", "status", "--porcelain"]).stdout
    tests_passed = rerun_15d(tmp)
    guarded(["M1.matrix_matches_records", "M2.no_class_e_drop", "M3.drops_have_causes", "M4.exceptions_documented"],
            lambda: matrix_checks(tests_passed))
