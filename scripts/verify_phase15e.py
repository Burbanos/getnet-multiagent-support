def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, bool(ok)))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def note(cid: str, text: str) -> None:
    print(f"INFO {cid} :: {text}", flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n") if p.exists() else ""


def sha(rel: str) -> str:
    return hashlib.sha256(read(rel).encode("utf-8")).hexdigest()


def run(cmd: list[str], env: dict | None = None, timeout: int = 2400, cwd: Path = ROOT) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True, encoding="utf-8", errors="replace",
                          timeout=timeout)


def base_file(rel: str, rev: str = BASE) -> str:
    r = run(["git", "show", f"{rev}:{rel}"])
    return r.stdout.replace("\r\n", "\n") if r.returncode == 0 else ""


def jsonl(rel: str) -> list[dict]:
    return [json.loads(x) for x in read(rel).splitlines() if x.strip()]


def guarded(cids: list[str], fn) -> None:
    """Run a probe; if it crashes, every check it owns and has not reported yet fails (never a crashed verifier)."""
    try:
        fn()
    except (Exception, SystemExit) as exc:
        done = {c for c, _ in RESULTS}
        for cid in cids:
            if cid not in done:
                check(cid, False, f"probe raised {type(exc).__name__}: {str(exc)[:300]}")


# ------------------------------------------------------------------------------------------------------------ format
def pct(v: float) -> str:
    return f"{v * 100:.1f}".replace(".", ",") + "%"


def dec(v: float, n: int) -> str:
    return f"{v:.{n}f}".replace(".", ",")


def sec(ms: float) -> str:
    return f"{ms / 1000:.1f}".replace(".", ",") + " s"


def usd(v: float) -> str:
    return "US$ " + f"{v:.3f}".replace(".", ",")


def num(s: str) -> float:
    return float(re.sub(r"[^0-9,\-−]", "", s).replace("−", "-").replace(",", "."))


