def static_checks() -> None:
    changed_py = [p for p in run(["git", "diff", "--name-only", BASE]).stdout.split() if p.endswith(".py")]
    changed_py += [p for p in run(["git", "ls-files", "--others", "--exclude-standard"]).stdout.split() if p.endswith(".py")]
    bad = []
    for rel in sorted(set(changed_py)):
        src = read(rel)
        if not src:
            continue
        try:
            ast.parse(src, feature_version=(3, 11))
        except SyntaxError as exc:
            bad.append(f"{rel}:{exc.lineno}")
    check("A0.py311_syntax", not bad, f"not valid Python 3.11: {bad}")

    mism = {rel: sha(rel)[:12] for rel, digest in PINNED.items() if sha(rel) != digest}
    check("A1.reviewer_files", not mism and (ROOT / "scripts/verify_phase15c.py").exists(),
          f"reviewer files differ from the reviewer's copy: {mism}")

    verifiers = sorted(p.name for p in (ROOT / "scripts").glob("verify_*.py"))
    prompts = sorted(p.name for p in (ROOT / "docs/phase-prompts").glob("*.md"))
    check("A2.retired_process_files", verifiers == ["verify_phase15c.py"] and prompts == ["15C.md"],
          f"only verify_phase15c.py and 15C.md may remain: {verifiers} {prompts}")

    diff = run(["git", "diff", "--name-only", "--no-renames", BASE])
    untracked = run(["git", "ls-files", "--others", "--exclude-standard"]).stdout.split()
    changed = set(diff.stdout.split()) | set(untracked)
    extra = sorted(p for p in changed if p not in REVIEWER and p not in RETIRED and p not in ALLOWED_CODE
                   and not (p.startswith("tests/") and not base_file(p)))
    check("A3.scope", diff.returncode == 0 and not extra,
          f"15C may change only {sorted(ALLOWED_CODE)} and add new test files; also changed: {extra or diff.stderr[-200:]}")
    check("A4.index_and_corpus_unchanged", not [p for p in changed if p.startswith(("data/index/", "data/corpus/"))],
          "data/index/ and data/corpus/ must not change in 15C (the author rebuilds the index before the round)")

    ls = run(["git", "ls-tree", "-r", "--name-only", BASE, "tests"]).stdout.split()
    problems: list[str] = []
    for rel in ls:
        old, new = base_file(rel), read(rel)
        if not new:
            problems.append(f"{rel} removed")
        elif old != new:
            problems.append(f"{rel} changed")
    check("A5.existing_tests_unchanged", not problems, "; ".join(problems[:6]))

    st = read("docs/STATUS.md")
    check("S1.status", 0 < len(st.split("\n")) <= 80 and "15C" in st and "Perguntas" in st
          and "verify_phase15c" in st, f"docs/STATUS.md must be rewritten for 15C in at most 80 lines "
          f"(has {len(st.splitlines())}) with the verifier output and 'Perguntas / divergências'")

    pat = re.compile(r"(?i)\b(r2[auo]\d\d|[auo]\d\d|g\d\d|h\d\d|w\d\d|n0[5-7]|off\d\d)\b")
    gained = [rel for rel in sorted(ALLOWED_CODE - {"docs/STATUS.md"})
              if len(pat.findall(read(rel))) > len(pat.findall(base_file(rel)))]
    check("A6.no_case_ids_in_code", not gained, f"files gained eval case or query ids: {gained}")

    counts = {}
    for rel, minimum in NEW_TESTS.items():
        counts[rel] = len(re.findall(r"(?m)^\s*(?:async\s+)?def (test_\w+)", read(rel)))
    check("Q6.new_tests_written", all(counts[r] >= m for r, m in NEW_TESTS.items()), f"{counts} (minimum {NEW_TESTS})",
          info=str(counts))


