def _spec(entries: list[tuple[str, str, str, str | None]]) -> str:
    out = []
    for raw, user, role, last_day in entries:
        h = hashlib.sha256(raw.encode()).hexdigest()
        out.append(f"{h}:{user}:{role}" + (f":{last_day}" if last_day else ""))
    return ";".join(out)


