def _page(url: str, lines: list[str]) -> dict:
    text = "\n".join(lines)
    return {"url": url, "status": "ok", "title": "t", "market": "BR", "fetched_at": "2026-11-20T00:00:00+00:00",
            "sha256": hashlib.sha256(text.encode()).hexdigest(), "text": text}


