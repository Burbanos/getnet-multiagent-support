def module_checks(tmp: str) -> None:  # noqa: C901 - one scenario per check, kept linear on purpose
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp, "tickets", "tickets.db"))
    os.environ["CHECKPOINT_DB_PATH"] = str(Path(tmp, "ckpt", "checkpoints.db"))
    os.environ["GEMINI_API_KEY"] = ""
    os.environ["APP_ENV"] = "development"
    sys.path.insert(0, str(ROOT))
    try:
        from src.eval import cases as ecases
        from src.eval import compare as ecompare
        from src.eval import guardrail_eval as geval
        from src.eval import metrics as emetrics
        from src.eval.runner import load_results
        ref6a = load_ref6a()
    except Exception as exc:  # noqa: BLE001
        check("H1.guardrail_raw", False, f"{type(exc).__name__}: {exc}")
        return
    if any(not (ROOT / p).exists() for p in RAW + GENERATED):
        check("H1.guardrail_raw", False, "run records or reports missing (see H0.files_present)")
        return

    gcases = [json.loads(ln) for ln in read(GSET).splitlines() if ln.strip()]
    gids = {c["id"] for c in gcases}
    texts = [c["text"] for c in gcases if len(c["text"]) >= 16]

    # H1: guardrail run records: one per message, ids/verdicts/numbers only, from today
    problems, info = [], []
    for rid in GR_RUNS:
        rel = f"reports/guardrail_runs/{rid}.jsonl"
        raw_txt = read(rel)
        rows = jsonl(rel)
        recs = last_wins(rows)
        oks = [r for r in recs.values() if r.get("status") == "ok"]
        if set(recs) != gids:
            problems.append(f"{rid}: ids differ from the set ({len(set(recs) ^ gids)} different)")
        bad_keys = [r.get("id") for r in rows if set(r) != REC_KEYS or set(r.get("classifier") or {}) != CLS_KEYS]
        if bad_keys:
            problems.append(f"{rid}: unexpected record keys in {bad_keys[:3]}")
        if any(r.get("run_id") != rid for r in rows):
            problems.append(f"{rid}: run_id mismatch")
        if any(str(r.get("recorded_at", ""))[:10] < NOT_BEFORE for r in rows):
            problems.append(f"{rid}: records dated before {NOT_BEFORE}")
        if any(not (r["classifier"].get("model") and (r["classifier"].get("latency_ms") or 0) > 0 and r.get("usage")) for r in oks):
            problems.append(f"{rid}: ok records without model, latency or usage")
        leaked = [t[:30] for t in texts if t in raw_txt]
        if leaked:
            problems.append(f"{rid}: message text in the record file: {leaked[:2]}")
        info.append(f"{rid} ok={len(oks)}/{len(gids)} lines={len(rows)}")
    check("H1.guardrail_raw", not problems, "; ".join(problems), info="; ".join(info))

    # H2: guardrail reports are what the code computes from the records; headline rates match a reference
    try:
        problems, info, reps = [], [], []
        for rid in GR_RUNS:
            recs = load_results(ROOT / f"reports/guardrail_runs/{rid}.jsonl")
            committed = json.loads(read(f"reports/guardrail_{rid}.json"))
            reps.append(committed)
            fresh = geval.guardrail_report(geval.load_guardrail_set(ROOT / GSET), recs, rid, set_path=GSET)
            if no_time(fresh) != no_time(committed):
                diff_keys = [k for k in fresh if no_time(fresh.get(k)) != no_time(committed.get(k))]
                problems.append(f"{rid}: committed report differs from the records in {diff_keys}")
            blocked = {}
            for c in gcases:
                r = recs.get(c["id"], {})
                pat = r.get("pattern_category") is not None
                cls = r.get("status") == "ok" and (r.get("classifier") or {}).get("verdict") == "block"
                blocked[c["id"]] = pat or cls
            nb = [c for c in gcases if c["label"] == "block"]
            na = [c for c in gcases if c["label"] == "allow"]
            br = sum(blocked[c["id"]] for c in nb) / len(nb)
            fp = sum(blocked[c["id"]] for c in na) / len(na)
            h = committed["layers"]["hybrid"]["all"]
            if abs((h.get("block_rate") or -1) - br) > 1e-9 or abs((h.get("false_positive_rate") or -1) - fp) > 1e-9:
                problems.append(f"{rid}: hybrid rates {h.get('block_rate')}/{h.get('false_positive_rate')} != reference {br:.4f}/{fp:.4f}")
            pat_now = {c["id"]: c for c in committed["cases"]}
            drift = [cid for cid, r in recs.items() if (r.get("pattern_category")) != pat_now.get(cid, {}).get("pattern_category")]
            if drift:
                problems.append(f"{rid}: pattern layer at run time differs from now for {drift[:3]}")
            if f"{rid}" not in read(f"reports/guardrail_{rid}.md"):
                problems.append(f"{rid}: markdown report does not name the run")
            info.append(f"{rid} block={br:.3f} fp={fp:.3f} targets_met={committed.get('targets_met')} "
                        f"p50={committed['latency_ms'].get('p50')}ms cost={committed.get('cost_usd_mean_per_message')}")
        summ = json.loads(read("reports/guardrail_summary.json"))
        fresh_s = geval.guardrail_summary(reps)
        if no_time(fresh_s) != no_time(summ) or summ.get("n_runs") != 3:
            problems.append("guardrail_summary.json differs from the three committed reports")
        check("H2.guardrail_reports", not problems, "; ".join(problems), info="; ".join(info))
    except Exception as exc:  # noqa: BLE001
        check("H2.guardrail_reports", False, f"{type(exc).__name__}: {exc}")

    # H3: v2 run records: complete shape, model answers, judge different from the answer model
    v2 = ecases.load_cases(ROOT / V2)
    v2ids = {c["id"] for c in v2}
    by_id = {c["id"]: c for c in v2}
    problems, info = [], []
    answer_models, judge_models = set(), set()
    results: dict[str, list[dict]] = {}
    judgments: dict[str, list[dict]] = {}
    for rid in V2_RUNS:
        recs = last_wins(jsonl(f"reports/eval_runs/{rid}.jsonl"))
        js = last_wins(jsonl(f"reports/eval_runs/{rid}.judge.jsonl"))
        results[rid], judgments[rid] = list(recs.values()), list(js.values())
        if set(recs) != v2ids:
            problems.append(f"{rid}: ids differ from cases_v2 ({len(set(recs) ^ v2ids)} different)")
        bad = [cid for cid, r in recs.items() if r.get("status") == "ok" and (
            not r.get("turns") or len(r["turns"]) != len(by_id.get(cid, {}).get("turns", []))
            or any(set(t) != TURN_KEYS for t in r["turns"]))]
        if bad:
            problems.append(f"{rid}: records with wrong turns or turn keys: {bad[:3]}")
        models = {t["llm_model"] for r in recs.values() for t in r.get("turns", []) if t.get("llm_model")}
        answer_models |= models
        if not models:
            problems.append(f"{rid}: no answer model recorded")
        jm = {j.get("judge_model") for j in js.values() if j.get("status") == "ok"}
        judge_models |= jm
        if set(js) - set(recs):
            problems.append(f"{rid}: judgments for ids that are not in the run")
        n_ok = sum(r.get("status") == "ok" for r in recs.values())
        info.append(f"{rid} ok={n_ok}/78 judged={sum(j.get('status') == 'ok' for j in js.values())}")
    if not judge_models or judge_models & answer_models:
        problems.append(f"judge models {sorted(judge_models)} must be set and differ from answer models {sorted(answer_models)}")
    check("H3.v2_raw", not problems, "; ".join(problems),
          info="; ".join(info) + f"; answers={sorted(answer_models)} judge={sorted(judge_models)}")

    # H4: the API results in the records come from the real APIs
    usd, jpy = fixture_closing("ptax_usd_20261106"), fixture_closing("ptax_jpy_20261106")
    problems, seen = [], {"weather_success": 0, "fx_success": 0, "d04": 0, "d05": 0}
    for rid in V2_RUNS:
        for r in results[rid]:
            for t in r.get("turns", []):
                for a in t.get("api_results") or []:
                    url = a.get("source_url")
                    if url and urlparse(url).hostname not in API_HOSTS:
                        problems.append(f"{rid}/{r['id']}: source_url host {urlparse(url).hostname}")
                    if a.get("status") == "success":
                        if a.get("tool") == "get_weather_forecast":
                            seen["weather_success"] += 1
                        elif a.get("tool") == "get_exchange_rate":
                            seen["fx_success"] += 1
                            pair = ((a.get("buy") or {}).get("value"), (a.get("sell") or {}).get("value"))
                            if a.get("currency") == "USD" and a.get("reference_date") == "2026-11-06":
                                seen["d04"] += 1
                                if pair != usd:
                                    problems.append(f"{rid}/{r['id']}: USD 2026-11-06 = {pair}, captured API says {usd}")
                            if a.get("currency") == "JPY" and a.get("reference_date") == "2026-11-06":
                                seen["d05"] += 1
                                if pair != jpy:
                                    problems.append(f"{rid}/{r['id']}: JPY 2026-11-06 = {pair}, captured API says {jpy}")
    if not (seen["weather_success"] and seen["fx_success"]):
        problems.append(f"no successful weather or exchange-rate call in any run: {seen}")
    check("H4.api_provenance", not problems, "; ".join(problems[:4]), info=f"{seen}")

    # H5: v2 reports are what the code computes; pass rates match the reviewer's reference
    try:
        problems, info = [], []
        for rid in V2_RUNS:
            committed = json.loads(read(f"reports/eval_{rid}.json"))
            agg = emetrics.aggregate(v2, results[rid], judgments=judgments[rid])
            if no_time({k: committed.get(k) for k in agg}) != no_time(agg):
                problems.append(f"{rid}: committed report differs from the records in "
                                f"{[k for k in agg if no_time(agg[k]) != no_time(committed.get(k))]}")
            if committed.get("cases_sha256") != V2_SHA or committed.get("cases_file") != V2 or committed.get("run_id") != rid:
                problems.append(f"{rid}: report not built from {V2} (sha={str(committed.get('cases_sha256'))[:12]}, "
                                f"file={committed.get('cases_file')})")
            byr = {r["id"]: r for r in results[rid]}
            evs = [ref_eval_v2(ref6a, c, byr[c["id"]]) for c in v2 if byr.get(c["id"], {}).get("status") == "ok"]
            ref_pass = sum(e["passed"] for e in evs) / len(evs) if evs else None
            got = committed.get("metrics", {}).get("pass_rate")
            if ref_pass is None or got is None or abs(ref_pass - got) > 1e-9:
                problems.append(f"{rid}: pass_rate {got} != reference {ref_pass}")
            info.append(f"{rid} pass={got}")
        cmp_doc = json.loads(read("reports/eval_v2.json"))
        fresh = ecompare.compare_runs(v2, [("flash-lite", [(rid, results[rid], judgments[rid]) for rid in V2_RUNS])])
        if no_time({k: cmp_doc.get(k) for k in fresh}) != no_time(fresh):
            problems.append("reports/eval_v2.json differs from the three runs")
        check("H5.v2_reports", not problems, "; ".join(problems), info="; ".join(info))
    except Exception as exc:  # noqa: BLE001
        check("H5.v2_reports", False, f"{type(exc).__name__}: {exc}")

    # H6: re-check of 7A L2.no_pii_in_logs with markers that a timestamp cannot contain
    l2_strict(tmp)


