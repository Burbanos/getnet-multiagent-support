def jsonl(rel: str) -> list[dict]:
    rows = []
    for ln in read(rel).splitlines():
        if ln.strip():
            rows.append(json.loads(ln))
    return rows


def last_wins(rows: list[dict]) -> dict[str, dict]:
    return {r["id"]: r for r in rows if r.get("id")}


def no_time(d: Any) -> Any:
    if isinstance(d, dict):
        return {k: no_time(v) for k, v in d.items() if k != "generated_at"}
    if isinstance(d, list):
        return [no_time(x) for x in d]
    return d


