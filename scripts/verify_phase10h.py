def ref_eval_v2(ref6a: Any, case: dict, result: dict) -> dict:
    """6A reference plus the 10G rule: tools_ok also needs every expected API status."""
    plain = json.loads(json.dumps(case))
    api_status = plain["expect"].pop("api_status", None)
    ev = ref6a.ref_eval(plain, result)
    if api_status and ev["checks"]["tools_ok"] is not None:
        api = (result["turns"][-1].get("api_results") or []) if result.get("turns") else []
        ok = ev["checks"]["tools_ok"] and all(any(a.get("tool") == t and a.get("status") == s for a in api)
                                              for t, s in api_status.items())
        ev["checks"]["tools_ok"] = ok
        ev["passed"] = all(v for v in ev["checks"].values() if v is not None)
    return ev


