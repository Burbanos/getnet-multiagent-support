def wilson(k: int, n: int) -> tuple[float | None, float | None]:
    if n == 0:
        return None, None
    p = k / n
    d = 1 + Z * Z / n
    c = (p + Z * Z / (2 * n)) / d
    h = Z * math.sqrt(p * (1 - p) / n + Z * Z / (4 * n * n)) / d
    return c - h, c + h


def ref_compare(pairs: list[tuple[str, str, object, object]]) -> dict:
    used = [(h, c, a, b) for h, c, a, b in pairs if b is not None]
    n = len(used)
    agree = sum(1 for _, _, a, b in used if a == b)
    lo, hi = wilson(agree, n)
    kappa = None
    if n:
        po = agree / n
        cats = {a for _, _, a, _ in used} | {b for _, _, _, b in used}
        pe = math.fsum((sum(1 for _, _, a, _ in used if a == c) / n) * (sum(1 for _, _, _, b in used if b == c) / n) for c in cats)
        kappa = None if pe == 1 else (po - pe) / (1 - pe)
    return {"n": n, "agree": agree, "rate": agree / n if n else None, "wilson_low": lo, "wilson_high": hi, "kappa": kappa,
            "disagreements": [{"hid": h, "case_id": c, "human": a, "other": b} for h, c, a, b in used if a != b]}


def ref_agreement(sample: dict, answers: dict, cases: dict, results: dict, judgments: dict, evaluate_case) -> dict:
    items = sample["items"]
    rows = {k: [] for k in COMP_KEYS}
    g_pairs, passed = [], 0
    for it in items:
        h, cid = it["hid"], it["case_id"]
        case, res, jd, a = cases[cid], results[cid], judgments[cid], answers[h]
        ok = bool(evaluate_case(case, res)["passed"])
        passed += ok
        rows["route_vs_label"].append((h, cid, a["rota"], ref_route(case)))
        rows["abstain_vs_label"].append((h, cid, a["deveria_abster"], case["expect"].get("abstain")))
        rows["acceptable_vs_checks"].append((h, cid, a["aceitavel"], ok))
        rows["acceptable_vs_judge"].append((h, cid, a["aceitavel"], jd["grounded"] >= 4 and jd["answers_question"] >= 4))
        rows["abstained_vs_judge"].append((h, cid, a["absteve"], jd["abstained"]))
        g_pairs.append({"hid": h, "case_id": cid, "human": a["fundamentacao"], "judge": jd["grounded"]})
    n = len(items)
    exact = sum(1 for p in g_pairs if p["human"] == p["judge"])
    within = sum(1 for p in g_pairs if abs(p["human"] - p["judge"]) <= 1)
    return {
        "n_items": n,
        "comparisons": {k: ref_compare(rows[k]) for k in COMP_KEYS},
        "grounded_vs_judge": {"n": n, "exact": exact, "exact_rate": exact / n, "within_one": within, "within_one_rate": within / n,
                              "human_mean": math.fsum(p["human"] for p in g_pairs) / n,
                              "judge_mean": math.fsum(p["judge"] for p in g_pairs) / n,
                              "human_lower": sum(1 for p in g_pairs if p["human"] < p["judge"]),
                              "human_higher": sum(1 for p in g_pairs if p["human"] > p["judge"]), "pairs": g_pairs},
        "pass_rate_checks": passed / n,
        "acceptable_rate_human": sum(1 for it in items if answers[it["hid"]]["aceitavel"]) / n,
    }


def same(a, b, path: str = "") -> list[str]:
    """Deep comparison with 1e-9 tolerance for floats; returns the differing paths."""
    if isinstance(a, bool) or isinstance(b, bool):
        return [] if a is b or (isinstance(a, bool) and isinstance(b, bool) and a == b) else [path]
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return [] if math.isclose(a, b, rel_tol=0, abs_tol=1e-9) else [path]
    if isinstance(a, dict) and isinstance(b, dict):
        if list(a) != list(b):
            return [f"{path} keys {list(a)} != {list(b)}"]
        return [d for k in a for d in same(a[k], b[k], f"{path}.{k}")]
    if isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            return [f"{path} len {len(a)} != {len(b)}"]
        return [d for i, (x, y) in enumerate(zip(a, b)) for d in same(x, y, f"{path}[{i}]")]
    return [] if a == b else [path]


def omit_session(obj):
    if isinstance(obj, dict):
        return {k: ("omitido" if k == "session_id" else omit_session(v)) for k, v in obj.items()}
    if isinstance(obj, list):
        return [omit_session(v) for v in obj]
    return obj


def csv_text(answers: dict, hids: list[str], sep: str = ";", yn=("S", "N")) -> str:
    out = [sep.join(FIELDS)]
    for h in hids:
        a = answers[h]
        out.append(sep.join([h, a["rota"], *(yn[0] if a[k] else yn[1] for k in ("deveria_abster", "aceitavel", "absteve")),
                             str(a["fundamentacao"])]))
    return "\n".join(out) + "\n"


