def ref_allocate(counts: dict[str, int], size: int) -> dict[str, int]:
    n = sum(counts.values())
    base = {c: size * k // n for c, k in counts.items()}
    rem = {c: size * k - base[c] * n for c, k in counts.items()}
    for c in sorted(counts, key=lambda c: (-rem[c], c))[: size - sum(base.values())]:
        base[c] += 1
    return {c: base[c] for c in sorted(counts)}


