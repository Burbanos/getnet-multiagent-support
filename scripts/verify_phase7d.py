def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


TURN_KEYS = {"message", "response", "agents_used", "tools_used", "sources", "retrieved_docs", "web_results", "tool_results",
             "ticket_id", "ticket_priority", "is_safe", "handoff", "llm_model", "tokens", "latency_ms"}


def words(text: str, vocab: set[str]) -> int:
    strip = ".,;:!?()[]{}\"'*`/-"
    return sum(1 for w in text.lower().split() if w.strip(strip) in vocab)


def static_checks() -> None:
    readme = read("README.md")
    check("W0.readme", all(w in readme for w in ("web_results", "internal_error")),
          "README must document web_results (recorded search results, seen by the judge) and the internal_error flag")


def main_checks(tmp: str) -> None:
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["CHECKPOINT_DB_PATH"] = str(Path(tmp) / "checkpoints.db")
    os.environ["GEMINI_API_KEY"] = ""
    os.environ.pop("API_KEYS", None)
    os.environ["APP_ENV"] = "development"
    sys.path.insert(0, str(ROOT))
    try:
        from types import SimpleNamespace
        from typing import Any
        from unittest.mock import patch

        from langchain_core.messages import AIMessage
        from langchain_core.outputs import ChatGeneration, ChatResult
        from pydantic import Field

        import src.core.graph as graph_mod
        import src.core.tickets_db as tdb
        import src.tools.agent_tools as agent_tools
        from src.eval import cases as ecases
        from src.eval import checks as echecks
        from src.eval import judge as ejudge
        from src.eval import runner as erunner
        from tests.fakes import ScriptedChatModel
    except Exception as exc:  # noqa: BLE001
        check("W1.imports", False, f"{type(exc).__name__}: {exc}")
        return

    class StepFake(ScriptedChatModel):
        responses: list[Any] = Field(default_factory=list)

        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            self.received.append(list(messages))
            return ChatResult(generations=[ChatGeneration(message=self.responses.pop(0))])

    def call(name: str, args: dict, cid: str) -> AIMessage:
        return AIMessage(content="", tool_calls=[{"name": name, "args": args, "id": cid}])

    canned = {"status": "success", "query": "q", "count": 2, "results": [
        {"title": "Previsão Porto Alegre", "snippet": "Amanhã: 15 a 22 graus, chuva. " + "x" * 900, "url": "https://weather.example/poa"},
        {"title": "Outro", "snippet": "Segundo resultado", "url": "https://weather.example/2"}]}
    try:
        with patch.object(agent_tools, "web_search_tool", lambda query, max_results=3: canned):
            fake = StepFake(responses=[call("ask_knowledge_agent", {"question": "weather in Porto Alegre tomorrow"}, "w1"),
                                       call("search_web", {"query": "previsão Porto Alegre amanhã"}, "w2"),
                                       AIMessage(content="15 to 22 degrees, rain."), AIMessage(content="Tomorrow: 15 to 22 °C, rain.")])
            st = graph_mod.OrchestrationGraph(chat_model=fake).run_sync(user_id="cliente1988", message="Weather tomorrow?", session_id="w-1")
        wr = getattr(st, "web_results", None) or []
        check("W1.state_web_results", len(wr) == 2 and wr[0].get("url") == "https://weather.example/poa"
              and wr[0].get("title") == "Previsão Porto Alegre" and wr[0].get("snippet", "").startswith("Amanhã: 15 a 22")
              and set(wr[0]) == {"url", "title", "snippet"}, f"web_results={wr!r:.200}")
        t = erunner.observe_turn(st, "Weather tomorrow?", 1.0)
        w0 = (t.get("web_results") or [{}])[0]
        check("W2.observe_turn", set(t) == TURN_KEYS and set(w0) == {"url", "title", "snippet"} and len(w0.get("snippet", "")) == 600,
              f"keys={sorted(t)}, web keys={sorted(w0)}, snippet len={len(w0.get('snippet', ''))}")
        big = SimpleNamespace(**{**vars(st), "retrieved_docs": [{"url": "u", "chunk_id": None, "score": None, "text": "Z" * 5000}]})
        check("W2.docs_cap_kept", len(erunner.observe_turn(big, "m", 1.0)["retrieved_docs"][0]["text"]) == 2000,
              "observe_turn must still keep up to 2000 characters per passage (6D)")
        cases = {c["id"]: c for c in ecases.load_cases(ROOT / "data/eval/cases.jsonl")}
        payload = json.loads(ejudge.build_judge_input(cases["off02"], {"id": "off02", "status": "ok", "turns": [t]}))
        texts = [p.get("text", "") for p in payload.get("passages", [])]
        check("W3.judge_sees_web", any(p.get("url") == "https://weather.example/poa" for p in payload.get("passages", []))
              and any("Amanhã: 15 a 22" in x and "Previsão Porto Alegre" in x for x in texts)
              and all(set(p) == {"url", "text"} for p in payload.get("passages", [])) and "off02" not in json.dumps(payload),
              f"passages={[(p.get('url'), p.get('text', '')[:40]) for p in payload.get('passages', [])]}")
    except Exception as exc:  # noqa: BLE001
        check("W1.state_web_results", False, f"{type(exc).__name__}: {exc}")

    # internal failure -> flagged, bilingual message, eval error (not a wrong answer)
    try:
        orch = graph_mod.OrchestrationGraph(chat_model=StepFake(responses=[]))

        def boom(*a, **k):
            raise RuntimeError("SECRET-INTERNAL-DETAIL")
        orch.graph.invoke = boom
        st = orch.run_sync(user_id="cliente1988", message="oi", session_id="e-1")
        msg = st.agent_response or ""
        check("E1.error_flag", getattr(st, "error", None) == "internal_error" and "SECRET-INTERNAL-DETAIL" not in msg
              and words(msg, echecks.PT_WORDS) >= 2 and words(msg, echecks.EN_WORDS) >= 2,
              f"error={getattr(st, 'error', None)!r}, response={msg!r}")

        class Orch:
            def run_sync(self, user_id, message, session_id, trace_id=None):
                return orch.run_sync(user_id=user_id, message=message, session_id=session_id)
        res = erunner.run_case(cases["k01"], Orch(), "E")
        check("E2.eval_counts_error", res.get("status") == "error" and res.get("error_type") == "internal_error",
              f"run_case on an internal failure: status={res.get('status')}, error_type={res.get('error_type')}")
        ok = graph_mod.OrchestrationGraph(chat_model=StepFake(responses=[AIMessage(content="Olá!")])).run_sync(
            user_id="cliente1988", message="oi", session_id="e-2")
        check("E3.no_flag_when_ok", getattr(ok, "error", "missing") is None, f"error={getattr(ok, 'error', 'missing')!r}")
    except Exception as exc:  # noqa: BLE001
        check("E1.error_flag", False, f"{type(exc).__name__}: {exc}")

    # fixed messages bilingual
    try:
        consts = {n: getattr(graph_mod, n, "") for n in ("INSTABILITY_MESSAGE", "FORCED_ESCALATION_MESSAGE", "FORCED_ESCALATION_FAILED_MESSAGE")}
        bad = [n for n, v in consts.items() if not isinstance(v, str) or words(v, echecks.PT_WORDS) < 2 or words(v, echecks.EN_WORDS) < 2]
        check("L1.fixed_messages_bilingual", not bad and "{ticket_id}" in consts["FORCED_ESCALATION_MESSAGE"]
              and "Não consegui concluir sua solicitação automaticamente." in consts["FORCED_ESCALATION_MESSAGE"],
              f"constants missing or not bilingual (PT and EN): {bad}")
        tdb.reset_tickets_repository()
        loop = [call("ask_support_agent", {"request": "x"}, f"s{i}") for i in range(20)]
        fake = StepFake(responses=[x for c in loop for x in (c, AIMessage(content="spec"))])
        st = graph_mod.OrchestrationGraph(chat_model=fake).run_sync(user_id="cliente1988", message="loop", session_id="f-1")
        tid = st.escalation_ticket_id or ""
        check("L2.forced_escalation_uses_constant", tid and st.agent_response == consts["FORCED_ESCALATION_MESSAGE"].format(ticket_id=tid),
              f"response={st.agent_response!r:.160}, ticket={tid!r}")
    except Exception as exc:  # noqa: BLE001
        check("L1.fixed_messages_bilingual", False, f"{type(exc).__name__}: {exc}")
    finally:
        tdb.reset_tickets_repository()


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks(tmp: str) -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    tests = read("tests/test_web_and_errors.py")
    n_tests = len(re.findall(r"^def test_", tests, flags=re.M))
    check("Q0.web_error_tests", n_tests >= 4, f"tests/test_web_and_errors.py has {n_tests} tests (need >= 4)")
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH",
                         "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1", CHECKPOINT_DB_PATH=str(Path(tmp) / "nested" / "checkpoints.db"))
    for script, allowed in PRIOR.items():
        env_s = {k: v for k, v in nested.items() if k != "CHECKPOINT_DB_PATH"} if script == "verify_phase4b.py" else nested
        r = run([sys.executable, f"scripts/{script}"], env=env_s)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    marks = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in ("data/tickets.db", "data/checkpoints.db")}
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "warning" not in last, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")
    after = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in marks}
    check("Q4.tests_do_not_touch_data_dbs", marks == after, f"the test suite wrote {[p for p in marks if marks[p] != after[p]]}")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p7d_")
    static_checks()
    main_checks(tmp)
    suite_checks(tmp)
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
