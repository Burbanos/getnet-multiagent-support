if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


NAMES = ["getnet_requests_total", "getnet_request_latency_seconds", "getnet_tool_calls_total", "getnet_escalations_total",
         "getnet_abstentions_total", "getnet_llm_tokens_total"]


def sample(text: str, name: str, labels: str = "") -> float | None:
    key = f"{name}{{{labels}}}" if labels else name
    for ln in text.splitlines():
        if ln.startswith(key + " "):
            return float(ln.split()[-1])
    return None


def static_checks() -> None:
    main = read("src/main.py")
    bad = [w for w in ("LLM misconfigured", "LLM not configured", "LLM provider unavailable")
           if re.search(r"logger\.exception\([^\n]*" + re.escape(w), main)]
    check("M0.llm_error_logs_no_traceback", not bad, f"use logger.error (class name only, no traceback) for: {bad}")
    req = read("requirements.txt").lower() + read("requirements-dev.txt").lower()
    check("M0.no_new_dependency", "prometheus" not in req, "no new dependency: write the exposition format by hand")
    readme = read("README.md")
    check("M0.readme", "/metrics" in readme and all(n in readme for n in NAMES),
          f"README must document /metrics and every metric name: {[n for n in NAMES if n not in readme]}")


def main_checks(tmp: str) -> None:
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["CHECKPOINT_DB_PATH"] = str(Path(tmp) / "checkpoints.db")
    os.environ["GEMINI_API_KEY"] = ""
    os.environ.pop("API_KEYS", None)
    os.environ["APP_ENV"] = "development"
    sys.path.insert(0, str(ROOT))
    try:
        from typing import Any

        from langchain_core.messages import AIMessage
        from langchain_core.outputs import ChatGeneration, ChatResult
        from pydantic import Field

        import src.core.tickets_db as tdb
        from src.core import metrics
        from src.core.graph import OrchestrationGraph
        from tests.fakes import ScriptedChatModel
    except Exception as exc:  # noqa: BLE001
        check("M1.imports", False, f"{type(exc).__name__}: {exc}")
        return
    need = [n for n in ("reset", "render", "inc_request", "inc_tool", "inc_escalation", "inc_abstention", "add_tokens")
            if not callable(getattr(metrics, n, None))]
    check("M1.api", not need, f"src/core/metrics.py is missing {need}")
    if need:
        return
    metrics.reset()
    txt = metrics.render()
    typed = all(f"# TYPE {n} " in txt and f"# HELP {n} " in txt for n in NAMES)
    check("M1.format", typed and "# TYPE getnet_request_latency_seconds histogram" in txt and sample(txt, "getnet_escalations_total") == 0
          and 'getnet_request_latency_seconds_bucket{le="+Inf"} 0' in txt, f"render() after reset:\n{txt[:400]}")
    metrics.inc_request(200, 0.7)
    metrics.inc_request(503, 3.0)
    metrics.inc_tool("made_up_tool_xyz", "ok")
    txt = metrics.render()
    check("M1.histogram_and_labels", sample(txt, "getnet_requests_total", 'status="200"') == 1 and sample(txt, "getnet_requests_total", 'status="503"') == 1
          and sample(txt, "getnet_request_latency_seconds_bucket", 'le="1.0"') == 1 and sample(txt, "getnet_request_latency_seconds_bucket", 'le="5.0"') == 2
          and sample(txt, "getnet_request_latency_seconds_count") == 2 and abs((sample(txt, "getnet_request_latency_seconds_sum") or 0) - 3.7) < 1e-9
          and "made_up_tool_xyz" not in txt and sample(txt, "getnet_tool_calls_total", 'tool="unknown",status="ok"') == 1,
          "requests by status, cumulative buckets (le=1.0 -> 1, le=5.0 -> 2), sum/count, unknown tool names folded into tool=\"unknown\"")

    class StepFake(ScriptedChatModel):
        responses: list[Any] = Field(default_factory=list)

        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            self.received.append(list(messages))
            return ChatResult(generations=[ChatGeneration(message=self.responses.pop(0))])

    def call(name: str, args: dict, cid: str) -> AIMessage:
        return AIMessage(content="", tool_calls=[{"name": name, "args": args, "id": cid}])

    usage = {"input_tokens": 100, "output_tokens": 20, "total_tokens": 120}
    try:
        metrics.reset()
        tdb.reset_tickets_repository()
        fake = StepFake(responses=[call("ask_support_agent", {"request": "settlement"}, "a1"), call("get_settlement_status", {}, "a2"),
                                   AIMessage(content="SPEC"), call("escalate_to_human", {"reason": "human", "priority": "standard"}, "a3"),
                                   AIMessage(content="FINAL", usage_metadata=usage)])
        OrchestrationGraph(chat_model=fake).run_sync(user_id="cliente1988", message="quando recebo?", session_id="m2")
        fake = StepFake(responses=[call("ask_knowledge_agent", {"question": "Shopify?"}, "b1"), AIMessage(content="not found"),
                                   AIMessage(content="Not in the official sources.")])
        OrchestrationGraph(chat_model=fake).run_sync(user_id="cliente1988", message="Shopify?", session_id="m3")
        txt = metrics.render()
        dir_in = 'direction="input"'  # Phase 9A: Python 3.11 forbids backslashes and reused quotes in f-string expressions
        got = {t: sample(txt, "getnet_tool_calls_total", f'tool="{t}",status="ok"') for t in
               ("ask_support_agent", "get_settlement_status", "escalate_to_human", "ask_knowledge_agent")}
        check("M2.graph_counters", all(v == 1 for v in got.values()) and sample(txt, "getnet_escalations_total") == 1
              and sample(txt, "getnet_abstentions_total") == 1 and (sample(txt, "getnet_llm_tokens_total", 'direction="input"') or 0) >= 100,
              f"tools={got}, escalations={sample(txt, 'getnet_escalations_total')}, abstentions={sample(txt, 'getnet_abstentions_total')}, "
              f"tokens_in={sample(txt, 'getnet_llm_tokens_total', dir_in)}")
    except Exception as exc:  # noqa: BLE001
        check("M2.graph_counters", False, f"{type(exc).__name__}: {exc}")
    finally:
        tdb.reset_tickets_repository()

    try:
        from fastapi.testclient import TestClient

        from src.main import app
        metrics.reset()
        with TestClient(app) as client:
            r1 = client.post("/chat", json={"message": "oi", "session_id": "m4"}, headers={"X-API-Key": "getnet-dev-key"})
            r2 = client.post("/chat", json={"message": "oi"})
            client.get("/health")
            m = client.get("/metrics")
        txt = m.text
        check("M3.endpoint", m.status_code == 200 and m.headers.get("content-type", "").startswith("text/plain")
              and "version=0.0.4" in m.headers.get("content-type", "")
              and sample(txt, "getnet_requests_total", f'status="{r1.status_code}"') == 1
              and sample(txt, "getnet_requests_total", f'status="{r2.status_code}"') == 1
              and sample(txt, "getnet_request_latency_seconds_count") == 2 and "cliente1988" not in txt,
              f"/metrics {m.status_code} {m.headers.get('content-type')}; chat statuses {r1.status_code}, {r2.status_code}; /health must not count")
    except Exception as exc:  # noqa: BLE001
        check("M3.endpoint", False, f"{type(exc).__name__}: {exc}")


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks(tmp: str) -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    tests = read("tests/test_metrics.py")
    n_tests = len(re.findall(r"^def test_", tests, flags=re.M))
    check("Q0.metrics_tests", n_tests >= 4, f"tests/test_metrics.py has {n_tests} tests (need >= 4)")
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH",
                         "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1", CHECKPOINT_DB_PATH=str(Path(tmp) / "nested" / "checkpoints.db"))
    for script, allowed in PRIOR.items():
        env_s = {k: v for k, v in nested.items() if k != "CHECKPOINT_DB_PATH"} if script == "verify_phase4b.py" else nested
        r = run([sys.executable, f"scripts/{script}"], env=env_s)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    marks = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in ("data/tickets.db", "data/checkpoints.db")}
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "warning" not in last, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")
    after = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in marks}
    check("Q4.tests_do_not_touch_data_dbs", marks == after, f"the test suite wrote {[p for p in marks if marks[p] != after[p]]}")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p7c_")
    static_checks()
    main_checks(tmp)
    suite_checks(tmp)
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
