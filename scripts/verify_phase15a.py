          f"candidates={len(cands)} autor={ {k: ra.get(k) for k in ('agreement', 'kappa', 'ac1')} } (want κ {exp_a}) "
          f"anotador={ {k: rb.get(k) for k in ('agreement', 'kappa', 'ac1')} } (want κ {exp_b:.4f}, AC1 {exp_ac1_b:.4f}) "
