def _drop_functions(src: str, names: set[str]) -> str:
    """Remove the top-level functions `names` (def line up to the next top-level statement) from a module's source."""
    out, skip = [], False
    for line in src.split("\n"):
        m = re.match(r"(?:async\s+)?def (\w+)\(", line)
        if m:
            skip = m.group(1) in names
        elif line and not line[0].isspace() and not line.startswith(("#", ")", "]", "}")):
            skip = False
        if not skip:
            out.append(line)
    return "\n".join(out)


def guarded(cid: str, fn) -> None:
    try:
        fn()
    except Exception as exc:  # a crash in a probe is a failed check, never a crashed verifier
        check(cid, False, f"probe raised {type(exc).__name__}: {str(exc)[:300]}")


class Settings:
    """Temporarily set attributes of src.config.settings."""

    def __init__(self, **kw) -> None:
        self.kw, self.old = kw, {}

    def __enter__(self):
        from src.config import settings
        for k, v in self.kw.items():
            self.old[k] = getattr(settings, k)
            setattr(settings, k, v)
        return settings

    def __exit__(self, *exc):
        from src.config import settings
        for k, v in self.old.items():
            setattr(settings, k, v)


