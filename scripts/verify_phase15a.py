def supervisor_calls(chat) -> list[str]:
    """System prompts of the supervisor calls recorded by a shared scripted model, in order."""
    out = []
    for msgs in chat.received:
        sysm = msg_text(msgs[0]) if msgs else ""
        if SUPERVISOR_HEAD in sysm:
            out.append(sysm)
    return out


