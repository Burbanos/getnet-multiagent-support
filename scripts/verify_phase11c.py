    texts = [json.loads(ln)["text"] for ln in read(HOLDOUT).splitlines() if ln.strip()]
    leaked = [t[:30] for t in texts if t in status]
    check("S2.status_without_messages", not leaked, f"STATUS must not quote the holdout messages: {leaked}")
    diff = run(["git", "diff", "--name-only", "--no-renames", BASE])
