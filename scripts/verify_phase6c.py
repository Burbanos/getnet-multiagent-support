def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def model_name(m) -> str:
    return str(getattr(m, "model", "") or "").split("/")[-1]


def fake_state(i: int = 0, **kw):
    base = dict(agent_response=f"resposta {i}", agents_used=["SupervisorAgent", "KnowledgeAgent"], tools_used=["search_knowledge_base"],
                sources=["https://site.getnet.com.br/crediario/"], retrieved_docs=[{"url": "https://site.getnet.com.br/crediario/",
                "chunk_id": "c1", "score": 0.8, "text": "texto", "title": "x", "market": "BR", "fetched_at": "2026"}],
                tool_results=[{"agent": "KnowledgeAgent", "answer": "48x"}], escalation_ticket_id=None, ticket=None, is_safe=True,
                handoff=None, llm_model="fake-model", tokens={"input_tokens": 3, "output_tokens": 2, "total_tokens": 5})
    base.update(kw)
    return SimpleNamespace(**base)


class ProviderError(Exception):
    """Mimics google.genai.errors.ServerError: carries an int `code`."""

    def __init__(self, code: int, msg: str):
        super().__init__(f"{code} {msg}")
        self.code = code


class WrapperError(Exception):
    """Mimics langchain_google_genai.GoogleAPIError raised `from` the provider error."""


def main_checks(tmp: str) -> None:
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["CHECKPOINT_DB_PATH"] = str(Path(tmp) / "checkpoints.db")
    os.environ["GEMINI_API_KEY"] = ""
    for k in ("LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER"):
        os.environ.pop(k, None)
    sys.path.insert(0, str(ROOT))
    try:
        from langchain_core.messages import AIMessage

        import src.core.llm as llm_mod
        import src.core.tickets_db as tdb
        from src.config import settings
        from src.eval import cases as ecases
        from src.eval import judge as ejudge
        from src.eval import metrics as emetrics
        from src.eval import runner as erunner
        from tests.fakes import ScriptedChatModel
    except Exception as exc:  # noqa: BLE001
        check("R0.imports", False, f"{type(exc).__name__}: {exc}")
        return

    # --- defaults (supersede 2C S2/R1/R2 and 6B R0.settings)
    have = {a: getattr(settings, a, None) for a in ("LLM_PROVIDER", "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S")}
    check("R0.settings_defaults", have == {"LLM_PROVIDER": "google_genai", "LLM_MODEL": PRIMARY, "LLM_FALLBACK_MODEL": FALLBACK,
                                           "EVAL_JUDGE_MODEL": JUDGE, "EVAL_SLEEP_S": 6.0}, f"settings={have}")
    env_ex, compose = read(".env.example"), read("docker-compose.yml")
    env_lines = {ln.strip() for ln in env_ex.splitlines()}
    want_env = {"LLM_PROVIDER=google_genai", f"LLM_MODEL={PRIMARY}", f"LLM_FALLBACK_MODEL={FALLBACK}", f"EVAL_JUDGE_MODEL={JUDGE}"}
    check("R0.env_and_compose", want_env <= env_lines and "LLM_MODEL=gemini-3.5-flash\n" not in env_ex + "\n"
          and f"${{LLM_MODEL:-{PRIMARY}}}" in compose and f"${{LLM_FALLBACK_MODEL:-{FALLBACK}}}" in compose,
          f".env.example needs {sorted(want_env)}; docker-compose.yml needs the same defaults")
    try:
        old_key = settings.GEMINI_API_KEY
        settings.GEMINI_API_KEY = "dummy-key-for-construction-only"
        p, f, jm = llm_mod.get_chat_model(), llm_mod.get_fallback_model(), ejudge.get_judge_model()
        check("R0.factory", model_name(p) == PRIMARY and f is not None and model_name(f) == FALLBACK and model_name(jm) == JUDGE
              and model_name(jm) != model_name(p), f"primary={model_name(p)}, fallback={model_name(f)}, judge={model_name(jm)}")
    except Exception as exc:  # noqa: BLE001
        check("R0.factory", False, f"{type(exc).__name__}: {exc}")
    finally:
        settings.GEMINI_API_KEY = old_key

    cases = ecases.load_cases(ROOT / "data/eval/cases.jsonl")
    by_id = {c["id"]: c for c in cases}
    res = {"id": "k01", "status": "ok", "error_type": None, "turns": [erunner.observe_turn(fake_state(), by_id["k01"]["turns"][0], 5.0)]}
    good = '{"grounded": 4, "answers_question": 5, "abstained": false, "rationale": "fine"}'

    # --- judge reads list-of-blocks replies (Gemini 3)
    try:
        check("J0.api", callable(getattr(ejudge, "response_text", None)) and callable(getattr(ejudge, "error_code", None)),
              "src/eval/judge.py must define response_text(message) and error_code(exc)")
        blocks = [{"type": "thinking", "thinking": '{"grounded": 1}'}, {"type": "text", "text": "Verdict:\n"},
                  {"type": "text", "text": good}]
        jm = ScriptedChatModel(responses=[AIMessage(content=blocks)])
        j = ejudge.judge_case(by_id["k01"], res, jm)
        check("J1.list_content_parsed", j.get("status") == "ok" and j.get("grounded") == 4 and j.get("answers_question") == 5,
              f"judgment={j}")
        rt = ejudge.response_text(AIMessage(content=["a", {"type": "text", "text": "b"}, {"type": "image_url", "image_url": "x"}]))
        check("J1.response_text", rt == "ab" and ejudge.response_text(AIMessage(content="plain")) == "plain", f"got {rt!r}")
    except Exception as exc:  # noqa: BLE001
        check("J1.runtime", False, f"{type(exc).__name__}: {exc}")

    # --- judge errors carry the HTTP code, never the message
    class RaisingModel(ScriptedChatModel):
        exc_factory: object = None

        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            self.received.append(list(messages))
            raise self.exc_factory()

    def wrapped(code: int, msg: str) -> Exception:
        try:
            try:
                raise ProviderError(code, msg)
            except ProviderError as inner:
                raise WrapperError(f"{code} UNAVAILABLE. {msg}") from inner
        except WrapperError as outer:
            return outer

    try:
        j1 = ejudge.judge_case(by_id["k01"], res, RaisingModel(responses=[], exc_factory=lambda: wrapped(503, "SECRET-MSG high demand")))
        j2 = ejudge.judge_case(by_id["k01"], res, RaisingModel(responses=[], exc_factory=lambda: RuntimeError("429 RESOURCE_EXHAUSTED x")))
        j3 = ejudge.judge_case(by_id["k01"], res, RaisingModel(responses=[], exc_factory=lambda: RuntimeError("boom")))
        j4 = ejudge.judge_case(by_id["k01"], res, ScriptedChatModel(responses=[AIMessage(content="no json")]))
        check("J2.error_code", j1.get("status") == "error" and j1.get("error_type") == "WrapperError" and j1.get("error_code") == 503
              and j2.get("error_code") == 429 and j3.get("error_code") is None and "error_code" in j3
              and j4.get("error_type") == "unparseable" and "error_code" in j4 and j4.get("error_code") is None
              and "SECRET-MSG" not in json.dumps([j1, j2, j3, j4]), f"j1={j1}, j2={j2}, j3={j3}, j4={j4}")
    except Exception as exc:  # noqa: BLE001
        check("J2.error_code", False, f"{type(exc).__name__}: {exc}")

    # --- run_judge stops after N consecutive errors of any kind; an ok resets the count
    try:
        rp = Path(tmp) / "runs" / "J.jsonl"
        rp.parent.mkdir(parents=True, exist_ok=True)
        ids = ["k01", "k02", "k03", "k04", "k05", "k06", "k07"]
        rp.write_text("".join(json.dumps(res | {"id": i}) + "\n" for i in ids), encoding="utf-8")
        sub = [by_id[i] for i in ids]
        jm = ScriptedChatModel(responses=[AIMessage(content="nope")] * 7)
        s1 = ejudge.run_judge(sub, rp, Path(tmp) / "runs" / "J1.judge.jsonl", model=jm, sleep_s=0)
        seq = [AIMessage(content="x"), AIMessage(content="x"), AIMessage(content=good), AIMessage(content="x"),
               AIMessage(content="x"), AIMessage(content="x"), AIMessage(content=good)]
        jm2 = ScriptedChatModel(responses=seq)
        s2 = ejudge.run_judge(sub, rp, Path(tmp) / "runs" / "J2.judge.jsonl", model=jm2, sleep_s=0)
        jm3 = RaisingModel(responses=[], exc_factory=lambda: wrapped(503, "busy"))
        s3 = ejudge.run_judge(sub, rp, Path(tmp) / "runs" / "J3.judge.jsonl", model=jm3, sleep_s=0)
        check("J3.stops_on_consecutive_errors", len(jm.received) == 3 and s1.get("stopped_early") is True
              and len(jm2.received) == 6 and s2.get("stopped_early") is True and s2.get("ok") == 1
              and len(jm3.received) == 3 and s3.get("stopped_early") is True,
              f"unparseable: calls={len(jm.received)} {s1}; mixed: calls={len(jm2.received)} {s2}; 503: calls={len(jm3.received)} {s3}")
    except Exception as exc:  # noqa: BLE001
        check("J3.stops_on_consecutive_errors", False, f"{type(exc).__name__}: {exc}")

    # --- runner removes its temporary tickets directory
    try:
        seen: list[str] = []

        class FakeOrch:
            def run_sync(self, user_id, message, session_id, trace_id=None):
                seen.append(settings.TICKETS_DB_PATH)
                tdb.get_tickets_repository()
                return fake_state()

        orig = settings.TICKETS_DB_PATH
        erunner.run_eval([by_id["k01"], by_id["k02"]], Path(tmp) / "runs" / "R.jsonl", "R", orchestrator_factory=FakeOrch, sleep_s=0)
        dirs = {str(Path(p).parent) for p in seen}
        check("R1.temp_tickets_dir_removed", seen and settings.TICKETS_DB_PATH == orig and all(not Path(d).exists() for d in dirs)
              and not any(str(ROOT / "data") in p for p in seen), f"temp dirs={dirs}, still exist={[d for d in dirs if Path(d).exists()]}")
    except Exception as exc:  # noqa: BLE001
        check("R1.temp_tickets_dir_removed", False, f"{type(exc).__name__}: {exc}")
    finally:
        tdb.reset_tickets_repository()

    # --- committed full run (raw file produced by the user's real run; must be byte-identical up to line endings)
    raw = (ROOT / RUN_FILE).read_bytes() if (ROOT / RUN_FILE).exists() else b""
    sha = hashlib.sha256(raw.replace(b"\r\n", b"\n")).hexdigest()
    check("D1.run_file_unchanged", sha == RUN_SHA256, f"{RUN_FILE} missing or modified (sha256 {sha})")
    results = erunner.load_results(ROOT / RUN_FILE)
    check("D1.run_file_complete", sorted(results) == sorted(by_id) and all(r.get("status") == "ok" for r in results.values()),
          f"{len(results)} results, {sum(r.get('status') == 'ok' for r in results.values())} ok")
    check("D2.buggy_judge_file_removed", not (ROOT / "reports/eval_runs/full-1.judge.jsonl").exists(),
          "reports/eval_runs/full-1.judge.jsonl (written by the list-content bug) must be deleted, not committed")
    rep_j, rep_m = ROOT / "reports/eval_full-1.json", ROOT / "reports/eval_full-1.md"
    try:
        rep = json.loads(rep_j.read_text(encoding="utf-8"))
        agg = emetrics.aggregate(cases, list(results.values()))
        diffs = [k for k in agg if json.dumps(agg[k], sort_keys=True) != json.dumps(rep.get(k), sort_keys=True)]
        check("D3.report_matches_raw", not diffs and rep.get("run_id") == "full-1" and rep.get("judge") is None
              and rep.get("cases_sha256") == ecases.cases_sha256(cases) and rep.get("complete") is True and rep_m.exists()
              and "pass_rate" in rep_m.read_text(encoding="utf-8"),
              f"keys differing from aggregate(cases, full-1): {diffs[:5]}, judge={rep.get('judge')!r}, complete={rep.get('complete')!r}")
    except Exception as exc:  # noqa: BLE001
        check("D3.report_matches_raw", False, f"{type(exc).__name__}: {exc}")


def static_checks() -> None:
    missing = [f"{p}: {m!r}" for p, ms in PROMPT_MARKS.items() for m in ms if m not in read(p)]
    check("P1.reviewer_prompts", not missing, f"reviewer prompt text missing: {missing}")
    readme = read("README.md")
    need = [PRIMARY, FALLBACK, "full-1", "reports/eval_runs/full-1.jsonl", "20"]
    check("S1.readme_models", all(w in readme for w in need) and "(padrão: `gemini-3.5-flash`)" not in readme
          and "padrão `gemini-3.5-flash-lite`)" not in readme,
          f"README must state the new defaults ({PRIMARY}, fallback {FALLBACK}, judge {JUDGE}), why (Flash free tier: 20 requests/day), "
          "and point to the committed run reports/eval_runs/full-1.jsonl")
    check("S2.readme_judge_caveat", "EVAL_JUDGE_MODEL=gemini-3.5-flash-lite" in readme and "judge_models" in readme,
          "README must document the judge fallback EVAL_JUDGE_MODEL=gemini-3.5-flash-lite (same model as the answers) and that "
          "judge_models records it")


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks(tmp: str) -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    tests = read("tests/test_eval_runner_judge.py")
    n_tests = len(re.findall(r"^def test_", tests, flags=re.M))
    check("Q0.runner_judge_tests", n_tests >= 13, f"tests/test_eval_runner_judge.py has {n_tests} tests (need >= 13: 9 from 6B + 4)")
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH",
                         "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1", CHECKPOINT_DB_PATH=str(Path(tmp) / "nested" / "checkpoints.db"))
    for script, allowed in PRIOR.items():
        env_s = {k: v for k, v in nested.items() if k != "CHECKPOINT_DB_PATH"} if script == "verify_phase4b.py" else nested
        r = run([sys.executable, f"scripts/{script}"], env=env_s)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    marks = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in ("data/tickets.db", "data/checkpoints.db")}
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "warning" not in last, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")
    after = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in marks}
    check("Q4.tests_do_not_touch_data_dbs", marks == after, f"the test suite wrote {[p for p in marks if marks[p] != after[p]]}")
    out_dir = Path(tmp) / "cli_out"
    cli = run([sys.executable, "-m", "src.eval", "report", "--run-id", "does-not-exist", "--runs-dir", str(Path(tmp) / "nope"),
               "--out-dir", str(out_dir)], env=env0)
    check("Q5.cli_report_missing_results", cli.returncode != 0 and "does-not-exist" in (cli.stdout + cli.stderr)
          and not (out_dir / "eval_does-not-exist.json").exists(), f"exit={cli.returncode}: {(cli.stdout + cli.stderr)[-200:]}")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p6c_")
    static_checks()
    main_checks(tmp)
    suite_checks(tmp)
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
