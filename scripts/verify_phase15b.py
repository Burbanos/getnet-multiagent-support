def human_sample2(tmp: str) -> None:
    from src.eval.cases import load_cases
    from src.eval.checks import evaluate_case
    from src.eval.human_validation import write_human_sample2
    from src.eval.runner import load_results

    out1, out2 = Path(tmp) / "hs2a", Path(tmp) / "hs2b"
    write_human_sample2(out1, size=40)
    write_human_sample2(out2, size=40)
    s1 = (out1 / "sample.json").read_text(encoding="utf-8")
    same = s1 == (out2 / "sample.json").read_text(encoding="utf-8")
    sample = json.loads(s1)
    items = sample.get("items", [])
    first = json.loads(read("reports/human_validation/sample.json"))
    first_pairs = {(first.get("source_run"), it["case_id"]) for it in first["items"]}
    fails = passes = 0
    cases_seen = set()
    bad = []
    for it in items:
        cases = {c["id"]: c for c in load_cases(it["cases_file"])}
        res = load_results(ROOT / "reports/eval_runs" / f"{it['run_id']}.jsonl").get(it["case_id"])
        if res is None or res.get("status") != "ok":
            bad.append(f"{it.get('hid')}: no ok record")
            continue
        passed = evaluate_case(cases[it["case_id"]], res)["passed"]
        fails += not passed
        passes += passed
        key = (it["cases_file"], it["case_id"])
        if key in cases_seen:
            bad.append(f"{it.get('hid')}: repeated case")
        cases_seen.add(key)
        if (it["run_id"], it["case_id"]) in first_pairs:
            bad.append(f"{it.get('hid')}: in the first sample")
        if not re.match(r"(v2|rh|rh2|h3)-\d+$", it["run_id"]):
            bad.append(f"{it.get('hid')}: run {it['run_id']}")
    hids = [it.get("hid") for it in items]
    form = (out1 / "form.md").read_text(encoding="utf-8") if (out1 / "form.md").exists() else ""
    # The blind ids g01–g40 can coincide with case ids of the v2 set (g01–g06): drop the item headings and the sentence that
    # names the id range before looking for case ids, so only a real leak in the text counts.
    form_body = re.sub(r"(?m)^#{1,6}\s*g\d{2}\s*$", "", form)
    form_body = re.sub(r"`g01`\s*(?:a|até|-|–)\s*`g40`", "", form_body)
    leaks = [it["case_id"] for it in items if re.search(rf"\b{re.escape(it['case_id'])}\b", form_body)]
    leaks += re.findall(r"\b(?:v2|rh|rh2|h3)-\d+\b", form_body) + [w for w in ("run_id", "passed") if w in form_body]
    tpl = list(csv.reader(io.StringIO((out1 / "answers_template.csv").read_text(encoding="utf-8")), delimiter=";"))
    tpl_first = list(csv.reader(io.StringIO(read("reports/human_validation/answers_template.csv")), delimiter=";"))
    ok = (same and len(items) == 40 and hids == [f"g{i:02d}" for i in range(1, 41)] and fails == 20 and passes == 20
          and not bad and not leaks and tpl and tpl[0] == tpl_first[0] and [r[0] for r in tpl[1:]] == hids)
    check("H1.second_sample_blind_and_balanced", ok,
          f"deterministic={same} items={len(items)} failing={fails} passing={passes} problems={bad[:4]} form_leaks={leaks[:4]} "
          f"template_header={tpl[0] if tpl else None}")
    committed = read("reports/human_validation_2/sample.json")
    check("H2.second_sample_committed", committed == s1 and not (ROOT / "reports/human_validation_2/answers.csv").exists()
          and (ROOT / "reports/human_validation_2/form.md").exists(),
          "reports/human_validation_2/ must hold the generated sample.json, form.md and answers_template.csv, without answers.csv")


