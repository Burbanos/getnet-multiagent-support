def _legacy_modules() -> list[str]:
    """LEGACY_NO_COVERAGE_MODULES of tests/conftest.py (module names), read without importing pytest plugins."""
    m = re.search(r"LEGACY_NO_COVERAGE_MODULES\s*(?::[^=]*)?=\s*(\(|\[|\{|frozenset\(\{?)(.*?)(\)|\]|\})", read("tests/conftest.py"),
                  re.S)
    return sorted(set(re.findall(r"[\"']([\w.]+)[\"']", m.group(2)))) if m else []


def suite_checks() -> None:
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH", "DATABASE_URL",
                         "REDIS_URL", "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER",
                         "TEST_DATABASE_URL", "TEST_REDIS_URL", "TRACING_EXPORTER")}
    env0["GEMINI_API_KEY"] = ""
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    marks = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None)
             for p in ("data/tickets.db", "data/checkpoints.db", "data/index/index_meta.json", "data/index/chunks.jsonl")}
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    m_all = re.search(r"(\d+) passed", last)
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "failed" not in last and bool(m_all)
          and int(m_all.group(1)) >= MIN_TESTS, f"{last} (want at least {MIN_TESTS}: 542 at 15A + the new tests)",
          info=last)
    counts = {f: len(re.findall(r"^\s*(?:async\s+)?def test_\w+", read(f), re.M)) for f in NEW_TESTS}
    check("Q6.new_tests_written", all(counts[f] >= n for f, n in NEW_TESTS.items()), f"{counts} (want {NEW_TESTS})",
          info=str(counts))
    legacy = _legacy_modules()
    bad_new = [m for m in legacy if any(m.endswith(Path(f).stem) for f in NEW_TESTS)]
    unjustified = []
    for mod in legacy:
        rel = "tests/" + mod.split(".")[-1] + ".py"
        r = run([sys.executable, "-m", "pytest", "-q", "-x", "-p", "verify_nonet", "-p", "no:cacheprovider", rel],
                env=dict(env, PLAN_COVERAGE_FORCE="1"))
        if r.returncode == 0:
            unjustified.append(mod)
    check("Q8.legacy_modules_without_gate_justified", not bad_new and not unjustified,
          f"modules that run with plan_coverage off in tests/conftest.py must fail with it on (PLAN_COVERAGE_FORCE=1) and "
          f"may not be new 15A files: new={bad_new} pass_with_gate_on={unjustified}", info=f"{len(legacy)} modules: {legacy}")
    o = run([sys.executable, "-m", "src.eval", "offline"], env=env0)
    check("Q5.offline_eval", o.returncode == 0 and "offline: 6/6 passed" in o.stdout, (o.stdout + o.stderr)[-300:])
    if os.environ.get("TEST_DATABASE_URL") and os.environ.get("TEST_REDIS_URL"):
        r = run([sys.executable, "-m", "pytest", "-m", "integration", "-q", "-p", "no:cacheprovider"])
        last_i = ([ln for ln in r.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)] or [r.stdout[-300:]])[-1]
        m = re.search(r"(\d+) passed", last_i)
        check("Q7.integration_suite", r.returncode == 0 and bool(m) and int(m.group(1)) >= 13, last_i, info=last_i)
    else:
        note("Q7.integration_suite", "TEST_DATABASE_URL/TEST_REDIS_URL not set: run by the reviewer and by the CI job")
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")
    after = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in marks}
    check("Q4.tests_do_not_touch_data", marks == after, f"the test suite wrote {[p for p in marks if marks[p] != after[p]]}")


