def oracle(required_per_call: list[list[str]] | None = None, default: list[str] | None = None):
    """Scripted verifier that grounds like the real one should: call i answers 'answered' only when every snippet of
    required_per_call[i] (or `default` past the list) reached its input outside the draft and the latest message."""
    from langchain_core.messages import AIMessage
    from langchain_core.outputs import ChatGeneration, ChatResult

    from tests.fakes import ScriptedChatModel

    plan = list(required_per_call or [])
    fallback = list(default or [])

    class Oracle(ScriptedChatModel):
        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            idx = len(self.received)
            self.received.append(list(messages))
            required = plan[idx] if idx < len(plan) else fallback
            text = re.sub(r"(?s)<draft>.*?</draft>", "", msg_text(messages[-1]))  # the draft never supports itself
            text = re.sub(r"(?s)<message>.*?</message>", "", text)
            missing = [s for s in required if s not in text]
            steps_block = msg_text(messages[-1]).split("<plan_steps>", 1)[-1].split("</plan_steps>", 1)[0]
            n_steps = max(1, len(re.findall(r"(?m)^\d+\. ", steps_block)))  # one verdict per plan step
            verdicts = [{"step": i, "verdict": "unsupported_claim" if (missing and i == 1) else "answered",
                         "note": "not in the evidence" if (missing and i == 1) else ""} for i in range(1, n_steps + 1)]
            msg = AIMessage(content="", tool_calls=[{"name": "Verification", "args": {"verdicts": verdicts},
                                                     "id": f"call_{uuid.uuid4().hex[:8]}"}])
            return ChatResult(generations=[ChatGeneration(message=msg)])

    return Oracle()


