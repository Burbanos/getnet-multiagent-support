def _b64(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()


def forge(header: dict, claims: dict, secret: str) -> str:
    """Sign a JWT the way HS256 does, to build tokens the implementation must reject."""
    h = _b64(json.dumps(header, separators=(",", ":")).encode())
    c = _b64(json.dumps(claims, separators=(",", ":")).encode())
    sig = hmac.new(secret.encode(), f"{h}.{c}".encode(), hashlib.sha256).digest()
    return f"{h}.{c}.{_b64(sig)}"


def _parts(token: str) -> tuple[dict, dict]:
    h, c, _ = token.split(".")
    pad = lambda x: x + "=" * (-len(x) % 4)  # noqa: E731
    return json.loads(base64.urlsafe_b64decode(pad(h))), json.loads(base64.urlsafe_b64decode(pad(c)))


