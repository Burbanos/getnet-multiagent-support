def ref_cost(pricing, ok_results: list[dict]) -> float | None:
    priced = []
    for r in ok_results:
        for t in r.get("turns", []):
            tk = t.get("tokens")
            if not tk:
                continue
            p = OFFICIAL.get((t.get("llm_model") or "").removeprefix("models/"))
            i, o = tk.get("input_tokens"), tk.get("output_tokens")
            priced.append(None if p is None or i is None or o is None else round(i / 1e6 * p[0] + o / 1e6 * p[1], 8))
    return round(sum(priced), 6) if priced and all(c is not None for c in priced) else None


def ref_compare(emetrics, cases: list[dict], groups: list[tuple[str, list[tuple[str, list, list | None]]]]) -> list[dict]:
    out = []
    for label, runs in groups:
        aggs = [emetrics.aggregate(cases, res, jud) for _, res, jud in runs]
        mets = {}
        for name, sec, key, _, _ in METRICS:
            vals = [((a.get(sec) or {}).get(key)) for a in aggs]
            if any(v is None for v in vals):
                mets[name] = {"values": vals, "mean": None, "min": None, "max": None}
            else:
                mets[name] = {"values": vals, "mean": sum(vals) / len(vals), "min": min(vals), "max": max(vals)}
        failed = None
        for a in aggs:
            ids = {pc["id"] for pc in a["per_case"] if pc["status"] == "ok" and not pc["passed"]}
            failed = ids if failed is None else failed & ids
        if all(a.get("judge") for a in aggs):
            ab = None
            for a in aggs:
                ids = set(a["judge"]["abstention_errors"])
                ab = ids if ab is None else ab & ids
            ab = sorted(ab)
        else:
            ab = []
        out.append({
            "label": label,
            "runs": [rid for rid, _, _ in runs],
            "answer_models": sorted({m for a in aggs for m in a.get("answer_models", [])}),
            "complete": all(a["n_errors"] == 0 and a["n_evaluated"] == len(cases) for a in aggs),
            "metrics": mets,
            "failed_in_all_runs": sorted(failed or []),
            "judge_abstention_errors_in_all_runs": ab,
        })
    return out


def fmt(kind: str, v) -> str:
    if v is None:
        return "n/d"
    if kind == "pct":
        s = f"{v * 100:.1f}"
    elif kind == "dec2":
        s = f"{v:.2f}"
    elif kind == "sec":
        s = f"{v / 1000:.1f}"
    elif kind == "int":
        return f"{round(v):,}".replace(",", ".")
    else:  # usd
        s = f"{v:.3f}"
    return s.replace(".", ",")


def cell(kind: str, m: dict) -> str:
    if m["mean"] is None:
        return "n/d"
    rng = f"{fmt(kind, m['min'])}–{fmt(kind, m['max'])}"
    if kind == "pct":
        return f"{fmt(kind, m['mean'])}% ({rng})"
    if kind == "sec":
        return f"{fmt(kind, m['mean'])} s ({rng})"
    if kind == "usd":
        return f"US$ {fmt(kind, m['mean'])} ({rng})"
    return f"{fmt(kind, m['mean'])} ({rng})"


def ref_table(groups: list[dict]) -> list[str]:
    lines = ["| Métrica | " + " | ".join(g["label"] for g in groups) + " |",
             "| :--- |" + " :--- |" * len(groups),
             "| Execuções | " + " | ".join(", ".join(g["runs"]) for g in groups) + " |",
             "| Modelo das respostas | " + " | ".join(", ".join(g["answer_models"]) or "n/d" for g in groups) + " |"]
    for name, _, _, title, kind in METRICS:
        lines.append(f"| {title} | " + " | ".join(cell(kind, g["metrics"][name]) for g in groups) + " |")
    return lines


def same_metrics(a: dict, b: dict) -> bool:
    if set(a) != {n for n, *_ in METRICS}:
        return False
    for n in a:
        x, y = a[n], b[n]
        if len(x.get("values", [])) != len(y["values"]) or not all(close(p, q) for p, q in zip(x["values"], y["values"])):
            return False
        if not all(close(x.get(k), y[k]) for k in ("mean", "min", "max")):
            return False
    return True


def diff_groups(got: list[dict], want: list[dict]) -> list[str]:
    errs = []
    if [g.get("label") for g in got] != [g["label"] for g in want]:
        return [f"labels {[g.get('label') for g in got]} != {[g['label'] for g in want]}"]
    for g, w in zip(got, want):
        for k in ("runs", "answer_models", "complete", "failed_in_all_runs", "judge_abstention_errors_in_all_runs"):
            if g.get(k) != w[k]:
                errs.append(f"{w['label']}.{k}: {g.get(k)!r} != {w[k]!r}")
        if not same_metrics(g.get("metrics", {}), w["metrics"]):
            errs.append(f"{w['label']}.metrics differ")
    return errs


