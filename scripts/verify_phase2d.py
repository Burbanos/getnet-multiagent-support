"""Phase 2D acceptance checks (docs/SPEC.md, Phase 2D: specialist sub-agents). Cross-platform.

Usage (from the repository root):  python scripts/verify_phase2d.py
Requires the dev environment. Never calls a real LLM.
Do NOT edit this file to make checks pass: the reviewer runs an independent copy.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

ROOT = Path.cwd()
RESULTS: list[tuple[str, bool]] = []
SUPERVISOR_TOOL_NAMES = {"ask_knowledge_agent", "ask_support_agent", "escalate_to_human"}
KNOWLEDGE_TOOLS = {"search_knowledge_base", "search_web"}
SUPPORT_TOOLS = {"get_settlement_status", "diagnose_declined_transaction", "diagnose_terminal"}
# Earlier-phase checks superseded by the sub-agent architecture (the supervisor no longer calls leaf tools).
SUPERSEDED = {
    "verify_phase2a.py": {"R2.single_tool_flow", "R3.user_id_injected", "R3.bound_tools", "R4.two_tools_sequence"},
    "verify_phase2b.py": {"S1.default_model_config", "S1.default_model_env_example", "R2.model_name"},
    "verify_phase2c.py": set(),
}

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=900)


def static_checks() -> None:
    sup, kno, spt = read("src/prompts/supervisor.md"), read("src/prompts/knowledge_agent.md"), read("src/prompts/support_agent.md")
    check("S1.supervisor_prompt", "ask_knowledge_agent" in sup and "ask_support_agent" in sup and '"em breve"' in sup,
          "supervisor.md missing agent tools or the no-vague-time-promise rule")
    check("S1.knowledge_prompt", "You are the Knowledge Agent" in kno, "src/prompts/knowledge_agent.md missing or wrong")
    check("S1.support_prompt", "You are the Customer Support Agent" in spt, "src/prompts/support_agent.md missing or wrong")
    check("S2.specialists_module", "class SpecialistAgent" in read("src/agents/specialists.py"),
          "src/agents/specialists.py::SpecialistAgent missing")
    readme = read("README.md")
    check("S3.readme_agents", all(w in readme for w in ["KnowledgeAgent", "SupportAgent", "ask_knowledge_agent"]),
          "README does not describe the supervisor + specialist agents")


def runtime_checks() -> None:
    tmp = tempfile.mkdtemp(prefix="verify_p2d_")
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["GEMINI_API_KEY"] = ""
    sys.path.insert(0, str(ROOT))
    try:
        from fastapi.testclient import TestClient
        from langchain_core.exceptions import ModelRateLimitError
        from langchain_core.messages import AIMessage, HumanMessage, SystemMessage, ToolMessage
        from langchain_core.outputs import ChatGeneration, ChatResult

        import src.core.graph as graph_mod
        from src.config import settings
        from src.core.graph import OrchestrationGraph
        from src.main import app
        from src.tools.supervisor_tools import SUPERVISOR_TOOLS
        from tests.fakes import ScriptedChatModel
    except Exception as exc:  # noqa: BLE001
        check("R0.imports", False, f"{type(exc).__name__}: {exc}")
        return

    from typing import Any

    from pydantic import Field

    class StepFake(ScriptedChatModel):
        """Scripted model whose script may contain exceptions to raise at that step."""

        responses: list[Any] = Field(default_factory=list)

        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            self.received.append(list(messages))
            if not self.responses:
                raise RuntimeError("StepFake: no scripted responses left")
            item = self.responses.pop(0)
            if isinstance(item, Exception):
                raise item
            return ChatResult(generations=[ChatGeneration(message=item)])

    def call(name: str, args: dict, cid: str) -> AIMessage:
        return AIMessage(content="", tool_calls=[{"name": name, "args": args, "id": cid}])

    def tool_payload(msgs) -> dict:
        for m in msgs:
            if isinstance(m, ToolMessage):
                try:
                    return json.loads(m.content)
                except (TypeError, ValueError):
                    return {}
        return {}

    check("R1.supervisor_tools", {t.name for t in SUPERVISOR_TOOLS} == SUPERVISOR_TOOL_NAMES,
          f"SUPERVISOR_TOOLS={sorted(t.name for t in SUPERVISOR_TOOLS)}")
    leaked = {t.name for t in SUPERVISOR_TOOLS if "user_id" in t.args}
    check("R1.no_user_id_in_supervisor_schema", not leaked, f"user_id visible in {leaked}")
    if not hasattr(settings, "MAX_SPECIALIST_STEPS"):
        check("R1.settings_specialist_steps", False, "settings.MAX_SPECIALIST_STEPS missing")
        return
    check("R1.settings_specialist_steps", settings.MAX_SPECIALIST_STEPS == 4, f"default={settings.MAX_SPECIALIST_STEPS}")

    try:
        probe = OrchestrationGraph(chat_model=StepFake(responses=[]))
        k, s = probe.knowledge_agent, probe.support_agent
        check("R2.agent_names", (k.name, s.name) == ("KnowledgeAgent", "SupportAgent"), f"names={(k.name, s.name)}")
        check("R2.knowledge_tools", {t.name for t in k.tools} == KNOWLEDGE_TOOLS, f"knowledge tools={sorted(t.name for t in k.tools)}")
        check("R2.support_tools", {t.name for t in s.tools} == SUPPORT_TOOLS, f"support tools={sorted(t.name for t in s.tools)}")
    except Exception as exc:  # noqa: BLE001
        check("R2.runtime", False, f"{type(exc).__name__}: {exc}")
        return

    support_prompt = read("src/prompts/support_agent.md").strip()
    try:
        fake = StepFake(responses=[
            call("ask_support_agent", {"request": "Check yesterday's settlement"}, "s1"),
            call("get_settlement_status", {}, "s2"),
            AIMessage(content="SPEC-ANSWER"),
            AIMessage(content="FINAL-A"),
        ])
        st = OrchestrationGraph(chat_model=fake).run_sync(user_id="cliente1988", message="When will I get paid?", session_id="v2d-a")
        check("R3.support_flow", st.agent_response == "FINAL-A" and st.tools_used == ["get_settlement_status"],
              f"response={st.agent_response!r}, tools_used={st.tools_used}")
        check("R3.agents_used", getattr(st, "agents_used", None) == ["SupervisorAgent", "SupportAgent"],
              f"agents_used={getattr(st, 'agents_used', None)}")
        spec_in = fake.received[1] if len(fake.received) > 1 else []
        isolated = (len(spec_in) == 2 and isinstance(spec_in[0], SystemMessage) and isinstance(spec_in[1], HumanMessage)
                    and spec_in[0].content.strip() == support_prompt and spec_in[1].content == "Check yesterday's settlement")
        check("R4.specialist_isolated_context", isolated,
              f"specialist received {[type(m).__name__ for m in spec_in]}; expected [support prompt, task only]")
        inner = fake.received[2] if len(fake.received) > 2 else []
        check("R4.user_id_injected_in_specialist", any(isinstance(m, ToolMessage) and '"cliente1988"' in str(m.content) for m in inner),
              "specialist tool did not receive the authenticated user_id")
        p = tool_payload(fake.received[3] if len(fake.received) > 3 else [])
        check("R5.specialist_payload", p.get("agent") == "SupportAgent" and p.get("status") == "ok" and p.get("answer") == "SPEC-ANSWER"
              and p.get("tools_used") == ["get_settlement_status"] and "sources" in p, f"payload={p}")

        fake = StepFake(responses=[
            call("ask_knowledge_agent", {"question": "Do I need a bank account for Pix?"}, "k1"),
            call("search_knowledge_base", {"query": "Pix conta bancária"}, "k2"),
            AIMessage(content="K-ANSWER"),
            AIMessage(content="FINAL-B"),
        ])
        st = OrchestrationGraph(chat_model=fake).run_sync(user_id="cliente1988", message="Pix?", session_id="v2d-b")
        check("R6.knowledge_flow", st.agent_response == "FINAL-B" and st.tools_used == ["search_knowledge_base"]
              and getattr(st, "agents_used", None) == ["SupervisorAgent", "KnowledgeAgent"] and len(st.sources) > 0,
              f"tools={st.tools_used}, agents={getattr(st, 'agents_used', None)}, sources={st.sources}")

        fake = StepFake(responses=[
            call("ask_support_agent", {"request": "settlement"}, "m1"), call("get_settlement_status", {}, "m2"), AIMessage(content="S"),
            call("ask_knowledge_agent", {"question": "antecipação"}, "m3"), call("search_knowledge_base", {"query": "antecipação"}, "m4"),
            AIMessage(content="K"), AIMessage(content="FINAL-C"),
        ])
        st = OrchestrationGraph(chat_model=fake).run_sync(user_id="cliente1988", message="two parts", session_id="v2d-c")
        check("R7.two_specialists", getattr(st, "agents_used", None) == ["SupervisorAgent", "SupportAgent", "KnowledgeAgent"]
              and st.tools_used == ["get_settlement_status", "search_knowledge_base"] and st.agent_response == "FINAL-C",
              f"agents={getattr(st, 'agents_used', None)}, tools={st.tools_used}")

        fake = StepFake(responses=[
            call("ask_support_agent", {"request": "settlement"}, "x1"),
            call("search_web", {"query": "euro"}, "x2"),
            AIMessage(content="S"), AIMessage(content="FINAL-D"),
        ])
        st = OrchestrationGraph(chat_model=fake).run_sync(user_id="cliente1988", message="x", session_id="v2d-d")
        inner = fake.received[2] if len(fake.received) > 2 else []
        refused = any(isinstance(m, ToolMessage) and "error" in str(m.content).lower() for m in inner)
        check("R8.specialist_tool_isolation", "search_web" not in st.tools_used and refused,
              f"tools_used={st.tools_used}; support agent tool error returned={refused}")

        fake = StepFake(responses=[call("escalate_to_human", {"reason": "human requested"}, "e1"), AIMessage(content="FINAL-E")])
        st = OrchestrationGraph(chat_model=fake).run_sync(user_id="cliente1988", message="atendente", session_id="v2d-e")
        check("R9.escalation_from_supervisor", bool((st.ticket or {}).get("ticket_id")) and st.tools_used == ["escalate_to_human"],
              f"ticket={st.ticket}, tools={st.tools_used}")

        old = settings.MAX_SPECIALIST_STEPS
        settings.MAX_SPECIALIST_STEPS = 2
        try:
            fake = StepFake(responses=[
                call("ask_support_agent", {"request": "loop"}, "l1"),
                call("get_settlement_status", {}, "l2"), call("get_settlement_status", {}, "l3"),
                AIMessage(content="FINAL-F"), AIMessage(content="EXTRA-UNUSED"),
            ])
            st = OrchestrationGraph(chat_model=fake).run_sync(user_id="cliente1988", message="x", session_id="v2d-f")
            p = tool_payload(fake.received[3] if len(fake.received) > 3 else [])
            check("R10.specialist_step_limit", len(fake.received) == 4 and p.get("status") == "step_limit" and st.agent_response == "FINAL-F",
                  f"model calls={len(fake.received)}, payload status={p.get('status')}, response={st.agent_response!r}")
        finally:
            settings.MAX_SPECIALIST_STEPS = old

        client = TestClient(app)
        graph_mod._orchestrator_instance = OrchestrationGraph(chat_model=StepFake(responses=[
            call("ask_support_agent", {"request": "settlement"}, "h1"), ModelRateLimitError("429")]))
        r = client.post("/chat", json={"message": "x", "user_id": "cliente1988"})
        check("R11.specialist_llm_error_503", r.status_code == 503 and "unavailable" in r.text.lower(), f"status {r.status_code}: {r.text[:200]}")

        graph_mod._orchestrator_instance = OrchestrationGraph(chat_model=StepFake(responses=[
            call("ask_support_agent", {"request": "settlement"}, "a1"), call("get_settlement_status", {}, "a2"),
            AIMessage(content="S"), AIMessage(content="ok")]))
        r = client.post("/chat", json={"message": "x", "user_id": "cliente1988"})
        meta = r.json().get("metadata", {}) if r.status_code == 200 else {}
        check("R12.api_agents_used", meta.get("agents_used") == ["SupervisorAgent", "SupportAgent"], f"status {r.status_code}, metadata={meta}")
    except Exception as exc:  # noqa: BLE001
        check("R3.runtime", False, f"{type(exc).__name__}: {exc}")
    finally:
        graph_mod._orchestrator_instance = None


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks() -> None:
    env0 = {k: v for k, v in os.environ.items() if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY")}
    env0["GEMINI_API_KEY"] = ""
    for script, allowed in SUPERSEDED.items():
        r = run([sys.executable, f"scripts/{script}"], env=env0)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed - {"Q0.phase2a_still_passes", "Q0.phase2b_only_superseded_fail"})
        check(f"Q0.{script[:-3]}_regressions", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    static_checks()
    runtime_checks()
    suite_checks()
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
