def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


class KeywordEmbedder:
    def __init__(self, keywords: list[str]):
        self.keywords = keywords

    def _vec(self, text: str) -> list[float]:
        t = text.lower()
        return [float(t.count(k)) for k in self.keywords] + [0.01]

    def embed_documents(self, texts: list[str]) -> list[list[float]]:
        return [self._vec(t) for t in texts]

    def embed_query(self, text: str) -> list[float]:
        return self._vec(text)


def static_checks() -> None:
    check("S1.old_kb_removed", not (ROOT / "data/getnet_kb.json").exists(), "data/getnet_kb.json still exists")
    files = [p for d in ("src", "tests") for p in (ROOT / d).rglob("*.py")]
    files += [ROOT / f for f in ("docker-compose.yml", "Dockerfile", ".env.example", "requirements.txt", "requirements-dev.txt")]
    hits = sorted({f"{p.relative_to(ROOT).as_posix()}:{w}" for p in files if p.exists()
                   for w in LEGACY if w in p.read_text(encoding="utf-8", errors="replace")})
    check("S2.legacy_removed", not hits, f"legacy references: {hits[:6]}")
    req = read("requirements.txt").lower()
    check("S3.requirements", "chromadb" not in req and "numpy" in req, "requirements.txt must drop chromadb and declare numpy")
    kp = read("src/prompts/knowledge_agent.md")
    check("S4.knowledge_prompt", "fetched_at" in kp and "do not contain the specific answer" in kp,
          "src/prompts/knowledge_agent.md is not the reviewer's 3C version")
    readme = read("README.md")
    check("S5.readme", "gemini-embedding-2" in readme and "data/index" in readme and "48x" in readme,
          "README must describe the wired RAG (gemini-embedding-2, data/index) and the 36x -> 48x correction example")


def runtime_checks() -> None:
    tmp = tempfile.mkdtemp(prefix="verify_p3c_")
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["GEMINI_API_KEY"] = ""
    sys.path.insert(0, str(ROOT))
    try:
        from langchain_core.messages import AIMessage

        import src.core.llm as llm_mod
        import src.rag.retriever as rag_retriever
        from src.config import settings
        from src.core.graph import OrchestrationGraph
        from src.rag import chunking, index
        from src.tools.agent_tools import TOOLS_BY_NAME
        from tests.fakes import ScriptedChatModel
    except Exception as exc:  # noqa: BLE001
        check("R0.imports", False, f"{type(exc).__name__}: {exc}")
        return

    check("R1.min_chunk_setting", getattr(settings, "RAG_MIN_CHUNK_CHARS", None) == 120,
          f"RAG_MIN_CHUNK_CHARS={getattr(settings, 'RAG_MIN_CHUNK_CHARS', None)}")

    def page(i: int, lines: list[str]) -> dict:
        import hashlib
        text = "\n".join(lines)
        return {"url": f"https://site.getnet.com.br/q{i}", "title": f"Q{i}", "market": "BR", "status": "ok",
                "fetched_at": "2026-11-06T00:00:00+00:00", "text": text, "chars": len(text),
                "sha256": hashlib.sha256(text.encode()).hexdigest()}
    try:
        tiny = page(1, ["Antecipação de Vendas"])
        body = [f"Linha de conteúdo número {n} sobre o crediário Getnet com parcelamento e taxa única." for n in range(11)]
        long_page = page(2, body + ["Tail curto."])
        default = chunking.build_chunks([tiny, long_page], max_chars=900, boilerplate_min_pages=4)
        strict = chunking.build_chunks([tiny, long_page], max_chars=900, boilerplate_min_pages=4, min_chars=120)
        check("R2.default_keeps_3b_behaviour", any(c["doc_url"].endswith("/q1") for c in default), "min_chars must default to 0")
        check("R2.tiny_page_dropped", not any(c["doc_url"].endswith("/q1") for c in strict), "page with <120 chars of content produced a chunk")
        long_chunks = [c for c in strict if c["doc_url"].endswith("/q2")]
        check("R2.tail_merged", bool(long_chunks) and all(len(c["text"]) >= 120 for c in long_chunks)
              and "Tail curto." in long_chunks[-1]["text"] and all(len(c["text"]) <= 900 + 120 for c in long_chunks),
              f"sizes={[len(c['text']) for c in long_chunks]}")
    except Exception as exc:  # noqa: BLE001
        check("R2.runtime", False, f"{type(exc).__name__}: {exc}")

    chunks_raw = [json.loads(ln) for ln in read("data/index/chunks.jsonl").splitlines() if ln.strip()]
    short = [c["chunk_id"] for c in chunks_raw if len(c.get("text", "")) < 120]
    check("R3.committed_index_regenerated", bool(chunks_raw) and not short, f"{len(short)} committed chunks shorter than 120 chars: {short[:3]}")

    calls = {"n": 0}
    try:
        emb = KeywordEmbedder(["crediário", "pix", "wi-fi"])
        fake_chunks = [
            {"chunk_id": "c1", "doc_url": "https://site.getnet.com.br/crediario/", "title": "Crediário", "market": "BR",
             "fetched_at": "2026-11-06T00:00:00+00:00", "doc_sha256": "x", "text": "Crediário: parcelamento em até 48x."},
            {"chunk_id": "c2", "doc_url": "https://site.getnet.com.br/pix/", "title": "Pix", "market": "BR",
             "fetched_at": "2026-11-06T00:00:00+00:00", "doc_sha256": "y", "text": "Venda com Pix na maquininha."},
        ]
        d = Path(tmp) / "idx"
        index.build_index(fake_chunks, emb, d, embedding_model="fake", dim=4)
        fake_retriever = rag_retriever.Retriever(index.VectorIndex.load(d), emb, min_score=0.6, top_k=2)

        def fake_get():
            calls["n"] += 1
            return fake_retriever

        original = rag_retriever.get_knowledge_retriever
        rag_retriever.get_knowledge_retriever = fake_get
        try:
            tool = TOOLS_BY_NAME["search_knowledge_base"]
            desc = tool.description or ""
            check("R4.tool_description_has_no_facts", not re.search(r"\d+\s*x\b", desc) and "36" not in desc,
                  f"tool description states product facts: {desc[:200]!r}")
            out = json.loads(tool.invoke({"query": "Em quantas vezes parcelo no crediário?"}))
            docs = out.get("documents", [])
            check("R4.tool_uses_retriever", calls["n"] >= 1 and out.get("status") == "success" and docs
                  and docs[0]["url"].endswith("/crediario/") and all(DOC_FIELDS <= set(x) for x in docs),
                  f"calls={calls['n']}, output={str(out)[:300]}")
            out = json.loads(tool.invoke({"query": "receita de bolo"}))
            check("R4.tool_abstains", out.get("status") == "abstain" and out.get("documents") == [], f"output={str(out)[:200]}")

            fake = ScriptedChatModel(responses=[
                AIMessage(content="", tool_calls=[{"name": "ask_knowledge_agent", "args": {"question": "crediário"}, "id": "k1"}]),
                AIMessage(content="", tool_calls=[{"name": "search_knowledge_base", "args": {"query": "crediário parcelas"}, "id": "k2"}]),
                AIMessage(content="Até 48x."), AIMessage(content="FINAL"),
            ])
            st = OrchestrationGraph(chat_model=fake).run_sync(user_id="cliente1988", message="crediário?", session_id="v3c-k")
            check("K6.knowledge_flow_real_index", st.agent_response == "FINAL" and "https://site.getnet.com.br/crediario/" in st.sources
                  and st.agents_used == ["SupervisorAgent", "KnowledgeAgent"], f"sources={st.sources}, agents={st.agents_used}")
        finally:
            rag_retriever.get_knowledge_retriever = original

        def broken():
            raise llm_mod.LLMNotConfiguredError("no key")

        rag_retriever.get_knowledge_retriever = broken
        try:
            out = json.loads(TOOLS_BY_NAME["search_knowledge_base"].invoke({"query": "pix"}))
            check("R5.tool_unavailable_without_key", out.get("status") == "unavailable" and out.get("documents") == [],
                  f"output={str(out)[:200]}")
        finally:
            rag_retriever.get_knowledge_retriever = original
    except Exception as exc:  # noqa: BLE001
        check("R4.runtime", False, f"{type(exc).__name__}: {exc}")

    try:
        reset = getattr(rag_retriever, "reset_knowledge_retriever", None)
        if reset:
            reset()
        settings.GEMINI_API_KEY = ""
        try:
            rag_retriever.get_knowledge_retriever()
            check("R6.real_retriever_requires_key", False, "get_knowledge_retriever() worked without GEMINI_API_KEY")
        except llm_mod.LLMNotConfiguredError:
            check("R6.real_retriever_requires_key", True)
        settings.GEMINI_API_KEY = "dummy-key-for-construction-only"
        if reset:
            reset()
        r = rag_retriever.get_knowledge_retriever()
        ok = (r.min_score == settings.RAG_MIN_SCORE and r.top_k == settings.RAG_TOP_K
              and len(r.index.chunks) == len(chunks_raw) and getattr(r.embedder, "task_type", None) == "RETRIEVAL_QUERY")
        check("R6.real_retriever_wiring", ok and rag_retriever.get_knowledge_retriever() is r,
              f"min_score={r.min_score}, top_k={r.top_k}, chunks={len(r.index.chunks)}, task={getattr(r.embedder, 'task_type', None)}")
    except Exception as exc:  # noqa: BLE001
        check("R6.runtime", False, f"{type(exc).__name__}: {exc}")
    finally:
        settings.GEMINI_API_KEY = ""
        if getattr(rag_retriever, "reset_knowledge_retriever", None):
            rag_retriever.reset_knowledge_retriever()


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks() -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    env0 = {k: v for k, v in os.environ.items() if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1")
    for script, allowed in PRIOR.items():
        r = run([sys.executable, f"scripts/{script}"], env=nested)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    static_checks()
    runtime_checks()
    suite_checks()
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
