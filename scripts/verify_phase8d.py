def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def static_checks() -> None:
    docker, ci, readme = read("Dockerfile"), read(".github/workflows/ci.yml"), read("README.md")
    line = "RUN chmod -R go-w /app/data /app/src /app/README.md && mkdir -p /app/state && chown -R appuser:appgroup /app/state"
    check("E1.dockerfile_read_only", line in docker and docker.find(line) < docker.find("USER appuser") and "777" not in docker
          and "CHECKPOINT_DB_PATH=state/checkpoints.db" in docker, "Dockerfile must strip group/other write from /app/data, /app/src and README.md before USER")
    check("E2.ci_write_probe", "! test -w /app/data/index/chunks.jsonl" in ci and "! test -w /app/src/main.py" in ci and "test -w /app/state" in ci
          and 'test "$(docker exec app id -u)" != "0"' in ci, "CI must probe that appuser cannot write the index or the code but can write /app/state")
    bad = [w for w in ("Zero Falsas Promessas", "preservado no volume Docker", "persistido em volume Docker") if w in readme]
    check("E3.readme_claims", not bad and "**Sem prazos nem filas**" in readme and readme.count("no volume `getnet_app_state`") >= 2,
          f"README still contains {bad} or misses the new wording")
    status = read("docs/STATUS.md")
    tail = status[status.rfind("Fase 8D"):] if "Fase 8D" in status else ""
    check("E4.status", bool(tail), "STATUS needs a 'Fase 8D' section")


