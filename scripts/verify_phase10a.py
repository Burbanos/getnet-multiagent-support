def section(text: str, start: str, stop: str) -> str:
    i = text.find(start)
    if i < 0:
        return ""
    j = text.find(stop, i + len(start))
    return text[i:j] if j > i else text[i:]


def canon_sha(records: list[dict]) -> str:
    return hashlib.sha256("\n".join(json.dumps(r, ensure_ascii=False, sort_keys=True) for r in records)
                          .encode("utf-8")).hexdigest()


def load_jsonl(rel: str) -> list[dict]:
    return [json.loads(ln) for ln in read(rel).splitlines() if ln.strip()]


def pattern_lists(source: str) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for node in ast.walk(ast.parse(source)):
        target = node.target if isinstance(node, ast.AnnAssign) else (node.targets[0] if isinstance(node, ast.Assign) else None)
        if isinstance(target, ast.Name) and target.id in ("INJECTION_PATTERNS", "TOXIC_PATTERNS") and node.value is not None:
            out[target.id] = ast.literal_eval(node.value)
    return out


def ref_category(text: str, inj: list[str], tox: list[str]) -> str | None:
    low = text.lower()
    if any(re.search(p, low, re.IGNORECASE) for p in inj):
        return "prompt_injection"
    if any(re.search(p, low, re.IGNORECASE) for p in tox):
        return "attack_request"
    return None


def ref_rates(cases: list[dict], blocked: dict[str, bool]) -> dict:
    blk = [c for c in cases if c["label"] == "block"]
    alw = [c for c in cases if c["label"] == "allow"]
    bb = [c["id"] for c in blk if blocked.get(c["id"], False)]
    ba = [c["id"] for c in alw if blocked.get(c["id"], False)]
    return {"n_block": len(blk), "n_allow": len(alw), "blocked_block": len(bb), "blocked_allow": len(ba),
            "block_rate": round(len(bb) / len(blk), 4) if blk else None,
            "false_positive_rate": round(len(ba) / len(alw), 4) if alw else None,
            "missed": sorted(c["id"] for c in blk if not blocked.get(c["id"], False)), "false_positives": sorted(ba)}


def ref_layer(cases: list[dict], blocked: dict[str, bool]) -> dict:
    kinds = sorted({c["kind"] for c in cases})
    return {"all": ref_rates(cases, blocked),
            "by_split": {s: ref_rates([c for c in cases if c["split"] == s], blocked) for s in ("dev", "holdout")},
            "by_kind": {k: {"n": sum(1 for c in cases if c["kind"] == k),
                            "blocked": sum(1 for c in cases if c["kind"] == k and blocked.get(c["id"], False))} for k in kinds}}


def fmt_ids(ids: list[str]) -> str:
    return ", ".join(ids) if ids else "nenhum"


def ref_markdown(rep: dict) -> str:
    def row(name: str, r: dict) -> str:
        return (f"| {name} | {r['blocked_block']}/{r['n_block']} ({r['block_rate']:.2f}) | "
                f"{r['blocked_allow']}/{r['n_allow']} ({r['false_positive_rate']:.2f}) |")
    m = rep["metrics"]
    lines = ["# Guardrail: camada de padrões", "",
             f"Conjunto: `{rep['set_path']}` (sha256 `{rep['set_sha256']}`), {rep['n_cases']} mensagens. "
             f"Gerado em {rep['generated_at']}.", "",
             "| Recorte | Injeções e ataques bloqueados | Legítimas bloqueadas (falsos positivos) |", "|---|---|---|",
             row("todos", m["all"]), row("dev", m["by_split"]["dev"]), row("holdout", m["by_split"]["holdout"]), "",
             f"Não bloqueadas pelos padrões: {fmt_ids(m['all']['missed'])}",
             f"Falsos positivos: {fmt_ids(m['all']['false_positives'])}"]
    return "\n".join(lines)


