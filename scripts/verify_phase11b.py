def module_checks(tmp: str) -> None:
    os.environ["GEMINI_API_KEY"] = ""
    sys.path.insert(0, str(ROOT))
    try:
        from src.eval import guardrail_eval as ge
    except Exception as exc:  # noqa: BLE001
        check("B2.holdout_valid", False, f"{type(exc).__name__}: {exc}")
        return
    # B2: the loader accepts the holdout; ids, origin, split and balance
    try:
        cases = ge.load_guardrail_set(ROOT / HOLDOUT)
        ids = [c["id"] for c in cases]
        bal = {(lab, lang): sum(1 for c in cases if c["label"] == lab and c["lang"] == lang)
               for lab in ("block", "allow") for lang in ("pt", "en")}
        ok = (ids == [f"ah{i:02d}" for i in range(1, 21)] and all(c["source"] == "author_holdout" and c["split"] == "holdout"
                                                                  for c in cases)
              and all(v == 5 for v in bal.values()))
        check("B2.holdout_valid", ok, f"ids={ids} balance={bal}", info=f"{len(cases)} messages, balance {bal}")
    except Exception as exc:  # noqa: BLE001
        check("B2.holdout_valid", False, f"{type(exc).__name__}: {exc}")
        return
    # B3: candidates file consistent with the selection (every chosen message maps to one candidate with the same labels)
    try:
        cands = [json.loads(ln) for ln in read(CANDIDATES).splitlines() if ln.strip()]
        by_id = {c["id"]: c for c in cases}
        sel = [c for c in cands if c["selected_as"] is not None]
        problems = []
        if len(cands) != 30 or [c["n"] for c in cands] != list(range(1, 31)) or any(set(c) != CAND_KEYS for c in cands):
            problems.append("30 candidates numbered 1..30 with the expected keys")
        if sorted(c["selected_as"] for c in sel) != sorted(by_id) or len(sel) != 20:
            problems.append("each holdout id must be selected exactly once")
        problems += [f"{c['selected_as']}: label/lang/kind differ" for c in sel if c["selected_as"] in by_id and
                     (c["label"], c["lang"], c["kind"]) != (by_id[c["selected_as"]]["label"], by_id[c["selected_as"]]["lang"],
                                                            by_id[c["selected_as"]]["kind"])]
        check("B3.candidates_consistent", not problems, "; ".join(problems[:4]))
    except Exception as exc:  # noqa: BLE001
        check("B3.candidates_consistent", False, f"{type(exc).__name__}: {exc}")
    # B4: disjoint from the 36-message set and absent from the classifier prompt
    try:
        old = {json.loads(ln)["text"].strip().lower() for ln in read("data/eval/guardrail_labeled.jsonl").splitlines() if ln.strip()}
        prompt = read("src/prompts/guardrail_classifier.md").lower()
        dup = [c["id"] for c in cases if c["text"].strip().lower() in old or c["text"].lower() in prompt]
        check("B4.disjoint_from_earlier_set", not dup, f"messages already in the 36-message set or in the classifier prompt: {dup}")
    except Exception as exc:  # noqa: BLE001
        check("B4.disjoint_from_earlier_set", False, f"{type(exc).__name__}: {exc}")


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks(tmp: str) -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH",
                         "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1", CHECKPOINT_DB_PATH=str(Path(tmp) / "nested" / "checkpoints.db"))
    for script, allowed in PRIOR.items():
        env_s = {k: v for k, v in nested.items() if k != "CHECKPOINT_DB_PATH"} if script == "verify_phase4b.py" else nested
        r = run([sys.executable, f"scripts/{script}"], env=env_s)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else (r.stdout + r.stderr)[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    marks = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in ("data/tickets.db", "data/checkpoints.db")}
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    m_all = re.search(r"(\d+) passed", last)
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "warning" not in last and bool(m_all) and int(m_all.group(1)) >= 331,
          f"{last} (want at least 331)", info=last)
    o = run([sys.executable, "-m", "src.eval", "offline"], env=env0)
    check("Q5.offline_eval", o.returncode == 0 and "offline: 6/6 passed" in o.stdout, (o.stdout + o.stderr)[-300:])
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")
    after = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in marks}
    check("Q4.tests_do_not_touch_data_dbs", marks == after, f"the test suite wrote {[p for p in marks if marks[p] != after[p]]}")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p11b_")
    static_checks()
    module_checks(tmp)
    suite_checks(tmp)
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
