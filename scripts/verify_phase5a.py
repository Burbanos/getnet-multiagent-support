FORBIDDEN = [r"\bem breve\b", r"\bshortly\b", r"\bsoon\b", r"\bminutos?\b", r"\bminutes?\b", r"\bhoras?\b", r"\bhours?\b",
             r"\b24 ?h\b", r"\bprazo\b", r"\bfila\b", r"\bqueue\b", r"\baguarde\b", r"\blogo\b", r"\bdentro de\b", r"\bwithin\b"]
CARD = "4111 1111 1111 1111"

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def promises(text: str) -> list[str]:
    return [p for p in FORBIDDEN if re.search(p, text or "", flags=re.I)]


def static_checks() -> None:
    src = read("src/core/tickets_db.py")
    bad = [w for w in ("/tmp", "TEMP", "gettempdir", "fallback", "chmod", "alt_conn", "DEFAULT_DB_PATH") if w in src]
    check("S1.no_silent_fallback", bool(src) and not bad, f"src/core/tickets_db.py still has: {bad}")
    env_ex, compose = read(".env.example"), read("docker-compose.yml")
    check("S2.config_documented", "TICKETS_DB_PATH=data/tickets.db" in env_ex and "TICKETS_DB_PATH" in compose,
          "TICKETS_DB_PATH must be in .env.example (data/tickets.db) and docker-compose.yml")
    readme = read("README.md")
    stale = [w for w in ("cálculo de custo por tokens", "acurácia de roteamento", "tela touch com Android") if w in readme]
    check("S3.readme_claims", not stale, f"README still claims: {stale}")
    check("S3.readme_tickets", all(w in readme for w in ("PATCH /tickets", "in_progress", "answered", "closed", "TICKETS_DB_PATH")),
          "README must document PATCH /tickets, the status lifecycle and TICKETS_DB_PATH")
    sp = read("src/prompts/supervisor.md")
    check("S4.supervisor_prompt", "escalate_to_human(reason, priority)" in sp and "could not be registered" in sp,
          "src/prompts/supervisor.md is not the reviewer's 5A version")


