def static_checks() -> None:
    print(f"INFO python {sys.version.split()[0]}")
    r = run([sys.executable, "-m", "ruff", "check", "--isolated", "--target-version", "py311", "--select", "E9",
             "--output-format", "concise", "scripts", "src", "tests"])
    check("E0.py311_syntax", r.returncode == 0, (r.stdout + r.stderr).strip()[-400:])

    raw = (ROOT / HOLDOUT2).read_bytes() if (ROOT / HOLDOUT2).exists() else b""
    sha = hashlib.sha256(raw.replace(b"\r\n", b"\n")).hexdigest()
    others_same = all(read(p) == base_text(p) for p in ("data/eval/cases_v2.jsonl", "data/eval/cases_routing_holdout.jsonl"))
    n = 0
    try:
        from src.eval.cases import load_cases
        n = len(load_cases(ROOT / HOLDOUT2))
    except Exception as exc:  # noqa: BLE001
        print(f"INFO holdout2 load error: {type(exc).__name__}: {exc}")
    check("E1.holdout2", sha == HOLDOUT2_SHA and n == 12 and others_same, f"{HOLDOUT2} must be the reviewer's file "
          f"(sha {sha[:12]}, {n} cases) and cases_v2.jsonl / cases_routing_holdout.jsonl must not change")

    sup_b, agt_b = base_text("src/tools/supervisor_tools.py"), base_text("src/tools/agent_tools.py")
    sup_ok = sup_b.count(OLD_K) == 1 and sup_b.count(OLD_S) == 1 and \
        read("src/tools/supervisor_tools.py") == sup_b.replace(OLD_K, NEW_K, 1).replace(OLD_S, NEW_S, 1)
    check("E3.supervisor_tools_file", sup_ok, "src/tools/supervisor_tools.py may change only by replacing the two "
          "docstrings with the prompt's texts")
    agt_ok = agt_b.count(OLD_D) == 1 and read("src/tools/agent_tools.py") == agt_b.replace(OLD_D, NEW_D, 1)
    check("E4.decline_tool_doc_file", agt_ok, "src/tools/agent_tools.py may change only by the two docstring lines "
          "inserted after the 'Dúvidas sobre o motivo de recusa' line")

    check("E5.old_tests_untouched", all(read(p) == base_text(p) for p in
                                         ("tests/test_answer_check_and_guards.py", "tests/fakes.py", "tests/conftest.py")),
          "existing tests must not change (only the new tests/test_tool_descriptions.py is added)")
    t = read(NEW_TEST)
    n_t = len(re.findall(r"^def test_", t, re.MULTILINE))
    check("E5.tests_written", n_t >= 3, f"{NEW_TEST} has {n_t} tests (want at least 3)", info=f"{n_t} tests")

    diff = run(["git", "diff", "--name-only", "--no-renames", BASE])
    untracked = run(["git", "ls-files", "--others", "--exclude-standard"]).stdout.split()
    author_untracked = {p for p in untracked if p.startswith(AUTHOR_FILES)}
    extra = sorted((set(diff.stdout.split()) | (set(untracked) - author_untracked)) - ALLOWED)
    check("E2.scope", diff.returncode == 0 and not extra, f"since 12D ({BASE}), 12E may change only {sorted(ALLOWED)}: "
          f"{extra or diff.stderr[-200:]}")
    committed = [p for p in run(["git", "ls-files"]).stdout.split() if p.startswith(AUTHOR_FILES)]
    check("E6.author_files_not_committed", not committed, f"the author's records and answers enter only in 12F: {committed}")
    check("E6.decisions_untouched", read("docs/DECISIONS.md") == base_text("docs/DECISIONS.md"),
          "docs/DECISIONS.md must not change")

    old = base_text("docs/STATUS.md")
    st = read("docs/STATUS.md")
    k = old.find("### Fase 12D")
