def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, bool(ok)))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None, cwd: Path | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=cwd or ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def base_text(rel: str) -> str:
    return run(["git", "show", f"{BASE}:{rel}"]).stdout.replace("\r\n", "\n")


def load_script(name: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


