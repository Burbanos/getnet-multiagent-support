def unanswered(messages: list[Any]) -> list[str]:
    from langchain_core.messages import AIMessage, ToolMessage
    answered = {m.tool_call_id for m in messages if isinstance(m, ToolMessage)}
    return [c.get("id") for m in messages if isinstance(m, AIMessage) for c in (m.tool_calls or []) if c.get("id") not in answered]


def main_checks(tmp: str) -> None:
    os.environ["GEMINI_API_KEY"] = ""
    sys.path.insert(0, str(ROOT))
    try:
        from langchain_core.messages import AIMessage, HumanMessage, ToolMessage
        from langchain_core.outputs import ChatGeneration, ChatResult
        from pydantic import Field

        from src.core.checkpointer import build_sqlite_checkpointer
        from src.core.graph import OrchestrationGraph
        from src.core.llm import LLMUnavailableError
        from tests.fakes import ScriptedChatModel
    except Exception as exc:  # noqa: BLE001
        check("M0.imports", False, f"{type(exc).__name__}: {exc}")
        return

    class Fake(ScriptedChatModel):
        responses: list[Any] = Field(default_factory=list)

        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            self.received.append(list(messages))
            r = self.responses.pop(0)
            if isinstance(r, Exception):
                raise r
            return ChatResult(generations=[ChatGeneration(message=r)])

    def call(*pairs: tuple[str, str, dict]) -> AIMessage:
        return AIMessage(content="", tool_calls=[{"name": n, "id": i, "args": a} for n, i, a in pairs])

    def build(name: str, responses: list[Any]) -> tuple[Any, Any, dict]:
        fake = Fake(responses=responses)
        orch = OrchestrationGraph(chat_model=fake, checkpointer=build_sqlite_checkpointer(Path(tmp) / f"{name}.db"))
        return fake, orch, {"configurable": {"thread_id": f"cliente1988:{name}"}}

    def tool_msgs(orch, cfg) -> dict[str, str]:
        msgs = orch.graph.get_state(cfg).values.get("messages", [])
        return {m.tool_call_id: str(m.content) for m in msgs if isinstance(m, ToolMessage)}

    # 1. Provider failure inside the support specialist (the audit's probe): 503 path.
    try:
        fake, orch, cfg = build("p1", [call(("ask_support_agent", "c1", {"request": "saldo de ontem"})),
                                       RuntimeError("503 overloaded")])
        raised = None
        try:
            orch.run_sync(user_id="cliente1988", session_id="p1", message="Quando recebo as vendas de ontem?")
        except LLMUnavailableError as exc:
            raised = exc
        snap = orch.graph.get_state(cfg)
        msgs = snap.values.get("messages", [])
        tm = tool_msgs(orch, cfg)
        payload = json.loads(tm.get("c1", "{}") or "{}") if tm.get("c1", "").startswith("{") else {}
        check("C1.provider_failure_closed", raised is not None and not unanswered(msgs) and snap.next == ()
              and payload.get("status") == "error" and payload.get("error") == "LLMUnavailableError",
              f"raised={type(raised).__name__ if raised else None}, unanswered={unanswered(msgs)}, next={snap.next}, c1={tm.get('c1')!r}")

        # 2. The next turn: the model never receives an orphan tool call and the turn completes.
        fake.responses = [AIMessage(content="Tudo certo agora.")]
        fake.received.clear()
        st = orch.run_sync(user_id="cliente1988", session_id="p1", message="E agora?")
        sent = fake.received[0] if fake.received else []
        check("C2.next_turn_no_orphan", st.agent_response == "Tudo certo agora." and sent and not unanswered(sent)
              and isinstance(sent[-1], HumanMessage), f"response={st.agent_response!r}, unanswered sent={unanswered(sent)}")
    except Exception as exc:  # noqa: BLE001
        check("C1.provider_failure_closed", False, f"{type(exc).__name__}: {exc}")

    # 3. Two tool calls in one message; the second specialist fails: both calls closed.
    try:
        fake, orch, cfg = build("p3", [call(("ask_knowledge_agent", "k1", {"question": "O que é a Get Smart?"}),
                                            ("ask_support_agent", "s1", {"request": "saldo"})),
                                       AIMessage(content="A Get Smart é uma maquininha."),
                                       RuntimeError("503 overloaded")])
        try:
            orch.run_sync(user_id="cliente1988", session_id="p3", message="Get Smart e meu saldo")
        except LLMUnavailableError:
            pass
        snap = orch.graph.get_state(cfg)
        tm = tool_msgs(orch, cfg)
        check("C3.parallel_calls_closed", not unanswered(snap.values.get("messages", [])) and {"k1", "s1"} <= set(tm)
              and snap.next == (), f"tool messages={sorted(tm)}, next={snap.next}")
    except Exception as exc:  # noqa: BLE001
        check("C3.parallel_calls_closed", False, f"{type(exc).__name__}: {exc}")

    # 4. Internal error (non-LLM exception in the tools node): the turn returns internal_error, the call is closed.
    try:
        fake, orch, cfg = build("p4", [call(("ask_support_agent", "c4", {"request": "saldo"}))])

        def boom(*a, **k):
            raise KeyError("unexpected")

        orch.support_agent.run = boom
        st = orch.run_sync(user_id="cliente1988", session_id="p4", message="Meu saldo?")
        snap = orch.graph.get_state(cfg)
        tm = tool_msgs(orch, cfg)
        check("C4.internal_error_closed", st.error == "internal_error" and not unanswered(snap.values.get("messages", []))
              and '"internal_error"' in tm.get("c4", "") and snap.next == (),
              f"error={st.error}, c4={tm.get('c4')!r}, next={snap.next}")
    except Exception as exc:  # noqa: BLE001
        check("C4.internal_error_closed", False, f"{type(exc).__name__}: {exc}")

    # 5. Failure before any tool call: nothing is added to the history.
    try:
        fake, orch, cfg = build("p5", [RuntimeError("503 overloaded")])
        try:
            orch.run_sync(user_id="cliente1988", session_id="p5", message="Oi")
        except LLMUnavailableError:
            pass
        msgs = orch.graph.get_state(cfg).values.get("messages", [])
        check("C5.no_tool_call_nothing_added", [type(m).__name__ for m in msgs] == ["HumanMessage"],
              f"history after a failure without tool calls: {[type(m).__name__ for m in msgs]}")
    except Exception as exc:  # noqa: BLE001
        check("C5.no_tool_call_nothing_added", False, f"{type(exc).__name__}: {exc}")

    # 6. A successful turn is untouched by the new code (no extra tool message, normal end).
    try:
        fake, orch, cfg = build("p6", [call(("ask_support_agent", "c6", {"request": "saldo"})),
                                       AIMessage(content="Recebe hoje."), AIMessage(content="Você recebe hoje.")])
        st = orch.run_sync(user_id="cliente1988", session_id="p6", message="Quando recebo?")
        tm = tool_msgs(orch, cfg)
        check("C6.success_path_unchanged", st.agent_response == "Você recebe hoje." and list(tm) == ["c6"]
              and '"status": "ok"' in tm["c6"] and orch.graph.get_state(cfg).next == (), f"response={st.agent_response!r}, tool messages={tm}")
    except Exception as exc:  # noqa: BLE001
        check("C6.success_path_unchanged", False, f"{type(exc).__name__}: {exc}")


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks(tmp: str) -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH",
                         "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1", CHECKPOINT_DB_PATH=str(Path(tmp) / "nested" / "checkpoints.db"))
    for script, allowed in PRIOR.items():
        env_s = {k: v for k, v in nested.items() if k != "CHECKPOINT_DB_PATH"} if script == "verify_phase4b.py" else nested
        r = run([sys.executable, f"scripts/{script}"], env=env_s)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else (r.stdout + r.stderr)[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    marks = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in ("data/tickets.db", "data/checkpoints.db")}
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "warning" not in last, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")
    after = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in marks}
    check("Q4.tests_do_not_touch_data_dbs", marks == after, f"the test suite wrote {[p for p in marks if marks[p] != after[p]]}")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p9c_")
    static_checks()
    main_checks(tmp)
    suite_checks(tmp)
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
