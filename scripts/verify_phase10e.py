def ref_fx_success(cur: str, name: str, url: str, requested: str | None) -> dict:
    rows = [r for r in fx(name)["value"] if r["tipoBoletim"] == "Fechamento" and (requested is None or r["dataHoraCotacao"].startswith(requested))]
    best = max(rows, key=lambda r: r["dataHoraCotacao"])
    names = {m["simbolo"]: m["nomeFormatado"] for m in fx("ptax_moedas")["value"]}
    unit = f"BRL per 1 {cur}"
    return {"status": "success", "source": CONSTS["FX_SOURCE"], "source_url": url, "currency": cur, "currency_name": names[cur],
            "rate_note": CONSTS["FX_RATE_NOTE"], "bulletin": "Fechamento", "quoted_at": best["dataHoraCotacao"],
            "reference_date": best["dataHoraCotacao"][:10], "requested_date": requested,
            "buy": {"value": best["cotacaoCompra"], "unit": unit}, "sell": {"value": best["cotacaoVenda"], "unit": unit}}


