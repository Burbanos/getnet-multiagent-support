def static_checks() -> None:
    demo, readme = read("src/static/demo.html"), read("README.md")
    bad = [w for w in BANNED_DEMO if w in demo]
    check("A0.demo_real_fields", not bad and "meta.tokens" in demo and "meta.estimated_cost_usd" in demo and "X-API-Key" in demo
          and "confidenceMetric" not in demo, f"demo.html: remove {bad}; show tokens and cost from the response metadata")
    bad = [w for w in BANNED_README if w in readme]
    check("A0.readme_leftovers", not bad, f"README still contains {bad}")
    ci = readme[readme.find("### Pipeline de Integração Contínua"):readme.find("## 6.")]
    check("A0.readme_ci", "docker" in ci.lower() and "/health" in ci, "README CI section must say CI also builds the Docker image and probes /health")
    dc = readme[readme.find("### Execução via Docker Compose"):readme.find("### Execução Local")]
    check("A0.readme_compose_keys", "API_KEYS" in dc and "python -m src.core.auth hash" in dc,
          "README Docker Compose section must say APP_ENV=production requires API_KEYS and how to create the hash")


def main_checks(tmp: str) -> None:
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["CHECKPOINT_DB_PATH"] = str(Path(tmp) / "checkpoints.db")
    os.environ["GEMINI_API_KEY"] = ""
    os.environ.pop("API_KEYS", None)
    os.environ["APP_ENV"] = "development"
    sys.path.insert(0, str(ROOT))
    try:
        from fastapi.testclient import TestClient

        import src.core.graph as graph_mod
        from src.config import settings
        from src.main import app
        from src.tools.supervisor_tools import SUPERVISOR_TOOLS
    except Exception as exc:  # noqa: BLE001
        check("A1.imports", False, f"{type(exc).__name__}: {exc}")
        return
    kt, st = getattr(graph_mod, "KNOWLEDGE_TOOLS", None), getattr(graph_mod, "SUPPORT_TOOLS", None)
    check("A1.tool_constants", bool(kt) and bool(st), "src/core/graph.py must define KNOWLEDGE_TOOLS and SUPPORT_TOOLS")
    if not (kt and st):
        return
    src_graph = read("src/core/graph.py")
    check("A1.specialists_use_constants", "tools=KNOWLEDGE_TOOLS" in src_graph and "tools=SUPPORT_TOOLS" in src_graph,
          "the specialists must be built from KNOWLEDGE_TOOLS and SUPPORT_TOOLS (single source of truth)")
    try:
        with TestClient(app) as client:
            r = client.get("/agents")
        data = r.json()
        txt = r.text
        agents = {a.get("name"): a for a in data.get("agents", [])}
        want = {"SupervisorAgent": [t.name for t in SUPERVISOR_TOOLS], "KnowledgeAgent": [t.name for t in kt],
                "SupportAgent": [t.name for t in st], "GuardrailAgent": []}
        got = {n: agents.get(n, {}).get("tools") for n in want}
        check("A2.agents_from_code", r.status_code == 200 and got == want, f"tools per agent: {got} (want {want})")
        models = data.get("models", {})
        check("A2.models_from_settings", models.get("primary") == settings.LLM_MODEL
              and models.get("fallback") == (settings.LLM_FALLBACK_MODEL or None), f"models={models}")
        all_tools = [*SUPERVISOR_TOOLS, *kt, *st]
        rows = {t.get("name"): t for t in data.get("tools", [])}
        wrong = [t.name for t in all_tools if t.name not in rows or rows[t.name].get("args") != sorted(t.args)
                 or rows[t.name].get("description") != (t.description or "").strip().splitlines()[0]]
        check("A3.tool_rows", not wrong and set(rows) == {t.name for t in all_tools},
              f"tool rows must be generated from the tool objects (name, first description line, sorted args): {wrong}")
        bad = [w for w in BANNED_AGENTS if w in txt]
        check("A3.no_fictional_names", not bad and "MemorySaver" not in txt and "data/" not in txt, f"/agents contains {bad}")
    except Exception as exc:  # noqa: BLE001
        check("A2.agents_from_code", False, f"{type(exc).__name__}: {exc}")


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks(tmp: str) -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    tests = read("tests/test_agents_endpoint.py")
    n_tests = len(re.findall(r"^def test_", tests, flags=re.M))
    check("Q0.agents_tests", n_tests >= 3, f"tests/test_agents_endpoint.py has {n_tests} tests (need >= 3)")
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH",
                         "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1", CHECKPOINT_DB_PATH=str(Path(tmp) / "nested" / "checkpoints.db"))
    for script, allowed in PRIOR.items():
        env_s = {k: v for k, v in nested.items() if k != "CHECKPOINT_DB_PATH"} if script == "verify_phase4b.py" else nested
        r = run([sys.executable, f"scripts/{script}"], env=env_s)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    marks = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in ("data/tickets.db", "data/checkpoints.db")}
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "warning" not in last, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")
    after = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in marks}
    check("Q4.tests_do_not_touch_data_dbs", marks == after, f"the test suite wrote {[p for p in marks if marks[p] != after[p]]}")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p8a_")
    static_checks()
    main_checks(tmp)
    suite_checks(tmp)
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
