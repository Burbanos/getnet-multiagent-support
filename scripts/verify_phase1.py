"""Phase 1 acceptance checks (docs/SPEC.md). Cross-platform, stdlib only.

Usage (from the repository root):
    python scripts/verify_phase1.py --part a
    python scripts/verify_phase1.py --part b
    python scripts/verify_phase1.py            # both parts

Exit code 0 only if every check of the selected part(s) passes.
Do NOT edit this file to make checks pass: the reviewer runs an independent copy.
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

ROOT = Path.cwd()
RESULTS: list[tuple[str, bool, str]] = []

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(check_id: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((check_id, ok, detail))
    status = "PASS" if ok else "FAIL"
    extra = info if ok else detail
    print(f"{status} {check_id}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def py_files(*dirs: str) -> list[Path]:
    files: list[Path] = []
    for d in dirs:
        base = ROOT / d
        if base.exists():
            files.extend(p for p in base.rglob("*.py") if ".venv" not in p.parts)
    return files


def find_in_files(pattern: str, files: list[Path], flags: int = 0) -> list[str]:
    rx = re.compile(pattern, flags)
    hits = []
    for f in files:
        for n, line in enumerate(f.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            if rx.search(line):
                hits.append(f"{f.relative_to(ROOT)}:{n}: {line.strip()[:100]}")
    return hits


def run(cmd: list[str], env: dict | None = None, timeout: int = 900) -> subprocess.CompletedProcess:
    return subprocess.run(
        cmd, cwd=ROOT, env=env, capture_output=True, text=True,
        encoding="utf-8", errors="replace", timeout=timeout,
    )


# ----------------------------------------------------------------------------- part A
def part_a() -> None:
    legacy = ["src/agents/router.py", "src/agents/support.py", "src/agents/escalation.py"]
    present = [f for f in legacy if (ROOT / f).exists()]
    check("A1.files", not present, f"still present: {present}" if present else "")

    hits = find_in_files(
        r"generate_text|RouterAgent|CustomerSupportAgent|HumanEscalationAgent|\bKnowledgeAgent\b|SupervisorLLMEngine",
        py_files("src", "tests"),
    )
    check("A1.refs", not hits, "; ".join(hits[:5]))

    llm = read("src/core/llm.py")
    check("A2.rules_engine_named", "class RulesFallbackEngine" in llm, "class RulesFallbackEngine not found")
    check("A2.no_fake_gemini", "genai" not in llm and "has_gemini" not in llm, "Gemini client code still in llm.py")
    hard = [w for w in ["touch", "android", "bobina", "teclado", "3.367,20", "saldo insuficiente no banco",
                        "Clássica", "classica", "Get Smart"]
            if w.lower() in llm.lower()]
    check("A2.no_hardcoded_answers", not hard, f"found in llm.py: {hard}")

    est = find_in_files(r"//\s*4|0\.000000075|0\.00000030", py_files("src"))
    check("A3.no_token_estimation", not est, "; ".join(est[:5]))
    graph = read("src/core/graph.py")
    check("A3.no_tool_aliases", "tool_aliases" not in graph, "tool_aliases still in graph.py")

    tmp = tempfile.mkdtemp(prefix="verify_p1_")
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ.setdefault("LLM_PROVIDER", "mock")
    sys.path.insert(0, str(ROOT))
    try:
        from fastapi.testclient import TestClient  # noqa: PLC0415
        from src.main import app  # noqa: PLC0415

        client = TestClient(app)
        r = client.post("/chat", json={"message": "Quais são as taxas da maquininha?", "user_id": "cliente1988"})
        meta = r.json().get("metadata", {}) if r.status_code == 200 else {}
        check("A4.chat_200", r.status_code == 200, f"status {r.status_code}")
        check("A4.decision_engine", meta.get("decision_engine") == "rules_fallback",
              f"decision_engine={meta.get('decision_engine')!r}")
        check("A4.tokens_null", meta.get("tokens") is None, f"tokens={meta.get('tokens')!r}")
        check("A4.cost_null", meta.get("estimated_cost_usd") is None, f"cost={meta.get('estimated_cost_usd')!r}")
        check("A4.no_confidence", "confidence" not in meta, "confidence still in metadata")

        real_tools = {"get_settlement_status", "diagnose_declined_transaction", "diagnose_terminal",
                      "search_knowledge_base", "search_web", "escalate_to_human"}
        extra = set(meta.get("tools_used", [])) - real_tools
        check("A4.tools_used_real", not extra, f"non-tool names: {sorted(extra)}")

        agents_txt = client.get("/agents").text
        bad = [s for s in ["Gemini 2.0", "< 0.35", "bind_tools"] if s in agents_txt]
        check("A5.agents_endpoint_truthful", not bad, f"found: {bad}")

        from src.agents.knowledge import get_retriever  # noqa: PLC0415

        docs = get_retriever()._lexical_fallback("taxas maquininha", top_k=2)
        fabricated = [d.get("id") for d in docs if "similarity" in d or "distance" in d]
        modes = {d.get("retrieval_mode") for d in docs}
        check("A6.lexical_no_fake_similarity", bool(docs) and not fabricated,
              f"docs={len(docs)}, with similarity/distance: {fabricated}")
        check("A6.retrieval_mode_tagged", modes == {"lexical_fallback"}, f"modes={modes}")
    except Exception as exc:  # report, do not crash
        check("A4.runtime", False, f"{type(exc).__name__}: {exc}")

    demo = read("src/static/demo.html")
    check("A7.demo_no_fake_metrics", "Similaridade Cosseno ChromaDB" not in demo and "toFixed(7)" not in demo,
          "demo.html still renders confidence/cost")


# ----------------------------------------------------------------------------- part B
NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def part_b() -> None:
    tracked = run(["git", "ls-files", "data"]).stdout.split()
    check("B1.tickets_db_untracked", not any(t.endswith(".db") for t in tracked), f"tracked: {tracked}")
    check("B1.gitignore", re.search(r"data/\*\.db|\*\.db", read(".gitignore")) is not None, "no *.db rule")

    tests_txt = "\n".join(p.read_text(encoding="utf-8", errors="replace") for p in py_files("tests"))
    fake = [s for s in ["_evaluate_faithfulness", "_evaluate_relevance", "llm_as_a_judge",
                        "test_llm_api_resilience"] if s in tests_txt]
    check("B2.fake_judge_removed", not fake, f"found: {fake}")
    check("B2.schema_test_kept", "def test_eval_dataset_schema" in tests_txt, "test_eval_dataset_schema missing")

    pyproject = read("pyproject.toml")
    check("B3.pytest_config", "network" in pyproject and "addopts" in pyproject
          and "asyncio_default_fixture_loop_scope" in pyproject, "pyproject.toml pytest config incomplete")
    check("B3.ruff_config", "[tool.ruff" in pyproject, "no [tool.ruff] section")

    req = read("requirements.txt").lower()
    dev = read("requirements-dev.txt").lower()
    check("B4.runtime_no_pytest", "pytest" not in req, "pytest still in requirements.txt")
    check("B4.langchain_core", "langchain-core" in req or "langchain_core" in req, "langchain-core not declared")
    check("B4.dev_reqs", all(x in dev for x in ["pytest", "ruff"]), "requirements-dev.txt missing pytest/ruff")
    lock = read("requirements.lock").lower()
    check("B4.lock_regenerated", bool(lock) and "langchain-core" in lock and "pytest==" not in lock,
          "requirements.lock missing, stale (no langchain-core) or contains pytest")
    check("B4.docker_uses_lock", "requirements.lock" in read("Dockerfile"), "Dockerfile does not install the lock")

    ci = read(".github/workflows/ci.yml")
    missing = [s for s in ["requirements-dev.txt", "ruff check", "pytest", "docker build", "/health", "3.11"]
               if s not in ci]
    check("B5.ci_steps", not missing, f"missing in ci.yml: {missing}")

    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("B6.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])

    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = {k: v for k, v in os.environ.items() if k != "TICKETS_DB_PATH"}  # tests must isolate themselves
    env["PYTHONPATH"] = plugdir + os.pathsep + os.environ.get("PYTHONPATH", "")
    tests = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    summary = [ln for ln in tests.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = summary[-1] if summary else tests.stdout[-300:]
    check("B7.pytest_passes_offline", tests.returncode == 0, last, info=last)
    after = run(["git", "status", "--porcelain"]).stdout
    check("B7.tree_unchanged_by_tests", before == after, f"changed by tests: {after}")

    readme = read("README.md")
    forbidden = ["LLM-as-a-Judge", "routing-brightgreen", "tests-56", "bind_tools", "Gemini 2.0",
                 "abandona completamente", "15 manuais", "sem constantes", "exigem o cabeçalho", "abém-se",
                 "Tool Calling nativo"]
    found = [s for s in forbidden if s.lower() in readme.lower()]
    check("B8.readme_claims_removed", not found, f"still in README: {found}")
    check("B8.readme_limitations", "Limitações atuais" in readme, "section 'Limitações atuais' missing")

    status_md = read("docs/STATUS.md")
    check("B9.status_questions_section", "Perguntas / divergências com o SPEC" in status_md,
          "STATUS.md missing 'Perguntas / divergências com o SPEC'")
    check("B9.spec_present", (ROOT / "docs/SPEC.md").exists(), "docs/SPEC.md missing")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--part", choices=["a", "b", "all"], default="all")
    args = ap.parse_args()
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    if args.part in ("a", "all"):
        part_a()
    if args.part in ("b", "all"):
        part_b()
    failed = [c for c, ok, _ in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
