def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def section(text: str, start: str, stop: str) -> str:
    i = text.find(start)
    if i < 0:
        return ""
    j = text.find(stop, i + len(start))
    return text[i:j] if j > i else text[i:]


def expected_files() -> dict[str, str]:
    """Run the transformation of docs/phase-prompts/11F.md in a scratch directory and return the three files."""
    prompt = read("docs/phase-prompts/11F.md")
    m = re.search(r"```python\n(.*?)\n```", prompt, re.DOTALL)
    if not m:
        return {}
    tmp = Path(tempfile.mkdtemp(prefix="verify_p11f_split_"))
    (tmp / "docs").mkdir()
    code = m.group(1).replace('["git", "show"', f'["git", "-C", {str(ROOT)!r}, "show"')
    (tmp / "split.py").write_text(code, encoding="utf-8")
    r = subprocess.run([sys.executable, str(tmp / "split.py")], cwd=tmp, capture_output=True, text=True, encoding="utf-8",
                       errors="replace", timeout=300)
    if r.returncode != 0:
        print("INFO split failed: " + (r.stdout + r.stderr)[-300:])
        return {}
    return {p: (tmp / p).read_bytes().decode("utf-8") for p in ("docs/STATUS.md", "docs/status-history.md", "docs/history.md")}


