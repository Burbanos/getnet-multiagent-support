# ------------------------------------------------------------------ reference implementation

def ref_sha(cases: list[dict]) -> str:
    return hashlib.sha256("\n".join(json.dumps(c, ensure_ascii=False, sort_keys=True) for c in cases).encode("utf-8")).hexdigest()


def norm(s: str) -> str:
    return " ".join((s or "").split()).lower()


def ref_lang(text: str) -> str:
    pt = en = 0
    for w in (text or "").lower().split():
        w = w.strip(STRIP)
        pt += w in PT_WORDS
        en += w in EN_WORDS
    return "pt" if pt > en else "en" if en > pt else "unknown"


def ref_eval(case: dict, result: dict) -> dict:
    out = {k: None for k in CHECKS}
    if result.get("status") != "ok" or not result.get("turns"):
        return {"checks": out, "passed": False}
    t = result["turns"][-1]
    e = case["expect"]
    spec = {a for a in t.get("agents_used", []) if a in SPECIALISTS}
    used = t.get("tools_used", [])
    resp = norm(t.get("response", ""))
    if e["agents"] is not None:
        out["routing_ok"] = spec == set(e["agents"])
    if e["tools_all"] or e["tools_none"]:
        out["tools_ok"] = all(x in used for x in e["tools_all"]) and not any(x in used for x in e["tools_none"])
    if e["escalate"] is not None:
        out["escalation_ok"] = (t.get("ticket_id") is not None) == e["escalate"]
    if e["priority"] is not None:
        out["priority_ok"] = t.get("ticket_priority") == e["priority"]
    out["blocked_ok"] = (not t.get("is_safe", True)) == e["blocked"]
    if e["gold_urls"]:
        out["sources_ok"] = any(u in t.get("sources", []) for u in e["gold_urls"])
    if e["facts_any"]:
        out["facts_ok"] = all(any(norm(a) in resp for a in grp) for grp in e["facts_any"])
    if e["facts_none"]:
        out["facts_none_ok"] = not any(norm(x) in resp for x in e["facts_none"])
    if not e["blocked"] and t.get("is_safe", True) and not t.get("handoff"):
        out["language_ok"] = ref_lang(t.get("response", "")) == case["lang"]
    return {"checks": out, "passed": all(v for v in out.values() if v is not None)}


def rate(vals):
    vals = [v for v in vals if v is not None]
    return (sum(1 for v in vals if v) / len(vals)) if vals else None


def pct(xs, p):
    if not xs:
        return None
    s = sorted(xs)
    return s[max(0, math.ceil(p * len(s)) - 1)]


def ref_aggregate(cases: list[dict], results: list[dict]) -> dict:
    by_id = {r["id"]: r for r in results}
    rows = []
    for c in cases:
        r = by_id.get(c["id"])
        if r is None:
            continue
        ev = ref_eval(c, r)
        rows.append((c, r, ev))
    ok = [(c, r, ev) for c, r, ev in rows if r.get("status") == "ok"]
    m = {name.replace("_ok", "") + "_rate": rate([ev["checks"][name] for _, _, ev in ok]) for name in CHECKS}
    m["pass_rate"] = rate([ev["passed"] for _, _, ev in ok])
    exp = [(c["expect"]["escalate"], r["turns"][-1].get("ticket_id") is not None) for c, r, _ in ok if c["expect"]["escalate"] is not None]
    tp = sum(1 for a, b in exp if a and b)
    pred = sum(1 for _, b in exp if b)
    pos = sum(1 for a, _ in exp if a)
    m["escalation_precision"] = tp / pred if pred else None
    m["escalation_recall"] = tp / pos if pos else None
    lat = [sum(t.get("latency_ms", 0.0) for t in r["turns"]) for _, r, _ in ok]
    m["latency_ms_p50"], m["latency_ms_p95"] = pct(lat, 0.5), pct(lat, 0.95)
    tok = [sum((t.get("tokens") or {}).get("total_tokens", 0) for t in r["turns"]) for _, r, _ in ok
           if any(t.get("tokens") for t in r["turns"])]
    m["tokens_total"] = sum(tok) if tok else None
    m["tokens_mean_per_case"] = (sum(tok) / len(tok)) if tok else None
    groups = {}
    for key in ("category", "lang"):
        g = {}
        for c, _, ev in ok:
            g.setdefault(c[key], []).append(ev["passed"])
        groups[key] = {k: {"n": len(v), "pass_rate": rate(v)} for k, v in sorted(g.items())}
    off = [ev["passed"] for c, _, ev in ok if c["official"]]
    return {"n_cases": len(cases), "n_evaluated": len(ok), "n_errors": sum(1 for _, r, _ in rows if r.get("status") != "ok"),
            "error_ids": sorted(r["id"] for _, r, _ in rows if r.get("status") != "ok"), "metrics": m,
            "by_category": groups["category"], "by_lang": groups["lang"], "official": {"n": len(off), "pass_rate": rate(off)},
            "per_case": {c["id"]: ev for c, _, ev in rows}}


def close(a, b) -> bool:
    if a is None or b is None:
        return a is None and b is None
    return math.isclose(float(a), float(b), abs_tol=1e-6)


