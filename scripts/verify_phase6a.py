def synth_result(case: dict, rng: random.Random) -> dict:
    if rng.random() < 0.08:
        return {"id": case["id"], "status": "error", "error_type": "LLMUnavailableError", "turns": []}
    e = case["expect"]
    turns = []
    for i, _ in enumerate(case["turns"]):
        agents = ["SupervisorAgent"] + rng.sample(sorted(SPECIALISTS), rng.randint(0, 2))
        if e["agents"] is not None and rng.random() < 0.7:
            agents = ["SupervisorAgent"] + list(e["agents"])
        tools = rng.sample(LEAF, rng.randint(0, 3))
        if rng.random() < 0.6:
            tools = list(dict.fromkeys(tools + list(e["tools_all"])))
        facts = " ".join(rng.choice(g) for g in e["facts_any"]) if rng.random() < 0.6 else ""
        leak = rng.choice(e["facts_none"]) if e["facts_none"] and rng.random() < 0.2 else ""
        body = rng.choice(["Você pode fazer isso pelo aplicativo, com a sua conta e também no portal.",
                           "You can do this in the app, and it will be available for your account.",
                           "48 12 0000"])
        ticket = (f"GET-TKT-X-{i}" if (e["escalate"] if rng.random() < 0.8 else not e["escalate"]) else None) if e["escalate"] is not None else None
        turns.append({
            "message": case["turns"][i], "response": f"{body} {facts} {leak}".strip(), "agents_used": agents, "tools_used": tools,
            "sources": rng.sample(e["gold_urls"], 1) if e["gold_urls"] and rng.random() < 0.6 else ["https://x.example/"],
            "retrieved_docs": [], "ticket_id": ticket, "ticket_priority": rng.choice(["standard", "high"]) if ticket else None,
            "is_safe": (not e["blocked"]) if rng.random() < 0.85 else e["blocked"], "handoff": None,
            "llm_model": rng.choice([None, "gemini-3.5-flash"]), "latency_ms": round(rng.uniform(10, 9000), 1),
            "tokens": {"input_tokens": 10, "output_tokens": 5, "total_tokens": rng.randint(15, 900)} if rng.random() < 0.7 else None})
    return {"id": case["id"], "status": "ok", "error_type": None, "turns": turns}


