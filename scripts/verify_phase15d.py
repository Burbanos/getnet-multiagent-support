def compose_checks() -> None:
    sys.path.insert(0, str(ROOT / "scripts"))
    import importlib
    ce = importlib.import_module("compose_evidence")
    keys, spec = ce.make_api_keys()
    calls = []
    issued = {}

    def fake_http(method, url, *, api_key=None, bearer_token=None, body=None, timeout=45.0):
        calls.append((method, url, api_key, bearer_token, (body or {}).get("refresh_token")))
        if url.endswith("/auth/token"):
            n = len(issued)
            acc, ref = f"acc-{n}", f"ref-{n}"
            issued[acc] = api_key
            issued[ref] = api_key
            return 200, {}, {"access_token": acc, "refresh_token": ref}
        if url.endswith("/auth/refresh"):
            tok = (body or {}).get("refresh_token")
            if tok in issued and not tok.endswith("-used"):
                n = len(issued)
                acc, ref = f"acc-{n}", f"ref-{n}"
                issued[acc] = issued[tok]
                issued[ref] = issued[tok]
                issued[tok + "-used"] = issued[tok]
                spent = [c for c in calls[:-1] if c[4] == tok]
                if spent:
                    return 401, {}, {}
                return 200, {}, {"access_token": acc, "refresh_token": ref}
            return 401, {}, {}
        if bearer_token in issued:
            return 200, {}, {}
        return 401, {}, {}

    res = ce.auth_checks(keys, "probe-15d", http=fake_http)
    used_keys = {c[2] for c in calls if c[2]}
    bearer_owner = {issued.get(c[3]) for c in calls if c[3] and c[3] in issued}
    names = {"token_cross_replica", "tampered_token_rejected", "refresh_rotation_cross_replica",
             "refresh_reuse_revokes_family"}
    src = read("scripts/compose_evidence.py")
    run_body = src[src.find("def run_compose_evidence"):]
    check("H1.compose_auth_key_isolated",
          set(keys) == {"auth", "conversation", "ticket", "pii", "rate_limit", "operator"}
          and spec.count(":cliente_auth:customer") == 1
          and used_keys == {keys["auth"]} and bearer_owner <= {keys["auth"]}
          and set(res.get("checks", {})) == names and "auth_checks(keys" in run_body,
          f"keys={sorted(keys)} used_keys_are_auth={used_keys == {keys['auth']}} checks={res.get('checks')} "
          f"called_in_run={'auth_checks(keys' in run_body}")


