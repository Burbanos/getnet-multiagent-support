def delegation_checks() -> None:
    from src.agents import planner as pl

    tp = pl.TurnPlan
    field = tp.model_fields.get("terminal_issue")
    lit_ok = field is not None and field.default == "none" and set(getattr(field.annotation, "__args__", ())) == {
        "none", "not_working"}

    def mk(steps, **kw):
        base = dict(reply_language="en", scope="support", escalation_request="none", action_confirmation="none",
                    code_source="none", terminal_issue="none")
        base.update(kw)
        return tp(**base, steps=[pl.PlanStep(goal=g, delegate=d) for g, d in steps])

    cases = []

    def expect(name, plan, delegates, reason):
        before = plan.model_dump()
        out, why = pl.apply_delegate_rule(plan)
        got = [s.delegate for s in out.steps]
        ok = got == delegates and why == reason and plan.model_dump() == before
        cases.append((name, ok, f"{name}: got {got} {why!r}, expected {delegates} {reason!r}"))
        return out

    expect("declined_flip", mk([("Explain code 96", "knowledge")], code_source="declined_sale"), ["support"], "declined_sale")
    expect("not_working_first", mk([("Fix wifi", "knowledge"), ("Fees", "knowledge")], terminal_issue="not_working"),
           ["support", "knowledge"], "terminal_not_working")
    app = expect("append", mk([("Greet", "none")], terminal_issue="not_working"), ["none", "support"], "terminal_not_working")
    goal_ok = bool(app.steps[-1].goal) and app.steps[-1].goal == pl.SUPPORT_STEP_GOALS["terminal_not_working"]
    cases.append(("append_goal", goal_ok, f"appended goal {app.steps[-1].goal!r}"))
    expect("has_support", mk([("Deposits", "support"), ("Fees", "knowledge")], code_source="declined_sale"),
           ["support", "knowledge"], None)
    expect("escalation", mk([("Code", "knowledge")], code_source="declined_sale", escalation_request="asked_for_human"),
           ["knowledge"], None)
    expect("screen_code", mk([("Screen code", "knowledge")], code_source="terminal_screen"), ["knowledge"], None)
    expect("precedence", mk([("Both", "knowledge")], code_source="declined_sale", terminal_issue="not_working"),
           ["support"], "declined_sale")
    expect("full_no_knowledge", mk([("a", "none")] * 4, terminal_issue="not_working"), ["none"] * 4, None)
    oos = tp(reply_language="en", scope="out_of_scope", escalation_request="none", steps=[])
    out, why = pl.apply_delegate_rule(oos)
    cases.append(("out_of_scope", why is None and out.steps == [], f"out_of_scope changed: {why}"))
    bad = [d for _, ok, d in cases if not ok]
    check("P1.apply_delegate_rule", lit_ok and not bad, f"terminal_issue field ok={lit_ok}; " + "; ".join(bad[:4]))

    from langchain_core.messages import AIMessage

    from tests.fakes import ScriptedChatModel

    def tc(name, args):
        return AIMessage(content="", tool_calls=[{"name": name, "args": args, "id": f"call_{uuid.uuid4().hex[:8]}"}])

    plan_args = {"reply_language": "en", "scope": "support", "escalation_request": "none", "action_confirmation": "none",
                 "code_source": "declined_sale", "steps": [{"goal": "Explain decline code 96", "delegate": "knowledge"}]}
