def changed_files() -> set[str]:
    diff = run(["git", "diff", "--name-only", "--no-renames", BASE]).stdout.split()
    untracked = run(["git", "ls-files", "--others", "--exclude-standard"]).stdout.split()
    return set(diff) | set(untracked)


