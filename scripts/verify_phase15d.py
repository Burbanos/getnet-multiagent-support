def call_main(argv_tail: list[str]) -> int:
    """Run `python -m src.eval <argv_tail>` in-process; argparse errors become a non-zero code, never a crash."""
    import src.eval.__main__ as em
    saved = sys.argv
    sys.argv = ["src.eval", *argv_tail]
    try:
        return int(em.main() or 0)
    except SystemExit as exc:
        return int(exc.code) if isinstance(exc.code, int) else 2
    finally:
        sys.argv = saved


