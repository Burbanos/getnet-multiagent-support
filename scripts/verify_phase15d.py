def rerun_15c(tmp: str) -> None:
    src = base_file("scripts/verify_phase15c.py", "a1cfac9")
    if not src:
        check("P15C.previous_verifiers", False, "scripts/verify_phase15c.py not found at a1cfac9")
        return
    path = Path(tmp) / "verify_phase15c_from_a1cfac9.py"
    path.write_text(src, encoding="utf-8")
    env = {k: v for k, v in os.environ.items() if k not in ("GEMINI_API_KEY", "GOOGLE_API_KEY")}
    r = run([sys.executable, str(path)], env=env, timeout=5400)
    lines = r.stdout.splitlines()
    results, details = {}, {}
    for ln in lines:
        m = re.match(r"^(PASS|FAIL) (\S+)(?: :: (.*))?$", ln)
        if m:
            results[m.group(2)] = m.group(1) == "PASS"
            details[m.group(2)] = m.group(3) or ""
    for ln in lines:
        if ln.startswith("INFO "):
            print(ln, flush=True)
    failed = sorted(c for c, ok in results.items() if not ok and c not in SUPERSEDED_15C and c != "P15B.previous_verifier")
    inner_ok = results.get("P15B.previous_verifier", False)
    inner_detail = details.get("P15B.previous_verifier", "")
    if not inner_ok:
        m = re.search(r"failing \(not superseded\): \[(.*?)\]; missing: \[(.*?)\]", inner_detail)
        inner_failed = set(re.findall(r"'([^']+)'", m.group(1))) if m else {"<unparsed>"}
        inner_missing = re.findall(r"'([^']+)'", m.group(2)) if m else ["<unparsed>"]
        inner_ok = inner_failed <= SUPERSEDED_15B_INSIDE and not inner_missing
        note("P15C.P15B", f"15B failures inside the 15C re-run: {sorted(inner_failed)} (allowed: "
             f"{sorted(SUPERSEDED_15B_INSIDE)})")
    for c in sorted(SUPERSEDED_15C & set(results)):
        note(f"P15C.{c}", "superseded by 15D (" + ("passes" if results[c] else "fails") + ")")
    check("P15C.previous_verifiers", not failed and inner_ok and len(results) >= 21,
          f"15C checks failing (not superseded): {failed}; 15B inside ok={inner_ok}: {inner_detail[:300]}; "
          f"stderr: {r.stderr[-300:]}", info=f"{sum(results.values())}/{len(results)} pass")
    q2 = next((ln for ln in lines if " Q2c.test_count" in ln), "")
    m = re.search(r"(\d+) passed", q2)
    n = int(m.group(1)) if m else 0
    check("Q2.test_count", n >= MIN_TESTS, f"pytest passed {n} < {MIN_TESTS} (596 at 15C + new tests): {q2[:200]}",
          info=f"{n} passed")


