RUN_FILE, JUDGE_FILE = "reports/eval_runs/full-1.jsonl", "reports/eval_runs/full-1.judge.jsonl"
RUN_SHA256 = "70e300da87d51e49735bbb51b686e7433b0aba3c77a4bb66615e76c405deab2b"    # LF-normalised
JUDGE_SHA256 = "62b743f9137a3f456ee567722bb6f44ac42d600e2c5053e586037129b4963dd6"  # LF-normalised, judge run 2

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def sha(rel: str) -> str:
    p = ROOT / rel
    return hashlib.sha256(p.read_bytes().replace(b"\r\n", b"\n")).hexdigest() if p.exists() else "missing"


def pct(x) -> str:
    return f"{x * 100:.1f}%".replace(".", ",")


def dec(x, n=2) -> str:
    return f"{x:.{n}f}".replace(".", ",")


def main_checks(tmp: str) -> None:
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["CHECKPOINT_DB_PATH"] = str(Path(tmp) / "checkpoints.db")
    os.environ["GEMINI_API_KEY"] = ""
    sys.path.insert(0, str(ROOT))
    try:
        from src.eval import cases as ecases
        from src.eval import judge as ejudge
        from src.eval import metrics as emetrics
        from src.eval import runner as erunner
    except Exception as exc:  # noqa: BLE001
        check("R0.imports", False, f"{type(exc).__name__}: {exc}")
        return
    cases = ecases.load_cases(ROOT / "data/eval/cases.jsonl")
    check("D1.run_file_unchanged", sha(RUN_FILE) == RUN_SHA256, f"{RUN_FILE} missing or modified ({sha(RUN_FILE)})")
    check("D2.judge_file_unchanged", sha(JUDGE_FILE) == JUDGE_SHA256, f"{JUDGE_FILE} missing or modified ({sha(JUDGE_FILE)})")
    results = list(erunner.load_results(ROOT / RUN_FILE).values())
    judgments = list(ejudge.load_judgments(ROOT / JUDGE_FILE).values())
    try:
        rep = json.loads(read("reports/eval_full-1.json"))
        agg = emetrics.aggregate(cases, results, judgments)
        diffs = [k for k in agg if json.dumps(agg[k], sort_keys=True) != json.dumps(rep.get(k), sort_keys=True)]
        md = read("reports/eval_full-1.md")
        check("D3.report_matches_raw", not diffs and rep.get("run_id") == "full-1" and rep.get("complete") is True
              and (rep.get("judge") or {}).get("n_judged") == 63 and rep.get("cases_sha256") == ecases.cases_sha256(cases)
              and "abstention_precision" in md and "grounded_mean" in md,
              f"keys differing from aggregate(cases, full-1, judge run 2): {diffs[:5]}; judge={rep.get('judge')!r:.120}")
    except Exception as exc:  # noqa: BLE001
        check("D3.report_matches_raw", False, f"{type(exc).__name__}: {exc}")
        return
    m, j = agg["metrics"], agg["judge"]
    n_pass = sum(1 for c in agg["per_case"] if c["passed"])
    want = {
        "pass": f"{n_pass}/{agg['n_evaluated']} ({pct(m['pass_rate'])})",
        "official": f"{round(agg['official']['pass_rate'] * agg['official']['n'])}/{agg['official']['n']}",
        "routing_tools": f"{pct(m['routing_rate'])} / {pct(m['tools_rate'])}",
        "facts_sources": f"{pct(m['facts_rate'])} / {pct(m['sources_rate'])}",
        "language": pct(m["language_rate"]),
        "abstention": f"{pct(j['abstention_precision'])} / {pct(j['abstention_recall'])}",
        "judge_scores": f"{dec(j['grounded_mean'])} / {dec(j['answers_mean'])}",
        "latency": f"{dec(m['latency_ms_p50'] / 1000, 1)} s / {dec(m['latency_ms_p95'] / 1000, 1)} s",
    }
    readme = read("README.md")
    sec = readme[readme.find("Resultados da avaliação"):] if "Resultados da avaliação" in readme else ""
    missing = {k: v for k, v in want.items() if v not in sec}
    check("S1.readme_numbers_match_report", sec and not missing, f"section 'Resultados da avaliação' is missing {missing}")
    marks = ["gemini-3.5-flash-lite", "gemini-3.1-flash-lite", "full-1", "o04", "u01", "search_web", "teto", "uncovered"]
    check("S2.readme_caveats", sec and all(w in sec for w in marks), f"the results section must state models, run id and caveats: "
          f"missing {[w for w in marks if w not in sec]}")
    check("S3.readme_wording", "não ficam registrados no índice" not in readme,
          "README: search_web results are not recorded in the run record (not 'in the index')")


def static_checks() -> None:
    status = read("docs/STATUS.md")
    tail = status[status.rfind("Fase 6E"):] if "Fase 6E" in status else ""
    check("S4.status", bool(tail) and "maximizar pass rate" not in tail, "STATUS needs a 'Fase 6E' section without prompt tuning plans")


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks(tmp: str) -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    tests = read("tests/test_eval_runner_judge.py")
    n_tests = len(re.findall(r"^def test_", tests, flags=re.M))
    check("Q0.runner_judge_tests", n_tests >= 15, f"tests/test_eval_runner_judge.py has {n_tests} tests (need >= 15)")
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH",
                         "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1", CHECKPOINT_DB_PATH=str(Path(tmp) / "nested" / "checkpoints.db"))
    for script, allowed in PRIOR.items():
        env_s = {k: v for k, v in nested.items() if k != "CHECKPOINT_DB_PATH"} if script == "verify_phase4b.py" else nested
        r = run([sys.executable, f"scripts/{script}"], env=env_s)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    marks = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in ("data/tickets.db", "data/checkpoints.db")}
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "warning" not in last, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")
    after = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in marks}
    check("Q4.tests_do_not_touch_data_dbs", marks == after, f"the test suite wrote {[p for p in marks if marks[p] != after[p]]}")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p6e_")
    static_checks()
    main_checks(tmp)
    suite_checks(tmp)
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
