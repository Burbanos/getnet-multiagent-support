"""Phase 14B acceptance checks (docs/SPEC.md, Phase 14B: README dictated by the reviewer with the Phase 14 round).

Usage (from the repository root):  python scripts/verify_phase14b.py
Requires the dev environment. Never calls a real LLM or the network.
Do NOT edit this file to make checks pass: the reviewer runs its own copy.

Superseded checks: none. 14B changes only README.md and docs/STATUS.md; every other path is byte-identical to the round
commit (A3/A4), so the behaviour checked by verify_phase14a.py stands; its suite, lint and offline-eval checks are re-run here.
Besides pinning the README, this verifier recomputes from the raw records the round figures the README states (N checks), so
each of them has evidence in the repository.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path.cwd()
sys.path.insert(0, str(ROOT))
RESULTS: list[tuple[str, bool]] = []
BASE = "d95d55f"  # Phase 14 round
PROMPT = "docs/phase-prompts/14B.md"
README_SOURCE = "docs/phase-prompts/14B-README.md"
REVIEWER = {"docs/SPEC.md", PROMPT, "scripts/verify_phase14b.py"}
PINNED = {
    "docs/SPEC.md": "d1f1c86c58a36ca26f4ccbc6d8873bf0913d167210669aa0f843523a38a114b3",
    PROMPT: "76019616c6a2064b8d95f022c5e7812ff0ecbbb1ffce7922a49cb66010c31449",
    "README.md": "e8230761baed5749a8cf955eebbac1037f6da24cbec206111ec0ca4c687209e8",
}
RETIRED = {"docs/phase-prompts/14A.md", "scripts/verify_phase14a.py"}
ALLOWED = {"README.md", "docs/STATUS.md"}
MIN_TESTS = 516
V2_14 = ["v2-13", "v2-14", "v2-15"]

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, bool(ok)))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n") if p.exists() else ""


def sha(rel: str) -> str:
    return hashlib.sha256(read(rel).encode("utf-8")).hexdigest()


def run(cmd: list[str], env: dict | None = None, timeout: int = 1200) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True, encoding="utf-8", errors="replace",
                          timeout=timeout)


def guarded(cid: str, fn) -> None:
    try:
        fn()
    except Exception as exc:
        check(cid, False, f"probe raised {type(exc).__name__}: {str(exc)[:300]}")


def records(rid: str) -> list[dict]:
    return [json.loads(ln) for ln in read(f"reports/eval_runs/{rid}.jsonl").splitlines() if ln.strip()]


def static_checks() -> None:
    r = run([sys.executable, "-m", "ruff", "check", "--isolated", "--target-version", "py311", "--select", "E9",
             "--output-format", "concise", "scripts", "src", "tests"])
    check("A0.py311_syntax", r.returncode == 0, (r.stdout + r.stderr).strip()[-400:])
    bad = [p for p, h in PINNED.items() if sha(p) != h]
    check("A1.reviewer_files_and_readme", not bad, f"differ from the reviewer's copy: {bad}")
    verifiers = sorted(p.name for p in (ROOT / "scripts").glob("verify_*.py"))
    prompts = sorted(p.name for p in (ROOT / "docs" / "phase-prompts").glob("*.md"))
    check("A2.retired_process_files", verifiers == ["verify_phase14b.py"] and prompts == ["14B.md"]
          and not (ROOT / README_SOURCE).exists(),
          f"only verify_phase14b.py and 14B.md may remain, and {README_SOURCE} must be gone: {verifiers} {prompts}")
    diff = run(["git", "diff", "--name-only", "--no-renames", BASE])
    untracked = run(["git", "ls-files", "--others", "--exclude-standard"]).stdout.split()
    changed = set(diff.stdout.split()) | set(untracked)
    extra = sorted(p for p in changed if p not in REVIEWER | RETIRED | ALLOWED)
    check("A3.scope", diff.returncode == 0 and not extra, f"14B may only change README.md and docs/STATUS.md: {extra}")
    st = read("docs/STATUS.md")
    check("S1.status", 0 < len(st.split("\n")) <= 150 and "14B" in st and "Perguntas" in st,
          f"docs/STATUS.md must be rewritten for 14B in at most 150 lines (has {len(st.splitlines())})")


def readme_paths() -> None:
    text = read("README.md")
    tops = ("src/", "tests/", "data/", "reports/", "docs/", "scripts/", "deploy/", ".github/")
    paths = sorted({p for p in re.findall(r"`([A-Za-z0-9_./-]+)`", text) if p.startswith(tops)})
    missing = [p for p in paths if not (ROOT / p.rstrip("/")).exists()]
    check("E1.readme_paths_exist", not missing, f"README cites paths that do not exist: {missing}",
          info=f"{len(paths)} paths")


def _table_row(md: str, label: str) -> list[str]:
    for ln in md.splitlines():
        cells = [c.strip() for c in ln.strip().strip("|").split("|")]
        if cells and cells[0] == label:
            return cells
    return []


def readme_numbers() -> None:
    rep = read("reports/eval_v2_phase14.md")
    rd = read("README.md")
    pairs = {
        "Casos aprovados (checagens determinísticas)": "Casos aprovados (checagens determinísticas)",
        "Cenários oficiais aprovados": "Cenários oficiais aprovados",
        "Roteamento correto": "Roteamento correto",
        "Ferramentas corretas": "Ferramentas corretas",
        "Escalonamento correto": "Escalonamento correto",
        "Fatos esperados presentes": "Fatos esperados presentes",
        "Idioma da resposta": "Idioma da resposta",
        "Latência por caso, mediana": "Latência por caso, mediana",
        "Latência por caso, p95": "Latência por caso, p95",
        "Custo estimado por execução (USD, plano pago)": "Custo estimado por execução (plano pago)",
        "Juiz: precisão da abstenção": "Juiz: precisão da abstenção",
        "Juiz: cobertura da abstenção": "Juiz: cobertura da abstenção",
    }
    bad = []
    for rlabel, mlabel in pairs.items():
        rrow, mrow = _table_row(rep, rlabel), _table_row(rd, mlabel)
        # the README omits the (min–max) range when min == max, as the 13D column does
        if len(rrow) < 5 or len(mrow) < 5 or mrow[4].split(" (")[0] != rrow[4].split(" (")[0] or (
                "–" in rrow[4] and rrow[4].split(" (")[1].split("–")[0] != rrow[4].split("–")[1].rstrip(")")
                and not mrow[4].startswith(rrow[4])):
            bad.append((mlabel, rrow[4:5], mrow[4:5]))
    check("N1.v2_column_14_matches_report", not bad, f"{bad}")
    crit = {"Cenários oficiais aprovados": 96.7, "Fatos esperados presentes": 94.9, "Roteamento correto": 99.5,
            "Ferramentas corretas": 99.5, "Escalonamento correto": 100.0}
    got = {k: float(_table_row(rep, k)[4].split("%")[0].replace(",", ".")) for k in crit}
    met = {k: got[k] >= v for k, v in crit.items()}
    sentence = rd[rd.find("**Critério de sucesso da Fase 14**"):][:700]
    ok = (not all(met.values())) and "**Não foi atingido:**" in sentence and all(
        (f"({'atingido' if met[k] else 'não atingido'})" in sentence) for k in crit)
    check("N2.success_criterion_stated", ok, f"computed={got} met={met}")


def round_facts() -> None:
    import collections

    from src.eval.cases import load_cases
    from src.eval.checks import evaluate_case

    cases = {c["id"]: c for c in load_cases("data/eval/cases_v2.jsonl")}
    fails = collections.Counter()
    ver = collections.Counter()
    chars: list[int] = []
    trunc = 0
    u02 = 0
    for rid in V2_14:
        for r in records(rid):
            if not evaluate_case(cases[r["id"]], r)["passed"]:
                fails[r["id"]] += 1
            if r["id"] == "u02" and "4002-4000" in r["turns"][-1]["response"]:
                u02 += 1
            for t in r["turns"]:
                v = t.get("verification") or {}
                ver[v.get("status")] += 1
                if v.get("evidence_chars") is not None:
                    chars.append(v["evidence_chars"])
                trunc += bool(v.get("evidence_truncated"))
    chars.sort()
    median = chars[len(chars) // 2] if chars else None
    want_fail = {"m04": 2, "s03": 1, "off05": 1, "s01": 1, "x01": 1}
    ok_fail = dict(fails) == want_fail
    check("N3.v2_failures_as_stated", ok_fail and fails["off01"] == 0 and fails["d04"] == 0 and fails["d05"] == 0,
          f"failures per case={dict(fails)} (README states {want_fail}; off01, d04, d05 pass 3/3)")
    want_ver = {"passed": 191, "passed_after_replan": 5, "abstained": 2, "skipped": 15, None: 39}
    check("N4.verifier_counts_as_stated", dict(ver) == want_ver and trunc == 0 and median == 2355 and chars[-1] == 11467
          and u02 == 3, f"verification={dict(ver)} truncated={trunc} median={median} max={chars[-1] if chars else None} "
          f"u02_answered={u02}")
    hold = {"rh-10": ("cases_routing_holdout", set()), "rh2-7": ("cases_routing_holdout2", {"n05", "n06", "n07"}),
            "h3-4": ("cases_holdout3", {"t20"}), "act-4": ("cases_actions", {"a05"})}
    bad = {}
    for rid, (cs, want) in hold.items():
        cc = {c["id"]: c for c in load_cases(f"data/eval/{cs}.jsonl")}
        got = {r["id"] for r in records(rid) if not evaluate_case(cc[r["id"]], r)["passed"]}
        if got != want:
            bad[rid] = sorted(got)
    rr = read("reports/retrieval_hybrid_phase14.md")
    ok_r = "| `uncovered_abstain_rate` | 0.0000 | 0.9000 |" in rr and "| `u02` | uncovered | responde (4) | responde" in rr
    check("N5.holdouts_and_retrieval_as_stated", not bad and ok_r, f"holdout failures differ: {bad} retrieval_ok={ok_r}")
    judge = {json.loads(ln).get("judge_model") for rid in V2_14
             for ln in read(f"reports/eval_runs/{rid}.judge.jsonl").splitlines() if ln.strip()}
    check("N6.judge_model_as_stated", judge == {"gemini-3.1-flash-lite"}, f"judge models in v2-13..15: {judge}")


def suite_checks() -> None:
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH", "DATABASE_URL",
                         "REDIS_URL", "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER",
                         "TEST_DATABASE_URL", "TEST_REDIS_URL", "TRACING_EXPORTER")}
    env0["GEMINI_API_KEY"] = ""
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    before = run(["git", "status", "--porcelain"]).stdout
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"], env=env0)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    m = re.search(r"(\d+) passed", last)
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "failed" not in last and bool(m) and int(m.group(1)) >= MIN_TESTS,
          f"{last} (want at least {MIN_TESTS})", info=last)
    o = run([sys.executable, "-m", "src.eval", "offline"], env=env0)
    check("Q5.offline_eval", o.returncode == 0 and "offline: 6/6 passed" in o.stdout, (o.stdout + o.stderr)[-300:])
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    print(f"INFO python {sys.version.split()[0]}")
    static_checks()
    guarded("E1.readme_paths_exist", readme_paths)
    guarded("N1.v2_column_14_matches_report", readme_numbers)
    guarded("N3.v2_failures_as_stated", round_facts)
    suite_checks()
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
