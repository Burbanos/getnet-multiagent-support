def trace_checks() -> None:
    from opentelemetry.sdk.trace.export.in_memory_span_exporter import InMemorySpanExporter
    from starlette.testclient import TestClient

    import src.main as app_main
    from src.core import tracing
    from src.core.graph import OrchestrationGraph

    exporter = InMemorySpanExporter()
    tracing.configure_tracing(exporter, simple=True)
    orch = OrchestrationGraph(chat_model=scripted([text_msg("Resposta de teste do supervisor.")]),
                              planner_model=scripted([plan_msg("pt", "support", "none", [])]))
    old_get = app_main.get_orchestrator
    app_main.get_orchestrator = lambda: orch
    try:
        r = TestClient(app_main.app).post(
            "/chat", json={"message": f"Meu cartão {CARD} e CPF {CPF} {MARK}", "session_id": "sess-verify-13b"},
            headers={"X-API-Key": "getnet-dev-key", "traceparent": f"00-{TRACE}-{PARENT}-01"})
    finally:
        app_main.get_orchestrator = old_get
    spans = exporter.get_finished_spans()
    names = {s.name for s in spans}
    forbidden = (MARK, CARD, CARD_RAW, CPF, CPF_RAW, USER, "sess-verify-13b")
    leaks, keys = [], set()
    for s in spans:
        for k, v in (s.attributes or {}).items():
            keys.add(k)
            if any(f in str(v) for f in forbidden):
                leaks.append(f"{s.name}.{k}")
    planner_span = any(s.name == "llm.call" and (s.attributes or {}).get("llm.caller") == "Planner" for s in spans)
    check("R2.trace_and_span_privacy", r.status_code == 200 and "chat.request" in names and "graph.node.planner" in names
          and planner_span and all(format(s.context.trace_id, "032x") == TRACE for s in spans)
          and not leaks and keys <= ALLOWED_ATTRS,
          f"status={r.status_code} planner_node={'graph.node.planner' in names} planner_llm_span={planner_span} "
          f"leaks={leaks[:5]} extra_attrs={sorted(keys - ALLOWED_ATTRS)}")


