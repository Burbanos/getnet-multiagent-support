def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, bool(ok)))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def note(cid: str, text: str) -> None:
    print(f"INFO {cid} :: {text}", flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n") if p.exists() else ""


def sha(rel: str) -> str:
    return hashlib.sha256(read(rel).encode("utf-8")).hexdigest()


def run(cmd: list[str], env: dict | None = None, timeout: int = 1200) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True, encoding="utf-8", errors="replace",
                          timeout=timeout)


def base_file(rel: str) -> str:
    r = run(["git", "show", f"{BASE}:{rel}"])
    return r.stdout.replace("\r\n", "\n") if r.returncode == 0 else ""


def guarded(cid: str, fn) -> None:
    try:
        fn()
    except Exception as exc:  # a crash in a probe is a failed check, never a crashed verifier
        check(cid, False, f"probe raised {type(exc).__name__}: {str(exc)[:300]}")


# ------------------------------------------------------------------------------------------------------- scripted models
def scripted(responses):
    from tests.fakes import ScriptedChatModel
    return ScriptedChatModel(responses=list(responses))


def raising_model():
    from langchain_core.outputs import ChatResult  # noqa: F401

    from tests.fakes import ScriptedChatModel

    class Raising(ScriptedChatModel):
        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            self.received.append(list(messages))
            raise RuntimeError("provider down")

    return Raising()


def tool_msg(name: str, args: dict, usage: dict | None = None):
    from langchain_core.messages import AIMessage
    m = AIMessage(content="", tool_calls=[{"name": name, "args": args, "id": f"call_{uuid.uuid4().hex[:8]}"}])
    if usage:
        m.usage_metadata = usage
    return m


def plan_msg(lang="pt", scope="support", esc="none", steps=None, usage=None):
    steps = steps if steps is not None else [{"goal": "Answer the merchant's question", "delegate": "knowledge"}]
    return tool_msg("TurnPlan", {"reply_language": lang, "scope": scope, "escalation_request": esc, "steps": steps}, usage)


def verdict_msg(verdicts, usage=None):
    return tool_msg("Verification", {"verdicts": verdicts}, usage)


def text_msg(text: str):
    from langchain_core.messages import AIMessage
    return AIMessage(content=text)


def state_messages(orch, session: str):
    snap = orch.graph.get_state({"configurable": {"thread_id": f"{USER}:{session}"}})
    return list((snap.values or {}).get("messages") or []) if snap else []


def msg_text(m) -> str:
    c = getattr(m, "content", "")
    return c if isinstance(c, str) else json.dumps(c, ensure_ascii=False)


def sget(state, key, default=None):
    if isinstance(state, dict):
        return state.get(key, default)
    return getattr(state, key, default)


def _strip_ctx(line: str) -> str:
    """Normalise a test line for the one allowed edit: adding "code_context": "declined_sale" to the invoke dict."""
    flat = line.replace('"code_context": "declined_sale"', "").replace(" ", "")
    return flat.replace(",,", ",").replace("{,", "{").replace(",}", "}")


def _strip_keys(text: str) -> str:
    """Normalise expected_keys lines for the one allowed edit: adding the four new record keys."""
    flat = text.replace(" ", "")
    for k in NEW_RECORD_KEYS:
        flat = flat.replace(f'"{k}",', "").replace(f',"{k}"', "")
    return flat


