def msg_text(m) -> str:
    c = getattr(m, "content", "")
    return c if isinstance(c, str) else json.dumps(c, ensure_ascii=False)


def sget(state, key, default=None):
    if isinstance(state, dict):
        return state.get(key, default)
    return getattr(state, key, default)


def oracle(required: list[str]):
    """Scripted verifier that grounds like the real one should: 'answered' only when every required snippet reached its
    input outside the draft and the latest message (that is, in the evidence or the conversation). It records its inputs."""
    from langchain_core.messages import AIMessage
    from langchain_core.outputs import ChatGeneration, ChatResult

    from tests.fakes import ScriptedChatModel

    class Oracle(ScriptedChatModel):
        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            self.received.append(list(messages))
            text = re.sub(r"(?s)<draft>.*?</draft>", "", msg_text(messages[-1]))  # the draft never supports itself
            text = re.sub(r"(?s)<message>.*?</message>", "", text)
            missing = [s for s in required if s not in text]
            verdict = {"step": 1, "verdict": "unsupported_claim" if missing else "answered",
                       "note": "not in the evidence" if missing else ""}
            msg = AIMessage(content="", tool_calls=[{"name": "Verification", "args": {"verdicts": [verdict]},
                                                     "id": f"call_{uuid.uuid4().hex[:8]}"}])
            return ChatResult(generations=[ChatGeneration(message=msg)])

    return Oracle()


