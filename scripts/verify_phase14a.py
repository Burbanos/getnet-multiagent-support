def tool_msg(name: str, args: dict, usage: dict | None = None):
    from langchain_core.messages import AIMessage
    m = AIMessage(content="", tool_calls=[{"name": name, "args": args, "id": f"call_{uuid.uuid4().hex[:8]}"}])
    if usage:
        m.usage_metadata = usage
    return m


