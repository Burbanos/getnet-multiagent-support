def static_checks() -> None:
    print(f"INFO python {sys.version.split()[0]}")
    r = run([sys.executable, "-m", "ruff", "check", "--isolated", "--target-version", "py311", "--select", "E9",
             "--output-format", "concise", "scripts", "src", "tests"])
    check("A0.py311_syntax", r.returncode == 0, (r.stdout + r.stderr).strip()[-400:])
    bad = [p for p, h in PINNED.items() if sha(p) != h]
    check("A1.reviewer_files", not bad, f"reviewer files differ from the reviewer's copy: {bad}")

    verifiers = sorted(p.name for p in (ROOT / "scripts").glob("verify_*.py"))
    prompts = sorted(p.name for p in (ROOT / "docs" / "phase-prompts").glob("*.md"))
    check("A2.retired_process_files", verifiers == ["verify_phase14a.py"] and prompts == ["14A.md"],
          f"only verify_phase14a.py and 14A.md may remain: {verifiers} {prompts}")

    diff = run(["git", "diff", "--name-only", "--no-renames", BASE])
    untracked = run(["git", "ls-files", "--others", "--exclude-standard"]).stdout.split()
    changed = set(diff.stdout.split()) | set(untracked)
    extra = sorted(p for p in changed if p not in REVIEWER and p not in RETIRED and p not in ALLOWED_CODE
                   and not p.startswith(ALLOWED_PREFIX))
    check("A3.scope", diff.returncode == 0 and not extra, f"14A may not change: {extra or diff.stderr[-200:]}")

    fr = run(["git", "diff", "--name-only", BASE, "--", *FROZEN])
    fr_changed = [p for p in fr.stdout.split() if p not in REVIEWER and p not in ALLOWED_CODE]
    fr_new = [p for p in untracked if any(p == f or p.startswith(f + "/") for f in FROZEN) and p not in REVIEWER
              and p not in ALLOWED_CODE]
    check("A4.records_frozen", fr.returncode == 0 and not fr_changed and not fr_new,
          f"frozen paths changed (corpus, index, reports, README and other prompts stay as at {BASE}): "
          f"{fr_changed[:8]} {fr_new[:8]}")

    ls = run(["git", "ls-tree", "-r", "--name-only", BASE, "tests"]).stdout.split()
    problems: list[str] = []
    for rel in ls:
        if not rel.endswith(".py"):
            continue
        old, new = base_file(rel), read(rel)
        if not new:
            problems.append(f"{rel} removed")
            continue
        names_old = set(re.findall(r"^\s*(?:async\s+)?def (test_\w+)", old, re.M))
        names_new = set(re.findall(r"^\s*(?:async\s+)?def (test_\w+)", new, re.M))
        if names_old - names_new:
            problems.append(f"{rel}: tests removed {sorted(names_old - names_new)[:3]}")
        if rel == "tests/conftest.py":
            continue
        old_lines, new_lines = old.split("\n"), new.split("\n")
        for tag, i1, i2, _j1, _j2 in difflib.SequenceMatcher(None, old_lines, new_lines, autojunk=False).get_opcodes():
            if tag in ("replace", "delete"):
                problems.append(f"{rel}: lines changed or removed ({old_lines[i1:i2][:1]})")
    check("A5.existing_tests_only_grow", not problems, "; ".join(problems[:6]))

    st = read("docs/STATUS.md")
    check("S1.status", 0 < len(st.split("\n")) <= 150 and "14A" in st and "Perguntas" in st,
          f"docs/STATUS.md must be rewritten for 14A in at most 150 lines (has {len(st.splitlines())})")

    check("A6.no_case_tuning", _only_preexisting(),
          "src/ may not gain mentions of eval case ids or case strings (off01, d04, d05, m04, Get Smart, PTAX, Android)")


def _only_preexisting() -> bool:
    """True when no file 14A may change gained case-like tokens over BASE (PTAX already appears in fixed messages)."""
    pat = re.compile(r"(?i)\boff01\b|\bd04\b|\bd05\b|\bm04\b|get smart|ptax|android")
    for rel in sorted(ALLOWED_CODE - {"docs/STATUS.md"}):
        if len(pat.findall(read(rel))) > len(pat.findall(base_file(rel))):
            return False
    return True


