def chunk_corpus() -> None:
    from src.config import settings
    from src.rag.chunking import _norm, build_chunks

    pages = [json.loads(ln) for ln in read("data/corpus/pages.jsonl").splitlines() if ln.strip()]
    ok_pages = [p for p in pages if p.get("status") == "ok"]
    committed = [json.loads(ln) for ln in read("data/index/chunks.jsonl").splitlines() if ln.strip()]
    kw = dict(max_chars=900, boilerplate_min_pages=4, min_chars=settings.RAG_MIN_CHUNK_CHARS)
    old = build_chunks(ok_pages, boilerplate_min_run=1, **kw)
    new = build_chunks(ok_pages, **kw)
    reproduces = old == committed

    def by_url(chs):
        out: dict[str, list[str]] = {}
        for c in chs:
            out.setdefault(c["doc_url"], []).extend(c["text"].split("\n"))
        return out

    o_url, n_url = by_url(old), by_url(new)
    label_back = all("Get Smart\nR$ 129,90/mês" in "\n".join(n_url.get(u, [])) for u in
                     ("https://site.getnet.com.br/", "https://site.getnet.com.br/todas-as-maquininhas/"))
    label_gone_before = not any("Get Smart\nR$ 129,90/mês" in "\n".join(v) for v in o_url.values())
    check("C2.corpus_diagnosis_and_fix", reproduces and label_back and label_gone_before,
          f"min_run=1 reproduces the committed index={reproduces} label_back_after_fix={label_back} "
          f"label_absent_before={label_gone_before}")

    counts: dict[str, int] = {}
    for p in ok_pages:
        for k in {_norm(ln) for ln in (p.get("text") or "").split("\n") if _norm(ln)}:
            counts[k] = counts.get(k, 0) + 1
    cand = {k for k, v in counts.items() if v >= 4}
    not_subseq, adjacent = [], []
    for url, lines in o_url.items():
        it = iter(n_url.get(url, []))
        if not all(any(x == y for y in it) for x in lines):
            not_subseq.append(url)
    for url, lines in n_url.items():
        for a, b in zip(lines, lines[1:]):
            if _norm(a) in cand and _norm(b) in cand:
                adjacent.append((url, a, b))
    added = sum(len(v) for v in n_url.values()) - sum(len(v) for v in o_url.values())
    check("C3.fix_only_restores_isolated_lines", not not_subseq and not adjacent and added > 0,
          f"pages where old lines are not kept in order={not_subseq[:4]} repeated blocks left={adjacent[:3]} "
          f"lines added={added}", info=f"{added} lines restored")


