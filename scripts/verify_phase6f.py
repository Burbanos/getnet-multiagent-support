def static_checks() -> None:
    readme, demo, ref = read("README.md"), read("src/static/demo.html"), read("docs/phase-prompts/6F.md")
    found = [w for w in BANNED_README if w in readme]
    check("C1.readme_no_false_claims", not found, f"README still contains: {found}")
    check("C2.demo_no_confidence", "confidenceMetric" not in demo and "Confiança" not in demo and "X-API-Key" in demo
          and "costMetric" in demo, "demo.html: remove the confidence card and its JS only (keep X-API-Key and the cost field)")

    def block(text: str, start: str) -> str:
        i = text.find("````markdown\n" + start)
        i = i + len("````markdown\n") if i >= 0 else -1
        if i < 0:
            return ""
        j = text.find("\n````", i)
        return text[i:j].strip() if j > 0 else ""
    matrix = block(ref, "## 6. Matriz de Cobertura dos Cenários Oficiais")
    gloss = block(ref, '### 1. "A UI mostra uma confiança')
    check("C3.official_matrix", bool(matrix) and matrix in readme and readme.count("## 6. Matriz") == 1,
          "README section 6 must be exactly the matrix given in docs/phase-prompts/6F.md (statuses measured in full-1)")
    g_parts = [p.strip() for p in gloss.split("### ") if p.strip()]
    missing = [p.split("\n")[0][:60] for p in g_parts if p not in readme]
    check("C4.glossary", len(g_parts) == 4 and not missing and readme.count('### 1. "A UI mostra uma confiança') == 1
          and '### 2. "O que o modelo/Supervisor decide' in readme, f"glossary answers 1, 3, 4, 5 must be the given text: {missing}")
    check("C5.ticket_format_and_cost", "GET-TKT-YYYYMMDD-<10 hexadecimais>" in readme and "estimated_cost_usd" in readme
          and "input_tokens" in readme and "tokens_by_agent" in readme,
          "README must state the real ticket format, that estimated_cost_usd is null until Phase 7, and the real token fields")
    check("C6.retrieval_claim", "margem de apenas 0.04" in readme and "Abstenção Uncovered" in readme,
          "README 3D section must replace the 'ideal separation' items with the retrieval-only statement and keep 'Abstenção Uncovered'")
    status = read("docs/STATUS.md")
    tail = status[status.rfind("Fase 6F"):] if "Fase 6F" in status else ""
    check("C7.status", bool(tail) and "Fase 7" in tail, "STATUS needs a 'Fase 6F' section naming Phase 7 as next")
    results = readme[readme.find("### Resultados da avaliação"):readme.find("Limites e falhas conhecidas")]
    check("C8.results_section_kept", "62/69 (89,9%)" in results and "76,9% / 76,9%" in results,
          "the 'Resultados da avaliação' section from 6E must stay unchanged")


