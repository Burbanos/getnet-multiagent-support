    check("S1.dataset_identical", ok, f"{DATASET} differs from the reviewer's set: n={len(have)} vs {len(exp)}, ids={diff[:8]}",
          info=f"{len(exp)} queries, sha256 {ref_sha(exp)[:12]}")
