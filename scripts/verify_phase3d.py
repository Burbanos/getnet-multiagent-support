    check("P2.chosen_threshold", close(ab.get("chosen_threshold"), chosen), f"report={ab.get('chosen_threshold')} reference={chosen}",
          info=f"chosen={chosen:.2f} balanced_accuracy={at['balanced_accuracy']:.3f} answer_rate={at['answer_rate']:.3f} "
               f"off_topic_abstain={at['off_topic_abstain_rate']:.3f} uncovered_abstain={at['uncovered_abstain_rate']:.3f}")
    check("P2.warnings", sorted(rep.get("warnings", [])) == warns, f"report={rep.get('warnings')} reference={warns}",
          info=f"warnings={warns}")
    md = read(REPORT_MD)
