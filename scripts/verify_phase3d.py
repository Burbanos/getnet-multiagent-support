def ref_records() -> list[dict]:
    return [json.loads(ln) for ln in EXPECTED_DATASET.splitlines() if ln.strip()]


def ref_sha(records: list[dict]) -> str:
    canon = "\n".join(json.dumps(r, ensure_ascii=False, sort_keys=True) for r in records)
    return hashlib.sha256(canon.encode("utf-8")).hexdigest()


def ref_norm(s: str) -> str:
    return " ".join(s.split()).lower()


def ref_grid() -> list[float]:
    return [round(0.30 + 0.01 * i, 2) for i in range(66)]


def ref_evaluate(records, qvecs, chunks, cvecs) -> dict:
    import numpy as np
    C = np.asarray(cvecs, dtype=np.float32).astype(np.float64)
    per = []
    for r, q in zip(records, qvecs):
        q = np.asarray(q, dtype=np.float32).astype(np.float64)
        n = np.linalg.norm(q)
        q = q / n if n > 0 else q
        s = C @ q
        order = np.argsort(-s, kind="stable")
        gold = set(r["gold_urls"])
        rank = None
        for pos, idx in enumerate(order[:10], start=1):
            if chunks[idx]["doc_url"] in gold:
                rank = pos
                break
        snips = [ref_norm(x) for x in r["gold_snippets"]]
        ah3 = any(chunks[i]["doc_url"] in gold and any(x in ref_norm(chunks[i]["text"]) for x in snips) for i in order[:3])
        top = int(order[0])
        per.append({"id": r["id"], "lang": r["lang"], "category": r["category"], "top1_score": float(s[top]),
                    "top1_chunk_id": chunks[top]["chunk_id"], "top1_url": chunks[top]["doc_url"],
                    "gold_rank": rank, "answer_hit@3": bool(ah3) if r["category"] == "answerable" else None})

    def agg(rows):
        n = len(rows)
        if not n:
            return {k: None for k in METRIC_KEYS} | {"n": 0}
        return {"n": n,
                "hit@1": sum(1 for x in rows if x["gold_rank"] and x["gold_rank"] <= 1) / n,
                "hit@3": sum(1 for x in rows if x["gold_rank"] and x["gold_rank"] <= 3) / n,
                "hit@5": sum(1 for x in rows if x["gold_rank"] and x["gold_rank"] <= 5) / n,
                "mrr@10": sum(1.0 / x["gold_rank"] for x in rows if x["gold_rank"]) / n,
                "answer_hit@3": sum(1 for x in rows if x["answer_hit@3"]) / n}
    ans = [x for x in per if x["category"] == "answerable"]
    retrieval = agg(ans)
    retrieval["by_lang"] = {lg: agg([x for x in ans if x["lang"] == lg]) for lg in ("pt", "en")}
    return {"per_query": per, "retrieval": retrieval}


def ref_curve(per, thresholds) -> list[dict]:
    a = [x["top1_score"] for x in per if x["category"] == "answerable"]
    o = [x["top1_score"] for x in per if x["category"] == "off_topic"]
    u = [x["top1_score"] for x in per if x["category"] == "uncovered"]
    rows = []
    for t in thresholds:
        ar = sum(1 for s in a if s >= t) / len(a) if a else None
        orr = sum(1 for s in o if s < t) / len(o) if o else None
        ur = sum(1 for s in u if s < t) / len(u) if u else None
        abst = sum(1 for s in a if s < t) + sum(1 for s in o if s < t)
        prec = (sum(1 for s in o if s < t) / abst) if abst else None
        ba = (ar + orr) / 2 if ar is not None and orr is not None else None
        rows.append({"threshold": t, "answer_rate": ar, "off_topic_abstain_rate": orr, "uncovered_abstain_rate": ur,
                     "balanced_accuracy": ba, "abstain_precision": prec, "abstain_recall": orr})
    return rows


def ref_choose(curve) -> float:
    best = max(round(r["balanced_accuracy"], 9) for r in curve)
    cands = sorted(r["threshold"] for r in curve if round(r["balanced_accuracy"], 9) == best)
    return cands[(len(cands) - 1) // 2]


def ref_warnings(retrieval, at_chosen, chosen) -> list[str]:
    w = []
    if at_chosen["balanced_accuracy"] < 0.9:
        w.append("weak_separation")
    if at_chosen["uncovered_abstain_rate"] is not None and at_chosen["uncovered_abstain_rate"] < 0.5:
        w.append("uncovered_not_filtered")
    if retrieval["answer_hit@3"] is not None and retrieval["answer_hit@3"] < 0.7:
        w.append("low_answer_hit")
    if chosen in (0.30, 0.95):
        w.append("threshold_at_grid_edge")
    return sorted(w)


def close(a, b) -> bool:
    if a is None or b is None:
        return a is None and b is None
    return math.isclose(float(a), float(b), abs_tol=TOL)


