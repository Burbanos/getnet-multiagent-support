def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None, cwd: Path | None = None, timeout: int = 1200) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=cwd or ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=timeout)


def section(text: str, start: str, stop: str) -> str:
    i = text.find(start)
    if i < 0:
        return ""
    j = text.find(stop, i + len(start))
    return text[i:j] if j > i else text[i:]


def runner_env() -> dict[str, str]:
    """ENV values of the Dockerfile's final stage (continuation lines joined)."""
    docker = read("Dockerfile")
    stage = docker[docker.rfind("\nFROM "):] if "\nFROM " in docker else docker
    joined = re.sub(r"\\\s*\n\s*", " ", stage)
    env: dict[str, str] = {}
    for line in joined.splitlines():
        if line.strip().startswith("ENV "):
            for tok in shlex.split(line.strip()[4:]):
                if "=" in tok:
                    k, v = tok.split("=", 1)
                    env[k] = v
    return env


def image_like_env(tmp: str) -> dict[str, str]:
    env = {k: v for k, v in os.environ.items()
           if k not in ("APP_ENV", "API_KEYS", "GEMINI_API_KEY", "CHECKPOINT_DB_PATH", "TICKETS_DB_PATH", "ENVIRONMENT")}
    for k, v in runner_env().items():
        if k not in ("PATH", "PYTHONPATH", "HOME", "CHECKPOINT_DB_PATH", "TICKETS_DB_PATH"):
            env[k] = v
    env.update(GEMINI_API_KEY="", API_KEYS="", PYTHONPATH=str(ROOT),
               CHECKPOINT_DB_PATH=str(Path(tmp) / "img" / "checkpoints.db"), TICKETS_DB_PATH=str(Path(tmp) / "img" / "tickets.db"))
    (Path(tmp) / "img").mkdir(parents=True, exist_ok=True)
    return env


