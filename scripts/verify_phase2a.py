"""Phase 2A acceptance checks (docs/SPEC.md, Phase 2). Cross-platform.

Usage (from the repository root):  python scripts/verify_phase2a.py
Requires the dev environment (pip install -r requirements-dev.txt). Never calls a real LLM.
Do NOT edit this file to make checks pass: the reviewer runs an independent copy.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

ROOT = Path.cwd()
RESULTS: list[tuple[str, bool]] = []
REAL_TOOLS = {"get_settlement_status", "diagnose_declined_transaction", "diagnose_terminal",
              "search_knowledge_base", "search_web", "escalate_to_human"}
REGEX_ALLOWED = {"src/agents/guardrails.py", "src/core/pii.py", "src/agents/knowledge.py"}

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def src_files() -> list[Path]:
    return [p for p in (ROOT / "src").rglob("*.py")]


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=900)


def static_checks() -> None:
    hits = [f"{p.relative_to(ROOT)}" for p in src_files()
            if re.search(r"RulesFallbackEngine|def _format_|decide_or_synthesize", p.read_text(encoding="utf-8"))]
    check("S1.rules_engine_removed", not hits, f"still referenced in: {hits}")

    rx_users = []
    for p in src_files():
        rel = p.relative_to(ROOT).as_posix()
        if rel not in REGEX_ALLOWED and re.search(r"\bre\.(search|match|fullmatch|compile|findall)\(",
                                                  p.read_text(encoding="utf-8")):
            rx_users.append(rel)
    check("S2.no_regex_routing", not rx_users, f"regex used outside guardrail/PII/retriever: {rx_users}")

    all_src = "\n".join(p.read_text(encoding="utf-8") for p in src_files())
    check("S3.bind_tools", ".bind_tools(" in all_src, "no .bind_tools( call in src/")
    prompt = read("src/prompts/supervisor.md")
    check("S4.supervisor_prompt", len(prompt) >= 400 and re.search(r"language|idioma", prompt, re.I) is not None,
          "src/prompts/supervisor.md missing, too short, or no language instruction")
    check("S5.fake_model", "class ScriptedChatModel" in read("tests/fakes.py"), "tests/fakes.py::ScriptedChatModel missing")

    req, dev, lock = read("requirements.txt").lower(), read("requirements-dev.txt").lower(), read("requirements.lock").lower()
    check("S6.dep_declared", "langchain-google-genai" in req, "langchain-google-genai not in requirements.txt")
    ci_txt = read(".github/workflows/ci.yml")
    check("S6.ci_tests_use_lock", "-r requirements.lock" in ci_txt and "-r requirements.lock" not in dev,
          "CI test job must install -r requirements.lock; requirements-dev.txt must stay on requirements.txt "
          "(the Linux lock pins uvloop, which does not install on Windows)")
    check("S6.docker_no_fallback", "-r requirements.txt" not in read("Dockerfile"), "Dockerfile still falls back to requirements.txt")
    check("S6.lock_has_dep", "langchain-google-genai==" in lock,
          "requirements.lock not regenerated (user step in Codespaces)")
    ci = read(".github/workflows/ci.yml")
    check("S7.ci_actions_updated", "actions/checkout@v5" in ci and "actions/setup-python@v6" in ci,
          "ci.yml still on checkout@v4 / setup-python@v5")

    readme = read("README.md")
    low = readme.lower()
    stale = [s for s in ["nenhum llm é chamado", "fallback por regras"] if s in low]
    check("S8.readme_updated", not stale and "503" in readme and "GEMINI_API_KEY" in readme,
          f"README stale phrases {stale}, or missing GEMINI_API_KEY / 503 behavior")


def runtime_checks() -> None:
    tmp = tempfile.mkdtemp(prefix="verify_p2a_")
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["GEMINI_API_KEY"] = ""
    sys.path.insert(0, str(ROOT))
    try:
        from fastapi.testclient import TestClient
        from langchain_core.messages import AIMessage, HumanMessage, SystemMessage, ToolMessage

        import src.core.graph as graph_mod
        from src.core.graph import OrchestrationGraph
        from src.main import app
        from src.tools.agent_tools import ALL_TOOLS
        from tests.fakes import ScriptedChatModel
    except Exception as exc:  # noqa: BLE001
        check("R0.imports", False, f"{type(exc).__name__}: {exc}")
        return

    leaked = {t.name: list(t.args) for t in ALL_TOOLS if "user_id" in t.args}
    check("R1.user_id_not_model_visible", not leaked, f"user_id in tool schema: {leaked}")
    check("R1.tool_set", {t.name for t in ALL_TOOLS} == REAL_TOOLS, f"tools={sorted(t.name for t in ALL_TOOLS)}")

    def call(name: str, args: dict, cid: str) -> AIMessage:
        return AIMessage(content="", tool_calls=[{"name": name, "args": args, "id": cid}])

    try:
        fake = ScriptedChatModel(responses=[call("get_settlement_status", {}, "c1"), AIMessage(content="FINAL-1")])
        orch = OrchestrationGraph(chat_model=fake)
        st = orch.run_sync(user_id="cliente1988", message="When will yesterday's sales be deposited?", session_id="v2a-1")
        check("R2.single_tool_flow", st.tools_used == ["get_settlement_status"] and st.agent_response == "FINAL-1",
              f"tools_used={st.tools_used}, response={st.agent_response!r}")
        first = fake.received[0] if fake.received else []
        check("R2.system_prompt_first", bool(first) and isinstance(first[0], SystemMessage), "first message is not SystemMessage")
        humans = [m for m in first if isinstance(m, HumanMessage)]
        check("R2.no_duplicate_human", len(humans) == 1, f"{len(humans)} HumanMessages sent to the model in a single-turn run")
        tool_msgs = [m for m in (fake.received[1] if len(fake.received) > 1 else []) if isinstance(m, ToolMessage)]
        check("R3.user_id_injected", any('"cliente1988"' in str(m.content) for m in tool_msgs),
              "ToolMessage does not carry data for the authenticated user_id")
        check("R3.bound_tools", {getattr(t, "name", "") for t in fake.bound_tools} == REAL_TOOLS,
              f"bound={[getattr(t, 'name', t) for t in fake.bound_tools]}")

        fake2 = ScriptedChatModel(responses=[
            call("get_settlement_status", {}, "c2"),
            call("search_knowledge_base", {"query": "antecipação"}, "c3"),
            AIMessage(content="FINAL-2")])
        st2 = OrchestrationGraph(chat_model=fake2).run_sync(user_id="cliente1988", message="x", session_id="v2a-2")
        check("R4.two_tools_sequence", st2.tools_used == ["get_settlement_status", "search_knowledge_base"]
              and st2.agent_response == "FINAL-2", f"tools_used={st2.tools_used}")

        fake3 = ScriptedChatModel(responses=[AIMessage(content="T1"), AIMessage(content="T2")])
        o3 = OrchestrationGraph(chat_model=fake3)
        o3.run_sync(user_id="cliente1988", message="primeira pergunta", session_id="v2a-3")
        o3.run_sync(user_id="cliente1988", message="segunda pergunta", session_id="v2a-3")
        second = fake3.received[1] if len(fake3.received) > 1 else []
        check("R5.multi_turn_memory", any("primeira pergunta" in str(m.content) for m in second),
              "second turn did not include the first turn in the model input")

        fake4 = ScriptedChatModel(responses=[AIMessage(content="ok")])
        OrchestrationGraph(chat_model=fake4).run_sync(
            user_id="cliente1988", message="meu cartão 4111 1111 1111 1111 foi recusado", session_id="v2a-4")
        sent = " ".join(str(m.content) for m in (fake4.received[0] if fake4.received else []))
        check("R6.pii_masked_before_model", "4111 1111 1111 1111" not in sent and bool(sent),
              "raw card number reached the model")
    except Exception as exc:  # noqa: BLE001
        check("R2.runtime", False, f"{type(exc).__name__}: {exc}")

    client = TestClient(app)
    try:
        graph_mod._orchestrator_instance = None
        r = client.post("/chat", json={"message": "oi", "user_id": "cliente1988"})
        check("R7.no_key_503", r.status_code == 503, f"status {r.status_code}: {r.text[:200]}")

        class Boom(ScriptedChatModel):
            def _generate(self, messages, stop=None, run_manager=None, **kwargs):
                raise TimeoutError("simulated provider timeout")

        graph_mod._orchestrator_instance = OrchestrationGraph(chat_model=Boom())
        r2 = client.post("/chat", json={"message": "oi", "user_id": "cliente1988"})
        check("R8.llm_error_503", r2.status_code == 503, f"status {r2.status_code}: {r2.text[:200]}")
    except Exception as exc:  # noqa: BLE001
        check("R7.runtime", False, f"{type(exc).__name__}: {exc}")
    finally:
        graph_mod._orchestrator_instance = None


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks() -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = {k: v for k, v in os.environ.items() if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY")}
    env["PYTHONPATH"] = plugdir + os.pathsep + os.environ.get("PYTHONPATH", "")
    env["GEMINI_API_KEY"] = ""
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    static_checks()
    runtime_checks()
    suite_checks()
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
