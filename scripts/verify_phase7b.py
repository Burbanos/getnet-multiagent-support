if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


OFFICIAL = {"gemini-3.5-flash-lite": (0.30, 2.50), "gemini-3.1-flash-lite": (0.25, 1.50), "gemini-embedding-2": (0.20, 0.0)}


def static_checks() -> None:
    readme = read("README.md")
    need = ["ai.google.dev/gemini-api/docs/pricing", "2026-10-30", "2026-11-07", "estimated_cost_usd"]
    check("P0.readme", all(w in readme for w in need) and "embedding" in readme.lower(),
          f"README must document the price table source and dates, that unlisted models have cost null, "
          f"and that query embeddings are not counted; missing {[w for w in need if w not in readme]}")
    main = read("src/main.py")
    bad = [w for w in ("[trace_id={trace_id}]", "{exc}\")") if w in main]
    check("P0.main_logs", not bad, f"src/main.py log calls must not embed the trace id in text nor the exception message: {bad}")


def main_checks(tmp: str) -> None:
    os.environ["TICKETS_DB_PATH"] = str(Path(tmp) / "tickets.db")
    os.environ["CHECKPOINT_DB_PATH"] = str(Path(tmp) / "checkpoints.db")
    os.environ["GEMINI_API_KEY"] = ""
    os.environ.pop("API_KEYS", None)
    os.environ["APP_ENV"] = "development"
    sys.path.insert(0, str(ROOT))
    try:
        from langchain_core.messages import AIMessage

        from src.config import JsonFormatter
        from src.core import pricing
        from src.core.graph import OrchestrationGraph
        from tests.fakes import ScriptedChatModel
    except Exception as exc:  # noqa: BLE001
        check("P1.imports", False, f"{type(exc).__name__}: {exc}")
        return
    table = getattr(pricing, "PRICES_USD_PER_1M", {})
    got = {k: (v.get("input"), v.get("output")) for k, v in table.items()} if isinstance(table, dict) else {}
    check("P1.price_table", got == OFFICIAL and getattr(pricing, "PRICE_SOURCE_URL", "") == "https://ai.google.dev/gemini-api/docs/pricing"
          and getattr(pricing, "PRICE_PAGE_LAST_UPDATED", "") == "2026-10-30" and getattr(pricing, "PRICE_RETRIEVED_AT", "") == "2026-11-07",
          f"table={got}; the table must hold exactly the official prices (no unlisted model) with source and dates")
    f = getattr(pricing, "cost_usd", None)
    try:
        cases = [f("gemini-3.1-flash-lite", 1_000_000, 1_000_000), f("models/gemini-3.5-flash-lite", 2000, 500),
                 f("gemini-3.5-flash", 1000, 1000), f("unknown-model", 1000, 1000), f("gemini-3.5-flash-lite", None, 10), f(None, 1, 1)]
        check("P2.cost_usd", abs(cases[0] - 1.75) < 1e-9 and abs(cases[1] - 0.00185) < 1e-9 and cases[2:] == [None, None, None, None],
              f"got {cases}")
    except Exception as exc:  # noqa: BLE001
        check("P2.cost_usd", False, f"{type(exc).__name__}: {exc}")

    class Named(ScriptedChatModel):
        model: str = "x"

    def turn(model_name: str):
        usage = {"input_tokens": 4000, "output_tokens": 1000, "total_tokens": 5000}
        fake = Named(model=model_name, responses=[AIMessage(content="ok", usage_metadata=usage)])
        return OrchestrationGraph(chat_model=fake).run_sync(user_id="cliente1988", message="oi", session_id=f"p3-{model_name}")
    try:
        a, b = turn("gemini-3.5-flash-lite"), turn("gemini-3.5-flash")
        want = 4000 / 1e6 * 0.30 + 1000 / 1e6 * 2.50
        check("P3.turn_cost", a.estimated_cost_usd is not None and abs(a.estimated_cost_usd - want) < 1e-9 and b.estimated_cost_usd is None
              and (b.tokens or {}).get("total_tokens") == 5000,
              f"priced={a.estimated_cost_usd} (want {want}), unpriced={b.estimated_cost_usd}, tokens={b.tokens}")
    except Exception as exc:  # noqa: BLE001
        check("P3.turn_cost", False, f"{type(exc).__name__}: {exc}")

    # /chat error logs carry the request context (no key configured -> 503 path)
    try:
        from fastapi.testclient import TestClient

        from src.core import log_context as lc
        from src.main import app
        buf = io.StringIO()
        h = logging.StreamHandler(buf)
        h.setFormatter(JsonFormatter())
        lg = logging.getLogger("multiagent")
        lg.addHandler(h)
        try:
            with TestClient(app) as client:
                r = client.post("/chat", json={"message": "oi", "session_id": "p4-sess"}, headers={"X-API-Key": "getnet-dev-key"})
        finally:
            lg.removeHandler(h)
        recs = [json.loads(ln) for ln in buf.getvalue().splitlines() if ln.strip().startswith("{")]
        errs = [x for x in recs if x.get("level") == "ERROR"]
        tid = r.headers.get("X-Trace-Id")
        check("P4.chat_error_logs_have_context", r.status_code == 503 and errs and tid
              and all(x.get("trace_id") == tid and x.get("session_id") == "p4-sess" and x.get("user_hash") == lc.user_hash("cliente1988")
                      for x in errs) and "cliente1988" not in buf.getvalue(),
              f"status={r.status_code}, error records={[(x.get('message'), x.get('trace_id')) for x in errs][:3]}, header={tid}")
    except Exception as exc:  # noqa: BLE001
        check("P4.chat_error_logs_have_context", False, f"{type(exc).__name__}: {exc}")


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks(tmp: str) -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    tests = read("tests/test_pricing.py")
    n_tests = len(re.findall(r"^def test_", tests, flags=re.M))
    check("Q0.pricing_tests", n_tests >= 4, f"tests/test_pricing.py has {n_tests} tests (need >= 4)")
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH",
                         "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1", CHECKPOINT_DB_PATH=str(Path(tmp) / "nested" / "checkpoints.db"))
    for script, allowed in PRIOR.items():
        env_s = {k: v for k, v in nested.items() if k != "CHECKPOINT_DB_PATH"} if script == "verify_phase4b.py" else nested
        r = run([sys.executable, f"scripts/{script}"], env=env_s)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    marks = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in ("data/tickets.db", "data/checkpoints.db")}
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "warning" not in last, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")
    after = {p: ((ROOT / p).stat().st_mtime_ns if (ROOT / p).exists() else None) for p in marks}
    check("Q4.tests_do_not_touch_data_dbs", marks == after, f"the test suite wrote {[p for p in marks if marks[p] != after[p]]}")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p7b_")
    static_checks()
    main_checks(tmp)
    suite_checks(tmp)
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
