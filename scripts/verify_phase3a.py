"""Phase 3A acceptance checks (docs/SPEC.md, Phase 3A: ingestion of official sources).

Usage (from the repository root):  python scripts/verify_phase3a.py
Revision 2 (3A.1): Santander replaced by site.getnet.com.br after its CDN denied the project user agent.
Requires the dev environment. Never accesses the network: HTTP is simulated with httpx.MockTransport.
Do NOT edit this file to make checks pass: the reviewer runs an independent copy.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import textwrap
import time
from datetime import datetime
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path.cwd()
RESULTS: list[tuple[str, bool]] = []
ALLOWED_HOSTS = {"www.getnet.net", "site.getnet.com.br", "www.getnet.com.br"}
STATUSES = {"ok", "robots_disallowed", "http_error", "fetch_error", "no_content", "off_allowlist"}
REPO_URL = "https://github.com/Burbanos/getnet-multiagent-support"
PRIOR = {
    "verify_phase2a.py": {"R2.single_tool_flow", "R3.user_id_injected", "R3.bound_tools", "R4.two_tools_sequence"},
    "verify_phase2b.py": {"S1.default_model_config", "S1.default_model_env_example", "R2.model_name"},
    "verify_phase2c.py": set(),
    "verify_phase2d.py": set(),
    "verify_phase2e.py": set(),
}
LONG = "Conteúdo principal sobre a maquininha Getnet e recebimento via Pix. " * 10

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def corpus_checks() -> None:
    try:
        import yaml
    except ImportError:
        check("C0.pyyaml", False, "PyYAML not installed")
        return
    try:
        raw = yaml.safe_load(read("data/sources.yaml")) or {}
        sources = raw.get("sources", []) if isinstance(raw, dict) else []
    except Exception as exc:  # noqa: BLE001
        check("C1.sources_yaml", False, f"cannot parse data/sources.yaml: {exc}")
        return
    urls = [s.get("url", "") for s in sources]
    bad = [s for s in sources if not str(s.get("url", "")).startswith("https://")
           or urlparse(s.get("url", "")).hostname not in ALLOWED_HOSTS or s.get("market") not in ("BR", "global")]
    check("C1.sources_yaml", len(sources) >= 25 and not bad and len(set(urls)) == len(urls),
          f"{len(sources)} sources, invalid={bad[:3]}, duplicates={len(urls) - len(set(urls))}")
    check("C1.no_portugal_market", not any("getnet.net/pt" in u for u in urls), "getnet.net/pt (Portugal) must not be a source")
    check("C1.no_blocked_santander", not any("santander.com.br" in u for u in urls),
          "santander.com.br denies the project user agent (403 on robots.txt) and must not be a source")

    lines = [ln for ln in read("data/corpus/pages.jsonl").splitlines() if ln.strip()]
    try:
        recs = [json.loads(ln) for ln in lines]
    except json.JSONDecodeError as exc:
        check("C2.pages_jsonl", False, f"invalid JSONL: {exc}")
        return
    check("C2.one_record_per_source", sorted(r.get("url") for r in recs) == sorted(urls),
          f"{len(recs)} records for {len(urls)} sources")
    check("C2.statuses_valid", all(r.get("status") in STATUSES for r in recs),
          f"unknown statuses: {sorted({r.get('status') for r in recs} - STATUSES)}")
    ok_recs = [r for r in recs if r.get("status") == "ok"]
    broken = []
    for r in ok_recs:
        text = r.get("text") or ""
        try:
            ts = datetime.fromisoformat(str(r.get("fetched_at")))
            tz_ok = ts.tzinfo is not None
        except ValueError:
            tz_ok = False
        if not (len(text) >= 300 and r.get("sha256") == hashlib.sha256(text.encode("utf-8")).hexdigest() and tz_ok
                and r.get("chars") == len(text)):
            broken.append(r.get("url"))
    check("C3.ok_records_integrity", bool(ok_recs) and not broken, f"invalid ok records: {broken[:3]}")
    check("C3.non_ok_without_text", all(not r.get("text") for r in recs if r.get("status") != "ok"),
          "non-ok records must not carry text")
    br = [r for r in ok_recs if r.get("market") == "BR"]
    check("C4.corpus_size", len(ok_recs) >= 15 and len(br) >= 8, f"ok={len(ok_recs)}, ok BR={len(br)} (need >=15 and >=8)")

    try:
        manifest = json.loads(read("data/corpus/manifest.json"))
        counts = manifest.get("counts", {})
        expected = {s: sum(1 for r in recs if r.get("status") == s) for s in STATUSES}
        ok = (manifest.get("user_agent", "").find(REPO_URL) >= 0
              and {k: v for k, v in counts.items() if v} == {k: v for k, v in expected.items() if v})
        check("C5.manifest", ok, f"user_agent={manifest.get('user_agent')!r}, counts={counts}, expected={expected}")
    except Exception as exc:  # noqa: BLE001
        check("C5.manifest", False, f"cannot read data/corpus/manifest.json: {exc}")

    corpus_readme = read("data/corpus/README.md")
    check("C6.attribution", "não está coberto pela licença" in corpus_readme and "site.getnet.com.br" in corpus_readme
          and "getnet.net" in corpus_readme, "data/corpus/README.md missing attribution/licence notice")
    readme = read("README.md")
    check("C6.readme_sources", "data/corpus" in readme and "robots.txt" in readme, "README does not document the corpus and robots.txt policy")


def mock_checks() -> None:
    sys.path.insert(0, str(ROOT))
    try:
        import httpx

        from src.rag import ingest
    except Exception as exc:  # noqa: BLE001
        check("M0.imports", False, f"{type(exc).__name__}: {exc}")
        return

    ua = getattr(ingest, "USER_AGENT", "")
    check("M1.user_agent", REPO_URL in ua and "ingest" in ua, f"USER_AGENT={ua!r}")
    check("M1.allowed_domains", set(getattr(ingest, "ALLOWED_DOMAINS", set())) == ALLOWED_HOSTS,
          f"ALLOWED_DOMAINS={getattr(ingest, 'ALLOWED_DOMAINS', None)}")

    page = (f"<html><head><title>Página Teste</title><script>SCRIPT-Y</script><style>STYLE-Z</style></head><body>"
            f"<nav>MENU-NAV</nav><header>HEADER-H</header><main><h1>Título</h1><p>{LONG}</p></main>"
            f"<footer>FOOTER-X</footer></body></html>")

    def make(routes: dict, log: list):
        def handler(request: "httpx.Request") -> "httpx.Response":
            log.append((request.method, str(request.url), request.headers.get("user-agent")))
            key = str(request.url)
            if key in routes:
                status, body, headers = routes[key]
                return httpx.Response(status, text=body, headers=headers or {})
            return httpx.Response(404, text="not found")
        return httpx.Client(transport=httpx.MockTransport(handler), follow_redirects=True)

    def fetch(routes: dict, url: str, market: str = "BR", min_delay: float = 0.0):
        log: list = []
        ing = ingest.Ingestor(client=make(routes, log), min_delay_s=min_delay)
        return ing.fetch(url, market), log, ing

    base = "https://site.getnet.com.br"
    try:
        rec, log, _ = fetch({f"{base}/robots.txt": (200, "User-agent: *\nDisallow: /", None),
                             f"{base}/blog/x": (200, page, None)}, f"{base}/blog/x")
        check("M2.robots_disallow", rec.get("status") == "robots_disallowed" and not any(u.endswith("/blog/x") for _, u, _ in log),
              f"status={rec.get('status')}, requests={[u for _, u, _ in log]}")

        rec, log, _ = fetch({f"{base}/blog/x": (200, page, None)}, f"{base}/blog/x")
        text = rec.get("text") or ""
        check("M3.robots_404_allows", rec.get("status") == "ok", f"status={rec.get('status')}")
        check("M3.ua_header", bool(log) and all(h == ua for _, _, h in log), f"user-agents sent={[h for _, _, h in log]}")
        check("M4.extraction", "Conteúdo principal" in text and not any(x in text for x in
              ("MENU-NAV", "FOOTER-X", "SCRIPT-Y", "STYLE-Z", "HEADER-H")) and rec.get("title") == "Página Teste",
              f"title={rec.get('title')!r}, text={text[:160]!r}")
        check("M4.record_fields", rec.get("sha256") == hashlib.sha256(text.encode("utf-8")).hexdigest()
              and rec.get("chars") == len(text) and rec.get("market") == "BR" and rec.get("http_status") == 200
              and rec.get("url") == f"{base}/blog/x", f"record={ {k: v for k, v in rec.items() if k != 'text'} }")

        rec, log, _ = fetch({f"{base}/robots.txt": (500, "err", None)}, f"{base}/blog/x")
        check("M5.robots_5xx_disallows", rec.get("status") == "robots_disallowed" and not any(u.endswith("/blog/x") for _, u, _ in log),
              f"status={rec.get('status')}")

        rec, _, _ = fetch({f"{base}/blog/x": (500, "boom", None)}, f"{base}/blog/x")
        check("M6.http_error", rec.get("status") == "http_error" and not rec.get("text"), f"status={rec.get('status')}")

        rec, _, _ = fetch({f"{base}/blog/x": (200, "<html><body><main>curto</main></body></html>", None)}, f"{base}/blog/x")
        check("M6.no_content", rec.get("status") == "no_content" and not rec.get("text"), f"status={rec.get('status')}")

        rec, _, _ = fetch({f"{base}/blog/x": (302, "", {"location": "https://evil.example.com/p"}),
                           "https://evil.example.com/p": (200, page, None)}, f"{base}/blog/x")
        check("M7.redirect_off_allowlist", rec.get("status") == "off_allowlist" and not rec.get("text"), f"status={rec.get('status')}")

        rec, log, _ = fetch({}, "https://other.example.com/page")
        check("M7.unknown_host_no_request", rec.get("status") == "off_allowlist" and log == [], f"status={rec.get('status')}, requests={log}")

        log = []
        ing = ingest.Ingestor(client=make({f"{base}/a": (200, page, None), f"{base}/b": (200, page, None)}, log), min_delay_s=0.3)
        t0 = time.perf_counter()
        ing.fetch(f"{base}/a", "BR")
        ing.fetch(f"{base}/b", "BR")
        elapsed = time.perf_counter() - t0
        robots_calls = sum(1 for _, u, _ in log if u.endswith("/robots.txt"))
        check("M8.robots_cached", robots_calls == 1, f"robots.txt requested {robots_calls} times")
        check("M8.rate_limit", elapsed >= 0.28, f"two requests to the same host took {elapsed:.3f}s with min_delay_s=0.3")

        tmp = Path(tempfile.mkdtemp(prefix="verify_p3a_"))
        (tmp / "sources.yaml").write_text(
            "sources:\n"
            f"  - url: {base}/a\n    market: BR\n"
            f"  - url: {base}/blocked\n    market: BR\n"
            "  - url: https://www.getnet.net/en/x\n    market: global\n", encoding="utf-8")
        log = []
        routes = {f"{base}/robots.txt": (200, "User-agent: *\nDisallow: /blocked", None), f"{base}/a": (200, page, None),
                  "https://www.getnet.net/en/x": (200, page, None)}
        ing = ingest.Ingestor(client=make(routes, log), min_delay_s=0.0)
        summary = ing.run(tmp / "sources.yaml", tmp / "out")
        recs = [json.loads(ln) for ln in (tmp / "out" / "pages.jsonl").read_text(encoding="utf-8").splitlines() if ln.strip()]
        manifest = json.loads((tmp / "out" / "manifest.json").read_text(encoding="utf-8"))
        ok = ([r["url"] for r in recs] == [f"{base}/a", f"{base}/blocked", "https://www.getnet.net/en/x"]
              and [r["status"] for r in recs] == ["ok", "robots_disallowed", "ok"]
              and manifest.get("counts", {}).get("ok") == 2 and manifest.get("counts", {}).get("robots_disallowed") == 1
              and isinstance(summary, dict))
        check("M9.run_writes_outputs", ok, f"statuses={[r.get('status') for r in recs]}, counts={manifest.get('counts')}")
    except Exception as exc:  # noqa: BLE001
        check("M2.runtime", False, f"{type(exc).__name__}: {exc}")


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks() -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    env0 = {k: v for k, v in os.environ.items() if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1")
    for script, allowed in PRIOR.items():
        r = run([sys.executable, f"scripts/{script}"], env=nested)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    corpus_checks()
    mock_checks()
    suite_checks()
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
