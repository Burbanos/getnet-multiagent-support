def section(text: str, start: str, stop: str) -> str:
    i = text.find(start)
    if i < 0:
        return ""
    j = text.find(stop, i + len(start))
    return text[i:j] if j > i else text[i:]


def log_calls(rel: str) -> list[tuple[int, str, str]]:
    """(line, method, source) of every logger.<level>(...) call in a file."""
    src = read(rel)
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return [(0, "parse_error", rel)]
    out = []
    for node in ast.walk(tree):
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and isinstance(node.func.value, ast.Name)
                and node.func.value.id == "logger"):
            out.append((node.lineno, node.func.attr, ast.get_source_segment(src, node) or ""))
    return out


