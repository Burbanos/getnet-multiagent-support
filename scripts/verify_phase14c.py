"""Phase 14C acceptance checks (docs/SPEC.md, Phase 14C: README and comparison report with the corrected judge).

Usage (from the repository root):  python scripts/verify_phase14c.py
Requires the dev environment. Never calls a real LLM or the network.
Do NOT edit this file to make checks pass: the reviewer runs its own copy.

Superseded checks: verify_phase14b.py N1 (README column 14 against the report) and N6 (judge model gemini-3.1-flash-lite in
v2-13..15) are superseded by J1-J4 below under the corrected judge. Its other checks concern files that 14C may not change
(A3), except README.md, pinned again here (A1); the suite, lint and offline-eval checks are re-run.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path.cwd()
sys.path.insert(0, str(ROOT))
RESULTS: list[tuple[str, bool]] = []
BASE = "bc9b2be"  # re-judge commit
README_BASE = "9a2e19c"  # README of 14B
ROUND = "d95d55f"  # first judgments
PROMPT = "docs/phase-prompts/14C.md"
REVIEWER = {"docs/SPEC.md", PROMPT, "scripts/verify_phase14c.py"}
PINNED = {
    "docs/SPEC.md": "163b3c6871d20620c0471001591e4b34ebfaabaaf4fba59221600647d26f8396",
    PROMPT: "5f98ff51eed307c6515ecfd5ea135f06c3edda3582a9db03217572fc9fb7c522",
    "README.md": "b9b8660ec9ae60a8fa746e6838be2e1687b84731b0da4f6830a3c9c56d6a5538",
}
RETIRED = {"docs/phase-prompts/14B.md", "scripts/verify_phase14b.py"}
ALLOWED = {"README.md", "docs/STATUS.md", "reports/eval_v2_phase14.md", "reports/eval_v2_phase14.json"}
RUNS = ["v2-13", "v2-14", "v2-15"]
JUDGE = "gemini-3.6-flash"
OLD_JUDGE_DIR = "reports/eval_runs/judge_gemini-3.1-flash-lite"
JUDGE_ROWS = ("Juiz: precisão da abstenção", "Juiz: cobertura da abstenção")
COMPARE = ["compare", "--name", "v2_phase14", "--group", "11G=v2-1,v2-2,v2-3", "--group", "12E=v2-7,v2-8,v2-9",
           "--group", "13D=v2-10,v2-11,v2-12", "--group", "14=v2-13,v2-14,v2-15", "--cases", "data/eval/cases_v2.jsonl"]
MIN_TESTS = 516

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, bool(ok)))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n") if p.exists() else ""


def sha(rel: str) -> str:
    return hashlib.sha256(read(rel).encode("utf-8")).hexdigest()


def run(cmd: list[str], env: dict | None = None, timeout: int = 1200) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True, encoding="utf-8", errors="replace",
                          timeout=timeout)


def at(rev: str, rel: str) -> bytes:
    r = subprocess.run(["git", "show", f"{rev}:{rel}"], cwd=ROOT, capture_output=True)
    return r.stdout.replace(b"\r\n", b"\n") if r.returncode == 0 else b""


def guarded(cid: str, fn) -> None:
    try:
        fn()
    except Exception as exc:
        check(cid, False, f"probe raised {type(exc).__name__}: {str(exc)[:300]}")


def table_rows(md: str) -> dict[str, list[str]]:
    rows: dict[str, list[str]] = {}
    for ln in md.splitlines():
        if ln.startswith("| ") and not ln.startswith("| :"):
            cells = [c.strip() for c in ln.strip().strip("|").split("|")]
            rows.setdefault(cells[0], cells)
    return rows


def static_checks() -> None:
    r = run([sys.executable, "-m", "ruff", "check", "--isolated", "--target-version", "py311", "--select", "E9",
             "--output-format", "concise", "scripts", "src", "tests"])
    check("A0.py311_syntax", r.returncode == 0, (r.stdout + r.stderr).strip()[-400:])
    bad = [p for p, h in PINNED.items() if sha(p) != h]
    check("A1.reviewer_files_and_readme", not bad, f"differ from the reviewer's copy: {bad}")
    verifiers = sorted(p.name for p in (ROOT / "scripts").glob("verify_*.py"))
    prompts = sorted(p.name for p in (ROOT / "docs" / "phase-prompts").glob("*.md"))
    check("A2.retired_process_files", verifiers == ["verify_phase14c.py"] and prompts == ["14C.md"],
          f"only verify_phase14c.py and 14C.md may remain: {verifiers} {prompts}")
    diff = run(["git", "diff", "--name-only", "--no-renames", BASE])
    untracked = run(["git", "ls-files", "--others", "--exclude-standard"]).stdout.split()
    extra = sorted(p for p in set(diff.stdout.split()) | set(untracked) if p not in REVIEWER | RETIRED | ALLOWED)
    check("A3.scope", diff.returncode == 0 and not extra, f"14C may not change: {extra}")
    st = read("docs/STATUS.md")
    check("S1.status", 0 < len(st.split("\n")) <= 150 and "14C" in st and "Perguntas" in st,
          f"docs/STATUS.md must be rewritten for 14C in at most 150 lines (has {len(st.splitlines())})")


def judge_records() -> None:
    bad, counts = [], {}
    for rid in RUNS:
        rows = [json.loads(ln) for ln in read(f"reports/eval_runs/{rid}.judge.jsonl").splitlines() if ln.strip()]
        counts[rid] = len(rows)
        if len(rows) != 72 or any(r.get("judge_model") != JUDGE or r.get("status") != "ok" for r in rows) \
                or len({r["id"] for r in rows}) != 72:
            bad.append(rid)
    check("J1.judge_model_in_every_judgment", not bad, f"runs with judgments not all ok/{JUDGE} or not 72: {bad} {counts}",
          info=f"{counts}, all {JUDGE}")
    kept = [rid for rid in RUNS if (ROOT / OLD_JUDGE_DIR / f"{rid}.judge.jsonl").read_bytes().replace(b"\r\n", b"\n")
            == at(ROUND, f"reports/eval_runs/{rid}.judge.jsonl") and at(ROUND, f"reports/eval_runs/{rid}.judge.jsonl")]
    check("J2.first_judgments_preserved", kept == RUNS,
          f"files in {OLD_JUDGE_DIR} must equal the judgments of {ROUND}: ok for {kept}")


def report_regenerated() -> None:
    out = tempfile.mkdtemp(prefix="verify_p14c_")
    r = run([sys.executable, "-m", "src.eval", *COMPARE, "--out-dir", out])
    md_ok = r.returncode == 0 and Path(out, "eval_v2_phase14.md").read_text(encoding="utf-8").replace("\r\n", "\n") \
        == read("reports/eval_v2_phase14.md")
    try:
        a = json.loads(Path(out, "eval_v2_phase14.json").read_text(encoding="utf-8"))
        b = json.loads(read("reports/eval_v2_phase14.json"))
        a.pop("generated_at", None)
        b.pop("generated_at", None)
        json_ok = a == b
    except Exception:
        json_ok = False
    old = table_rows(at(BASE, "reports/eval_v2_phase14.md").decode("utf-8"))
    new = table_rows(read("reports/eval_v2_phase14.md"))
    changed = sorted(k for k in set(old) | set(new) if old.get(k) != new.get(k))
    check("J3.report_regenerated_from_records", md_ok and json_ok
          and set(changed) <= {"Juiz: fundamentação (1 a 5)", "Juiz: responde à pergunta (1 a 5)"},
          f"md_matches_compare={md_ok} json_matches_compare={json_ok} rows changed={changed}")


def readme_checks() -> None:
    rd, base = read("README.md"), at(README_BASE, "README.md").decode("utf-8")
    rep = table_rows(read("reports/eval_v2_phase14.md"))
    mine = table_rows(rd)
    def same(m: str, r: str) -> bool:  # the README omits the (min–max) range when min == max, as elsewhere
        lo_hi = re.search(r"\((.+)–(.+)\)", r)
        return m == r or (bool(lo_hi) and lo_hi.group(1) == lo_hi.group(2) and m == r.split(" (")[0])

    bad = [(k, mine.get(k, [""] * 5)[4:5], rep.get(k, [""] * 5)[4:5]) for k in JUDGE_ROWS
           if len(mine.get(k, [])) < 5 or not same(mine[k][4], rep.get(k, [""] * 5)[4])]
    check("J4.readme_judge_rows_match_report", not bad, f"{bad}")
    old_t, new_t = table_rows(base), table_rows(rd)
    other = sorted(k for k in set(old_t) | set(new_t) if k not in JUDGE_ROWS and old_t.get(k) != new_t.get(k))
    check("J5.no_other_table_row_changed", not other, f"table rows changed besides the judge rows: {other}")
    gone = [s for s in ("outro juiz", "não se comparam") if s in rd]
    mentions = len(re.findall(r"(?<!judge_)gemini-3\.1-flash-lite", rd))
    check("J6.caveat_removed_and_recorded", not gone and mentions == 1 and OLD_JUDGE_DIR in rd,
          f"leftover caveats={gone} mentions of the first judge={mentions} (want 1, in the sentence that points to "
          f"{OLD_JUDGE_DIR})")


def suite_checks() -> None:
    env0 = {k: v for k, v in os.environ.items()
            if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY", "API_KEYS", "APP_ENV", "CHECKPOINT_DB_PATH", "DATABASE_URL",
                         "REDIS_URL", "LLM_MODEL", "LLM_FALLBACK_MODEL", "EVAL_JUDGE_MODEL", "EVAL_SLEEP_S", "LLM_PROVIDER",
                         "TEST_DATABASE_URL", "TEST_REDIS_URL", "TRACING_EXPORTER")}
    env0["GEMINI_API_KEY"] = ""
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    before = run(["git", "status", "--porcelain"]).stdout
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"], env=env0)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    m = re.search(r"(\d+) passed", last)
    check("Q2.pytest_offline_no_key", t.returncode == 0 and "failed" not in last and bool(m) and int(m.group(1)) >= MIN_TESTS,
          f"{last} (want at least {MIN_TESTS})", info=last)
    o = run([sys.executable, "-m", "src.eval", "offline"], env=env0)
    check("Q5.offline_eval", o.returncode == 0 and "offline: 6/6 passed" in o.stdout, (o.stdout + o.stderr)[-300:])
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    print(f"INFO python {sys.version.split()[0]}")
    static_checks()
    guarded("J1.judge_model_in_every_judgment", judge_records)
    guarded("J3.report_regenerated_from_records", report_regenerated)
    guarded("J4.readme_judge_rows_match_report", readme_checks)
    suite_checks()
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
