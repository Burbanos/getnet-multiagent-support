def trace_checks() -> None:
    from opentelemetry.sdk.trace.export.in_memory_span_exporter import InMemorySpanExporter
    from starlette.testclient import TestClient

    import src.main as app_main
    from src.core import tracing
    from src.core.graph import OrchestrationGraph

    exporter = InMemorySpanExporter()
    tracing.configure_tracing(exporter, simple=True)
    orch = OrchestrationGraph(chat_model=scripted([text_msg("Resposta de teste do supervisor.")]),
                              planner_model=scripted([plan_msg("pt", "support", "none", [])]))
    old_get = app_main.get_orchestrator
