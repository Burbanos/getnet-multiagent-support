def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n") if p.exists() else ""


def sha(rel: str) -> str:
    return hashlib.sha256(read(rel).encode("utf-8")).hexdigest()


def run(cmd: list[str], env: dict | None = None, timeout: int = 1200) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True, encoding="utf-8", errors="replace",
                          timeout=timeout)


def base_file(rel: str) -> str:
    r = run(["git", "show", f"{BASE}:{rel}"])
    return r.stdout.replace("\r\n", "\n") if r.returncode == 0 else ""


def guarded(cid: str, fn) -> None:
    try:
        fn()
    except Exception as exc:  # a crash in a probe is a failed check, never a crashed verifier
        check(cid, False, f"probe raised {type(exc).__name__}: {str(exc)[:300]}")


