def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    tmp = tempfile.mkdtemp(prefix="verify_p13c_")
    os.environ.update(APP_ENV="testing", GEMINI_API_KEY="", API_KEYS="", DATABASE_URL="", REDIS_URL="",
                      TRACING_EXPORTER="none", REPLICA_NAME="", TICKETS_DB_PATH=str(Path(tmp) / "app" / "tickets.db"),
                      CHECKPOINT_DB_PATH=str(Path(tmp) / "app" / "checkpoints.db"), ENABLE_GUARDRAILS="true",
                      ANSWER_CHECK_ENABLED="true", PLANNER_ENABLED="true", VERIFIER_ENABLED="true",
                      LANGUAGE_ENFORCEMENT_ENABLED="true")
    from src.config import JsonFormatter
    lines: list[str] = []

    class Capture(logging.Handler):
        def emit(self, record):
            with suppress(Exception):
                lines.append(JsonFormatter().format(record))

    lg = logging.getLogger("multiagent")
    lg.addHandler(Capture())
    for h in list(lg.handlers):
        if not isinstance(h, Capture):
            lg.removeHandler(h)
    static_checks()
    component_checks(tmp)
    graph_checks(lines)
    guarded("E1.audit_and_replacements_endpoints", endpoint_checks)
    guarded("R1.production_fail_fast", lambda: prod_checks(tmp))
    guarded("R2.trace_and_span_privacy", trace_checks)
    guarded("R3.no_raw_pii_in_checkpoints", lambda: pii_invariant(tmp))
    for k in ("APP_ENV", "GEMINI_API_KEY", "API_KEYS", "DATABASE_URL", "REDIS_URL", "TRACING_EXPORTER", "REPLICA_NAME",
              "TICKETS_DB_PATH", "CHECKPOINT_DB_PATH", "ENABLE_GUARDRAILS", "ANSWER_CHECK_ENABLED", "PLANNER_ENABLED",
              "VERIFIER_ENABLED", "LANGUAGE_ENFORCEMENT_ENABLED"):
        os.environ.pop(k, None)
    suite_checks()
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
