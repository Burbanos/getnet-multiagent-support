def check(cid: str, ok: bool, detail: str = "", info: str = "") -> None:
    RESULTS.append((cid, ok))
    extra = info if ok else detail
    print(f"{'PASS' if ok else 'FAIL'} {cid}" + (f" :: {extra}" if extra else ""), flush=True)


def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def norm(line: str) -> str:
    return " ".join(line.split()).lower()


class KeywordEmbedder:
    """Deterministic fake: one dimension per keyword (counts), plus a constant bias dimension."""

    def __init__(self, keywords: list[str]):
        self.keywords = keywords

    def _vec(self, text: str) -> list[float]:
        t = text.lower()
        return [float(t.count(k)) for k in self.keywords] + [0.01]

    def embed_documents(self, texts: list[str]) -> list[list[float]]:
        return [self._vec(t) for t in texts]

    def embed_query(self, text: str) -> list[float]:
        return self._vec(text)


def committed_index_checks() -> None:
    try:
        import numpy as np
    except ImportError:
        check("I0.numpy", False, "numpy not installed")
        return
    pages = [json.loads(ln) for ln in read("data/corpus/pages.jsonl").splitlines() if ln.strip()]
    ok_pages = {p["url"]: p for p in pages if p.get("status") == "ok"}
    meta_raw = read("data/index/index_meta.json")
    chunks_raw = [ln for ln in read("data/index/chunks.jsonl").splitlines() if ln.strip()]
    emb_path = ROOT / "data/index/embeddings.npy"
    if not (meta_raw and chunks_raw and emb_path.exists()):
        check("I1.index_files", False, "data/index/{index_meta.json,chunks.jsonl,embeddings.npy} missing")
        return
    check("I1.index_files", True)
    meta = json.loads(meta_raw)
    chunks = [json.loads(ln) for ln in chunks_raw]
    emb = np.load(emb_path)
    corpus_sha = hashlib.sha256("".join(p["sha256"] for p in pages if p.get("status") == "ok").encode()).hexdigest()
    check("I2.meta", meta.get("embedding_model") == "gemini-embedding-2" and meta.get("dim") == 768
          and meta.get("n_chunks") == len(chunks) and meta.get("corpus_sha256") == corpus_sha,
          f"meta={ {k: meta.get(k) for k in ('embedding_model', 'dim', 'n_chunks', 'corpus_sha256')} }, expected corpus_sha256={corpus_sha}")
    norms = np.linalg.norm(emb, axis=1) if emb.ndim == 2 else np.array([0.0])
    check("I3.embeddings_shape", emb.shape == (len(chunks), 768) and emb.dtype == np.float32
          and bool(np.all(np.abs(norms - 1.0) < 1e-3)), f"shape={emb.shape}, dtype={emb.dtype}, norm range=({norms.min():.4f}, {norms.max():.4f})")

    ids = [c.get("chunk_id") for c in chunks]
    check("I4.chunk_fields", all(CHUNK_FIELDS <= set(c) for c in chunks) and len(set(ids)) == len(ids),
          f"missing fields or duplicate chunk_id (unique={len(set(ids))}/{len(ids)})")
    bad_src, not_verbatim, too_long = [], [], []
    for c in chunks:
        page = ok_pages.get(c.get("doc_url"))
        if not page or c.get("doc_sha256") != page.get("sha256") or c.get("fetched_at") != page.get("fetched_at"):
            bad_src.append(c.get("chunk_id"))
            continue
        page_lines = set(page["text"].split("\n"))
        if any(ln not in page_lines for ln in c["text"].split("\n")):
            not_verbatim.append(c.get("chunk_id"))
        if not c["text"].strip() or len(c["text"]) > 1200:
            too_long.append(c.get("chunk_id"))
    check("I5.chunk_provenance", not bad_src, f"chunks with wrong doc_url/sha256/fetched_at: {bad_src[:3]}")
    check("I5.chunk_verbatim", not not_verbatim, f"chunks with lines not present in the source page: {not_verbatim[:3]}")
    check("I5.chunk_size", not too_long, f"empty or >1200-char chunks: {too_long[:3]}")

    freq = Counter()
    for p in ok_pages.values():
        freq.update({norm(ln) for ln in p["text"].split("\n") if norm(ln)})
    boiler = {ln for ln, n in freq.items() if n >= 4}
    leaked = [c["chunk_id"] for c in chunks if any(norm(ln) in boiler for ln in c["text"].split("\n"))]
    check("I6.no_boilerplate", not leaked, f"{len(leaked)} chunks contain lines repeated in >=4 pages (e.g. {leaked[:2]})")
    covered = {c["doc_url"] for c in chunks}
    check("I6.page_coverage", len(covered) >= len(ok_pages) - 3, f"{len(covered)} of {len(ok_pages)} ok pages have chunks")

    if emb.ndim == 2 and len(chunks) > 5:
        sims = emb @ emb.T
        same = np.array([[a["doc_url"] == b["doc_url"] for b in chunks] for a in chunks])
        np.fill_diagonal(same, False)
        diff = ~same
        np.fill_diagonal(diff, False)
        intra = float(sims[same].mean()) if same.any() else 1.0
        inter = float(sims[diff].mean())
        check("I7.embeddings_are_semantic", intra > inter + 0.03,
              f"mean cosine within page {intra:.3f} vs across pages {inter:.3f} (real embeddings should differ)", info=f"intra={intra:.3f} inter={inter:.3f}")


def library_checks() -> None:
    sys.path.insert(0, str(ROOT))
    os.environ["GEMINI_API_KEY"] = ""
    try:
        import numpy as np

        import src.core.llm as llm_mod
        from src.config import settings
        from src.rag import chunking, index, retriever
    except Exception as exc:  # noqa: BLE001
        check("L0.imports", False, f"{type(exc).__name__}: {exc}")
        return

    have = {k: getattr(settings, k, None) for k in EXPECTED_SETTINGS}
    check("L1.settings", have == EXPECTED_SETTINGS, f"settings={have}")
    try:
        settings.GEMINI_API_KEY = "dummy-key-for-construction-only"
        q = llm_mod.get_embedder("RETRIEVAL_QUERY")
        d = llm_mod.get_embedder("RETRIEVAL_DOCUMENT")
        check("L2.get_embedder", getattr(q, "task_type", None) == "RETRIEVAL_QUERY" and getattr(d, "task_type", None) == "RETRIEVAL_DOCUMENT"
              and "gemini-embedding-2" in str(getattr(q, "model", "")) and getattr(q, "output_dimensionality", None) == 768,
              f"query embedder: model={getattr(q, 'model', None)}, task={getattr(q, 'task_type', None)}, dim={getattr(q, 'output_dimensionality', None)}")
        settings.GEMINI_API_KEY = ""
        try:
            llm_mod.get_embedder("RETRIEVAL_QUERY")
            check("L2.get_embedder_requires_key", False, "no error without GEMINI_API_KEY")
        except llm_mod.LLMNotConfiguredError:
            check("L2.get_embedder_requires_key", True)
    except Exception as exc:  # noqa: BLE001
        check("L2.runtime", False, f"{type(exc).__name__}: {exc}")
    finally:
        settings.GEMINI_API_KEY = ""

    footer = ["Fale já", "Ligue 4002-4000", "Já é cliente?", "Baixe o app"]
    def page(i: int, body: list[str], status: str = "ok") -> dict:
        text = "\n".join(body + footer)
        return {"url": f"https://site.getnet.com.br/p{i}", "title": f"P{i}", "market": "BR", "status": status,
                "fetched_at": "2026-11-06T00:00:00+00:00", "text": text, "chars": len(text),
                "sha256": hashlib.sha256(text.encode()).hexdigest()}
    long_lines = [f"O crediário permite parcelar em até 48x, linha {n}, com taxa única e recebimento em 2 dias." for n in range(30)]
    records = [
        page(0, ["Crediário Getnet"] + long_lines),
        page(1, ["Pix na maquininha", "Venda com Pix por QR Code na maquininha Getnet.", "—", "Receba na hora."]),
        page(2, ["Wi-Fi", "Para configurar o Wi-Fi da maquininha acesse Configurações e escolha a rede."]),
        page(3, ["Antecipação", "Antecipe suas vendas pelo app Getnet Brasil."]),
        page(4, ["Não ok"], status="no_content"),
    ]
    try:
        chunks = chunking.build_chunks(records, max_chars=900, boilerplate_min_pages=4)
        chunks2 = chunking.build_chunks(records, max_chars=900, boilerplate_min_pages=4)
        all_text = "\n".join(c["text"] for c in chunks)
        check("L3.boilerplate_removed", not any(f in all_text for f in footer), "footer lines present in 4 pages leaked into chunks")
        check("L3.dash_lines_removed", "\n—\n" not in f"\n{all_text}\n", "lines with only dashes/punctuation must be dropped")
        check("L3.non_ok_ignored", not any(c["doc_url"].endswith("/p4") for c in chunks), "non-ok record produced chunks")
        check("L3.max_chars", all(len(c["text"]) <= 900 for c in chunks) and sum(c["doc_url"].endswith("/p0") for c in chunks) >= 3,
              f"sizes={[len(c['text']) for c in chunks]}")
        src = {r["url"]: set(r["text"].split("\n")) for r in records}
        check("L3.verbatim_lines", all(ln in src[c["doc_url"]] for c in chunks for ln in c["text"].split("\n")),
              "chunk lines must be verbatim lines of the source page")
        check("L3.deterministic_ids", [c["chunk_id"] for c in chunks] == [c["chunk_id"] for c in chunks2]
              and len({c["chunk_id"] for c in chunks}) == len(chunks), "chunk ids not deterministic or not unique")
        check("L3.fields", all(CHUNK_FIELDS <= set(c) for c in chunks)
              and all(c["doc_sha256"] == next(r["sha256"] for r in records if r["url"] == c["doc_url"]) for c in chunks),
              "missing fields or wrong doc_sha256")

        emb = KeywordEmbedder(["crediário", "pix", "wi-fi", "antecip"])
        tmp = Path(tempfile.mkdtemp(prefix="verify_p3b_"))
        index.build_index(chunks, emb, tmp, embedding_model="fake-kw", dim=5)
        meta = json.loads((tmp / "index_meta.json").read_text(encoding="utf-8"))
        arr = np.load(tmp / "embeddings.npy")
        check("L4.build_index", meta.get("embedding_model") == "fake-kw" and meta.get("dim") == 5 and meta.get("n_chunks") == len(chunks)
              and arr.shape == (len(chunks), 5) and arr.dtype == np.float32 and bool(np.all(np.abs(np.linalg.norm(arr, axis=1) - 1) < 1e-4)),
              f"meta={meta}, shape={arr.shape}, dtype={arr.dtype}")
        vi = index.VectorIndex.load(tmp, expected_model="fake-kw", expected_dim=5)
        try:
            index.VectorIndex.load(tmp, expected_model="gemini-embedding-2", expected_dim=768)
            check("L4.load_rejects_mismatch", False, "no error for a model/dim mismatch")
        except ValueError:
            check("L4.load_rejects_mismatch", True)
        hits = vi.search(emb.embed_query("wi-fi"), k=2)
        check("L4.search_sorted", bool(hits) and hits[0][0]["doc_url"].endswith("/p2") and all(hits[i][1] >= hits[i + 1][1] for i in range(len(hits) - 1)),
              f"hits={[(h[0]['doc_url'][-3:], round(h[1], 3)) for h in hits]}")

        r = retriever.Retriever(vi, emb, min_score=0.6, top_k=2)
        res = r.search("Como configuro o Wi-Fi?")
        docs = res.get("documents", [])
        check("L5.retriever_success", res.get("status") == "success" and docs and docs[0]["url"].endswith("/p2")
              and all(set(d) >= {"url", "title", "fetched_at", "chunk_id", "score", "text"} for d in docs)
              and all(d["score"] >= 0.6 for d in docs) and len(docs) <= 2, f"result={str(res)[:300]}")
        res = r.search("receita de bolo de chocolate")
        check("L5.retriever_abstain", res.get("status") == "abstain" and res.get("documents") == [], f"result={str(res)[:200]}")
        res = retriever.Retriever(vi, emb, min_score=0.0, top_k=1).search("crediário")
        check("L5.top_k", len(res.get("documents", [])) == 1, f"top_k=1 returned {len(res.get('documents', []))}")
    except Exception as exc:  # noqa: BLE001
        check("L3.runtime", False, f"{type(exc).__name__}: {exc}")


NO_NETWORK_PLUGIN = textwrap.dedent('''
    import socket
    _orig = socket.socket.connect
    def _guard(self, address, *a, **k):
        host = address[0] if isinstance(address, tuple) else str(address)
        if host not in ("127.0.0.1", "::1", "localhost"):
            raise RuntimeError(f"network access blocked during tests: {address}")
        return _orig(self, address, *a, **k)
    socket.socket.connect = _guard
''')


def suite_checks() -> None:
    if os.environ.get("VERIFY_NESTED") == "1":  # called by a later verifier: skip suite and recursion
        return
    env0 = {k: v for k, v in os.environ.items() if k not in ("TICKETS_DB_PATH", "GEMINI_API_KEY")}
    env0["GEMINI_API_KEY"] = ""
    nested = dict(env0, VERIFY_NESTED="1")
    for script, allowed in PRIOR.items():
        r = run([sys.executable, f"scripts/{script}"], env=nested)
        fails = {ln.split()[1] for ln in r.stdout.splitlines() if ln.startswith("FAIL")}
        unexpected = sorted(fails - allowed)
        check(f"Q0.{script[:-3]}", "SUMMARY" in r.stdout and not unexpected,
              f"unexpected failures: {unexpected}" if unexpected else r.stdout[-300:])
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    check("Q1.ruff_clean", ruff.returncode == 0, (ruff.stdout + ruff.stderr).strip()[-300:])
    before = run(["git", "status", "--porcelain"]).stdout
    plugdir = tempfile.mkdtemp(prefix="verify_nonet_")
    Path(plugdir, "verify_nonet.py").write_text(NO_NETWORK_PLUGIN, encoding="utf-8")
    env = dict(env0, PYTHONPATH=plugdir + os.pathsep + os.environ.get("PYTHONPATH", ""))
    t = run([sys.executable, "-m", "pytest", "-q", "-p", "verify_nonet", "-p", "no:cacheprovider"], env=env)
    lines = [ln for ln in t.stdout.splitlines() if re.search(r"\d+ (passed|failed|error)", ln)]
    last = lines[-1] if lines else t.stdout[-300:]
    check("Q2.pytest_offline_no_key", t.returncode == 0, last, info=last)
    check("Q3.tree_unchanged", before == run(["git", "status", "--porcelain"]).stdout, "tests changed the working tree")


def main() -> int:
    if not (ROOT / "src").exists():
        print("Run from the repository root.")
        return 2
    library_checks()
    committed_index_checks()
    suite_checks()
    failed = [c for c, ok in RESULTS if not ok]
    print(f"\nSUMMARY: {len(RESULTS) - len(failed)}/{len(RESULTS)} passed" + (f"; failed: {', '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
