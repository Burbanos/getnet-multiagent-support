def read(rel: str) -> str:
    p = ROOT / rel
    return p.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n") if p.exists() else ""


def run(cmd: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=1200)


def section(text: str, start: str, stop: str) -> str:
    i = text.find(start)
    if i < 0:
        return ""
    j = text.find(stop, i + len(start))
    return text[i:j] if j > i else text[i:]


def jl(rel: str) -> list[dict]:
    return [json.loads(ln) for ln in read(rel).splitlines() if ln.strip()]


def br(x: float, nd: int) -> str:
    return f"{x:.{nd}f}".replace(".", ",")


def expected_readme() -> str:
    """The README block of docs/phase-prompts/11G.md, written the way the prompt's script writes it."""
    prompt = read("docs/phase-prompts/11G.md")
    marker = "## README novo\n\n````markdown\n"
    i = prompt.find(marker)
    j = prompt.find("\n````\n", i + len(marker)) if i >= 0 else -1
    return prompt[i + len(marker):j] + "\n" if 0 <= i < j else ""


def static_checks() -> None:  # noqa: C901 - one claim per block, kept linear on purpose
    print(f"INFO python {sys.version.split()[0]}")
    r = run([sys.executable, "-m", "ruff", "check", "--isolated", "--target-version", "py311", "--select", "E9",
             "--output-format", "concise", "scripts", "src", "tests"])
    check("G0.py311_syntax", r.returncode == 0, (r.stdout + r.stderr).strip()[-400:])
    readme, exp = read("README.md"), expected_readme()
    lines = readme.split("\n")
    # G1: the README is the block given in the prompt, byte for byte (LF)
    check("G1.readme_from_prompt", bool(exp) and readme == exp,
          "README.md must be exactly the block of docs/phase-prompts/11G.md (run the prompt's script; do not edit by hand)"
          + next((f"; first difference at line {k + 1}: {a[:80]!r}" for k, (a, b) in enumerate(zip(lines, exp.split("\n"))) if a != b), ""),
          info=f"{len(lines) - 1} lines")

    # G2: structure, titles and banned wording
    heads = [ln[3:] for ln in lines if ln.startswith("## ")]
    titles = [ln for ln in lines if ln.startswith("#")]
    probs = []
    if heads != SECTIONS:
        probs.append(f"sections {heads}")
    if len(lines) - 1 > 350:
        probs.append(f"{len(lines) - 1} lines (max 350)")
    probs += [f"title {t!r}" for t in titles if "Fase" in t or re.search(r"\b\d+[A-I]\b", t) or MARKETING.search(t)]
    probs += [f"old claim {w!r}" for w in OLD_CLAIMS if w in readme]
    probs += [f"word {m.group(0)!r}" for m in re.finditer(r"\bcandidat(?:o|a|os)\b|\bv[íi]deo\b|\bFase \d", readme, re.IGNORECASE)]
    probs += [f"reviewer called independent: {m.group(0)[:60]!r}"
              for m in REVIEWER_NEAR.finditer(readme.replace("não é uma revisão independente", ""))]
    check("G2.structure", not probs, "; ".join(probs[:6]))

    # G3: claims table: every evidence path exists
    table = section(readme, "### Afirmações e evidências", "\n## ")
    rows = [ln for ln in table.splitlines() if ln.startswith("| ") and not ln.startswith("| Afirmação") and not ln.startswith("| :")]
    paths = sorted({p for row in rows for p in re.findall(r"`((?:src|tests|scripts|data|reports|docs|\.github)/[A-Za-z0-9_./*-]*|"
                                                           r"Dockerfile|docker-compose\.yml)`", row.split(" | ", 1)[-1])})
    missing = [p for p in paths if not (ROOT / p.rstrip("/")).exists()]
    no_ev = [row[:60] for row in rows if not re.search(r"`[^`]+`\s*\|$", row)]
    check("G3.claims_evidence", len(rows) >= 20 and paths and not missing and not no_ev,
          f"rows={len(rows)} missing paths={missing} rows without evidence={no_ev}", info=f"{len(rows)} rows, {len(paths)} paths")

    # G6: tier and models stated, matching reports/run_context.json
    ctx = json.loads(read("reports/run_context.json") or "{}")
    runs = ctx.get("runs", ctx) if isinstance(ctx, dict) else {}
