def norm_sha(b: bytes) -> str:
    return hashlib.sha256(b.replace(b"\r\n", b"\n")).hexdigest()


def load_script() -> Any:
    spec = importlib.util.spec_from_file_location("capture_public_data_verify", ROOT / "scripts" / "capture_public_data.py")
    mod = importlib.util.module_from_spec(spec)
