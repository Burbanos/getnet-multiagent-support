def script_checks(tmp: str) -> None:
    try:
        import httpx
        mod = load_script()
    except Exception as exc:  # noqa: BLE001
        check("D1.script_api", False, f"{type(exc).__name__}: {exc}")
        return
    ok = (getattr(mod, "USER_AGENT", None) == UA and getattr(mod, "OLINDA", None) == OLINDA
          and Path(getattr(mod, "OUT_DIR", "")).as_posix() == "tests/fixtures/public_data"
          and mod.ptax_period_url("EUR", "11-06-2026", "11-06-2026") == STATIC_URLS["ptax_eur_20261106"]
          and mod.forecast_url(-30.03, -51.23) == forecast(-30.03, -51.23))
    check("D1.script_api", ok, "USER_AGENT, OLINDA, OUT_DIR, ptax_period_url and forecast_url must match the prompt exactly")

    seen: list[str] = []
    ua_seen: list[str] = []

    def handler(request: "httpx.Request") -> "httpx.Response":
        url = str(request.url)
        seen.append(url)
        ua_seen.append(request.headers.get("user-agent", ""))
        if "geocoding" in url and "Porto" in url:
            return httpx.Response(200, json={"results": [{"name": "Porto Alegre", "latitude": -30.0, "longitude": -51.25}]})
        if "latitude=999" in url:
            return httpx.Response(400, json={"error": True, "reason": "bad latitude"})
        return httpx.Response(200, content=b'{"value": []}\r\n', headers={"content-type": "application/json"})

    try:
        out = Path(tmp, "cap")
        out.mkdir(parents=True, exist_ok=True)
        client = httpx.Client(transport=httpx.MockTransport(handler), headers={"User-Agent": UA})
        man = mod.capture(client, out)
        disk = json.loads((out / "manifest.json").read_text(encoding="utf-8"))
        files = man.get("files", {})
        want_urls = dict(STATIC_URLS, forecast_porto_alegre=forecast(-30.0, -51.25))
        urls_ok = list(files) == NAMES or sorted(files) == sorted(NAMES)
        urls_ok = urls_ok and all(files[n]["url"] == want_urls[n] for n in NAMES)
        order_ok = len(seen) == 12 and "forecast" in seen[3] and "latitude=-30.0" in seen[3]
        meta_ok = (disk == man and set(man) == {"captured_at", "user_agent", "files"} and man["user_agent"] == UA
                   and all(set(files[n]) == {"url", "status_code", "content_type", "bytes", "sha256"} for n in NAMES)
                   and files["forecast_invalid"]["status_code"] == 400
                   and files["ptax_moedas"]["sha256"] == hashlib.sha256(b'{"value": []}\n').hexdigest()
                   and files["ptax_moedas"]["bytes"] == len(b'{"value": []}\r\n')
                   and (out / "ptax_moedas.json").read_bytes() == b'{"value": []}\r\n')
        check("D2.capture_offline", urls_ok and order_ok and meta_ok,
              f"urls_ok={urls_ok} order_ok={order_ok} (requests: {len(seen)}) meta_ok={meta_ok}")

        def boom(request: "httpx.Request") -> "httpx.Response":
            raise httpx.ConnectError("offline", request=request)
        out2 = Path(tmp, "cap2")
        out2.mkdir(parents=True, exist_ok=True)
        try:
            mod.capture(httpx.Client(transport=httpx.MockTransport(boom)), out2)
            raised = None
        except httpx.HTTPError as exc:
            raised = type(exc).__name__
        check("D2.capture_network_error", raised == "ConnectError" and not (out2 / "manifest.json").exists(),
              f"raised={raised} manifest_written={(out2 / 'manifest.json').exists()}")
    except Exception as exc:  # noqa: BLE001
        check("D2.capture_offline", False, f"{type(exc).__name__}: {exc}")


